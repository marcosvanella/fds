#!/usr/bin/env python3
"""Scratch-only hook: dump the FULL-BOX inputs and outputs of the pressure-area loops of FDS pres.f90 (FireX 36975d7), for the
bitwise check of the C++ translations in Source/pressure_backend/FdsPressureLoops.cpp against real FDS data.
Usage: fds_loops_dump_hook.py path/to/scratch/Source/pres.f90   (edits the given scratch copy in place; never apply it to the reference tree
or to the worktree). Write-only: every inserted call only reads FDS arrays and writes files; with FDS_LDUMP_STEPS unset every call returns
at its first statement.
Run time: FDS_LDUMP_STEPS=3,10 (ICYC values) or ALL, single OpenMP thread. Files (stream records of tests/fds_loops/ref_loops.f90.in) in the run directory:
  L1211_fds_n<ICYC>_<P|C>_m<NM>.bin   PRHS = divergence (pres.f90:250-260), inputs FVX FVY FVZ DDDT RDX RDY RDZ, PRHS before and after
  L1209_fds_n<ICYC>_<P|C>_m<NM>.bin   Poisson boundary arrays (pres.f90:65-228): the whole external wall list with every field the loop reads
  HBC_fds_n<ICYC>_<P|C>_m<NM>.bin     H ghost cells (pres.f90:450-492): H before and after, BXS..BZF, LBC MBC NBC, DXI DETA DZETA
  L1207_fds_n<ICYC>_<P|C>_m<NM>.bin   P = RHOP*(HP-KRES) (pres.f90:758-764): RHO H KRES (full box) and WORK7 after
Limits: the 3-D natural layout only (IPS 0/1/4/7, not cylindrical); a vent with synthetic eddies stops the run (the C++ test needs the eddy arrays).
"""
import sys

p = sys.argv[1]
s = open(p).read()


def rep(old, new, count=1):
    global s
    assert s.count(old) == count, (old, s.count(old))
    s = s.replace(old, new)


MODULE = r'''
MODULE LDUMP_MOD
! scratch-only dump of the pressure-area loops (see fds_loops_dump_hook.py); not part of FDS
USE PRECISION_PARAMETERS
USE MESH_POINTERS
USE GLOBAL_CONSTANTS
USE MATH_FUNCTIONS, ONLY: EVALUATE_RAMP
USE COMP_FUNCTIONS, ONLY: GET_FILE_NUMBER
IMPLICIT NONE
PRIVATE
PUBLIC LD_RHS_PRE,LD_RHS_POST,LD_HBC_PRE,LD_HBC_POST,LD_P_POST
INTEGER, PARAMETER :: LD_MAXSTEPS=64
INTEGER, SAVE :: LD_STEPS(LD_MAXSTEPS)=0,LD_N=0,LD_LU=0
LOGICAL, SAVE :: LD_INIT=.FALSE.,LD_ALL=.FALSE.
REAL(EB), ALLOCATABLE, SAVE, DIMENSION(:,:,:) :: S_PRHS,S_H
REAL(EB), ALLOCATABLE, SAVE, DIMENSION(:,:) :: S_BXS,S_BXF,S_BYS,S_BYF,S_BZS,S_BZF
CONTAINS

LOGICAL FUNCTION LD_ACTIVE()
CHARACTER(512) :: ENVSTR
INTEGER :: IP,IE,NV,IOS,ENVLEN,ENVSTAT,L
IF (.NOT.LD_INIT) THEN
   LD_INIT=.TRUE.
   ENVSTR=' '
   CALL GET_ENVIRONMENT_VARIABLE('FDS_LDUMP_STEPS',ENVSTR,ENVLEN,ENVSTAT)
   IF (ENVSTAT==0 .AND. ENVLEN>0) THEN
      IF (ENVSTR(1:3)=='ALL') THEN
         LD_ALL=.TRUE.
      ELSE
         IP=1
         DO WHILE (IP<=LEN_TRIM(ENVSTR) .AND. LD_N<LD_MAXSTEPS)
            IE=INDEX(ENVSTR(IP:),',')
            IF (IE==0) THEN ; IE=LEN_TRIM(ENVSTR) ; ELSE ; IE=IP+IE-2 ; ENDIF
            IF (IE>=IP) THEN
               READ(ENVSTR(IP:IE),*,IOSTAT=IOS) NV
               IF (IOS==0) THEN ; LD_N=LD_N+1 ; LD_STEPS(LD_N)=NV ; ENDIF
            ENDIF
            IP=IE+2
         ENDDO
      ENDIF
   ENDIF
ENDIF
LD_ACTIVE=LD_ALL
DO L=1,LD_N
   IF (LD_STEPS(L)==ICYC) LD_ACTIVE=.TRUE.
ENDDO
END FUNCTION LD_ACTIVE

SUBROUTINE LD_OPEN(KIND_,NM)
CHARACTER(*), INTENT(IN) :: KIND_
INTEGER, INTENT(IN) :: NM
CHARACTER(1) :: ST
CHARACTER(256) :: FN
ST='C' ; IF (PREDICTOR) ST='P'
WRITE(FN,'(A,A,I6.6,A,A,A,I3.3,A)') KIND_,'_fds_n',ICYC,'_',ST,'_m',NM,'.bin'
LD_LU=GET_FILE_NUMBER()
OPEN(LD_LU,FILE=TRIM(FN),ACCESS='stream',FORM='unformatted',STATUS='REPLACE')
END SUBROUTINE LD_OPEN

SUBROUTINE LD_HEAD(NAME,KIND_,RANK_,DIMS)
CHARACTER(*), INTENT(IN) :: NAME
INTEGER, INTENT(IN) :: KIND_,RANK_,DIMS(:)
CHARACTER(16) :: N16
N16=NAME
WRITE(LD_LU) N16,INT(KIND_,4),INT(RANK_,4),INT(DIMS(1:RANK_),4)
END SUBROUTINE LD_HEAD
SUBROUTINE LD_R1(NAME,A)
CHARACTER(*), INTENT(IN) :: NAME
REAL(EB), INTENT(IN) :: A(:)
CALL LD_HEAD(NAME,2,1,SHAPE(A)) ; WRITE(LD_LU) A
END SUBROUTINE LD_R1
SUBROUTINE LD_R2(NAME,A)
CHARACTER(*), INTENT(IN) :: NAME
REAL(EB), INTENT(IN) :: A(:,:)
CALL LD_HEAD(NAME,2,2,SHAPE(A)) ; WRITE(LD_LU) A
END SUBROUTINE LD_R2
SUBROUTINE LD_R3(NAME,A)
CHARACTER(*), INTENT(IN) :: NAME
REAL(EB), INTENT(IN) :: A(:,:,:)
CALL LD_HEAD(NAME,2,3,SHAPE(A)) ; WRITE(LD_LU) A
END SUBROUTINE LD_R3
SUBROUTINE LD_I1(NAME,A)
CHARACTER(*), INTENT(IN) :: NAME
INTEGER, INTENT(IN) :: A(:)
CALL LD_HEAD(NAME,1,1,SHAPE(A)) ; WRITE(LD_LU) INT(A,4)
END SUBROUTINE LD_I1
SUBROUTINE LD_RS(NAME,X)
CHARACTER(*), INTENT(IN) :: NAME
REAL(EB), INTENT(IN) :: X
CALL LD_R1(NAME,(/X/))
END SUBROUTINE LD_RS
SUBROUTINE LD_IS(NAME,N)
CHARACTER(*), INTENT(IN) :: NAME
INTEGER, INTENT(IN) :: N
CALL LD_I1(NAME,(/N/))
END SUBROUTINE LD_IS

! called at the start of PRESSURE_SOLVER_COMPUTE_RHS (after the pointers are set): keep the outputs' previous state
SUBROUTINE LD_RHS_PRE(NM)
INTEGER, INTENT(IN) :: NM
IF (.NOT.LD_ACTIVE()) RETURN
IF (ALLOCATED(S_PRHS)) DEALLOCATE(S_PRHS,S_BXS,S_BXF,S_BYS,S_BYF,S_BZS,S_BZF)
ALLOCATE(S_PRHS(SIZE(PRHS,1),SIZE(PRHS,2),SIZE(PRHS,3)),S_BXS(SIZE(BXS,1),SIZE(BXS,2)),S_BXF(SIZE(BXF,1),SIZE(BXF,2)),&
         S_BYS(SIZE(BYS,1),SIZE(BYS,2)),S_BYF(SIZE(BYF,1),SIZE(BYF,2)),S_BZS(SIZE(BZS,1),SIZE(BZS,2)),S_BZF(SIZE(BZF,1),SIZE(BZF,2)))
S_PRHS=PRHS ; S_BXS=BXS ; S_BXF=BXF ; S_BYS=BYS ; S_BYF=BYF ; S_BZS=BZS ; S_BZF=BZF
END SUBROUTINE LD_RHS_PRE

! called at the end of PRESSURE_SOLVER_COMPUTE_RHS
SUBROUTINE LD_RHS_POST(NM,T,DT,MODE)
INTEGER, INTENT(IN) :: NM,MODE
REAL(EB), INTENT(IN) :: T,DT
REAL(EB), POINTER, DIMENSION(:,:,:) :: HP,UU,VV,WW
INTEGER :: IW,N,NW,IA,NOM,NOPEN
INTEGER, ALLOCATABLE, DIMENSION(:) :: W_I,W_J,W_K,W_IOR,W_PBC,W_BT,WV_RAMP,WV_NEDDY,WV_IOR
REAL(EB), ALLOCATABLE, DIMENSION(:) :: W_DUNDT,W_TIGN,W_RHOF,W_OTHERD,WV_DYNP,W_WORK1,RAMPF,TSIS
REAL(EB) :: TSI
TYPE (WALL_TYPE), POINTER :: WC
TYPE (EXTERNAL_WALL_TYPE), POINTER :: EWC
TYPE (BOUNDARY_COORD_TYPE), POINTER :: BC
TYPE (BOUNDARY_PROP1_TYPE), POINTER :: B1
TYPE (VENTS_TYPE), POINTER :: VT
IF (.NOT.LD_ACTIVE()) RETURN
IF (SOLID_PHASE_ONLY .OR. FREEZE_VELOCITY) RETURN
IF (PREDICTOR) THEN
   HP=>H ; UU=>U ; VV=>V ; WW=>W
ELSE
   HP=>HS ; UU=>US ; VV=>VS ; WW=>WS
ENDIF
IF (MODE==2) THEN
! ---- L1211 (3-D natural layout only)
IF ((IPS<=1 .OR. IPS==4 .OR. IPS==7) .AND. .NOT.CYLINDRICAL) THEN
   CALL LD_OPEN('L1211',NM)
   CALL LD_IS('IBAR',IBAR) ; CALL LD_IS('JBAR',JBAR) ; CALL LD_IS('KBAR',KBAR)
   CALL LD_R3('FVX',FVX) ; CALL LD_R3('FVY',FVY) ; CALL LD_R3('FVZ',FVZ) ; CALL LD_R3('DDDT',DDDT)
   CALL LD_R1('RDX',RDX(0:IBP1)) ; CALL LD_R1('RDY',RDY(0:JBP1)) ; CALL LD_R1('RDZ',RDZ(0:KBP1))
   CALL LD_R3('PRHS_IN',S_PRHS) ; CALL LD_R3('PRHS_OUT',PRHS)
   CLOSE(LD_LU)
ENDIF
ENDIF
IF (MODE==1) THEN
! ---- L1209
NW=N_EXTERNAL_WALL_CELLS
ALLOCATE(W_I(NW),W_J(NW),W_K(NW),W_IOR(NW),W_PBC(NW),W_BT(NW),WV_RAMP(NW),WV_NEDDY(NW),WV_IOR(NW))
ALLOCATE(W_DUNDT(NW),W_TIGN(NW),W_RHOF(NW),W_OTHERD(NW),WV_DYNP(NW),W_WORK1(NW),RAMPF(NW),TSIS(NW))
NOPEN=0
DO IW=1,NW
   WC=>WALL(IW) ; EWC=>EXTERNAL_WALL(IW) ; BC=>BOUNDARY_COORD(WC%BC_INDEX)
   W_I(IW)=BC%II ; W_J(IW)=BC%JJ ; W_K(IW)=BC%KK ; W_IOR(IW)=BC%IOR
   W_PBC(IW)=EWC%PRESSURE_BC_TYPE ; W_BT(IW)=WC%BOUNDARY_TYPE ; W_DUNDT(IW)=EWC%DUNDT ; W_WORK1(IW)=WALL_WORK1(IW)
   W_OTHERD(IW)=0._EB ; W_TIGN(IW)=0._EB ; W_RHOF(IW)=1._EB ; WV_RAMP(IW)=0 ; WV_NEDDY(IW)=0 ; WV_IOR(IW)=0 ; WV_DYNP(IW)=0._EB
   IA=ABS(BC%IOR) ; NOM=EWC%NOM
   IF (WC%BOUNDARY_TYPE==INTERPOLATED_BOUNDARY .AND. EWC%PRESSURE_BC_TYPE==DIRICHLET) THEN
      SELECT CASE(IA)
         CASE(1) ; W_OTHERD(IW)=MESHES(NOM)%DX(EWC%IIO_MIN)
         CASE(2) ; W_OTHERD(IW)=MESHES(NOM)%DY(EWC%JJO_MIN)
         CASE(3) ; W_OTHERD(IW)=MESHES(NOM)%DZ(EWC%KKO_MIN)
      END SELECT
   ENDIF
   IF (WC%BOUNDARY_TYPE==OPEN_BOUNDARY .AND. EWC%PRESSURE_BC_TYPE==DIRICHLET) THEN
      B1=>BOUNDARY_PROP1(WC%B1_INDEX) ; VT=>VENTS(WC%VENT_INDEX)
      IF (VT%N_EDDY>0) STOP 'LDUMP: synthetic eddies are not supported by the dump'
      W_TIGN(IW)=B1%T_IGN ; W_RHOF(IW)=B1%RHO_F
      WV_RAMP(IW)=VT%PRESSURE_RAMP_INDEX ; WV_NEDDY(IW)=VT%N_EDDY ; WV_IOR(IW)=VT%IOR ; WV_DYNP(IW)=VT%DYNAMIC_PRESSURE
      IF (ABS(B1%T_IGN-T_BEGIN)<=TWENTY_EPSILON_EB .AND. VT%PRESSURE_RAMP_INDEX >=1) THEN
         TSI = T
      ELSE
         TSI = T - T_BEGIN
      ENDIF
      NOPEN=NOPEN+1
      TSIS(NOPEN)=TSI
      RAMPF(NOPEN)=EVALUATE_RAMP(TSI,VT%PRESSURE_RAMP_INDEX)
   ENDIF
ENDDO
CALL LD_OPEN('L1209',NM)
CALL LD_IS('IBAR',IBAR) ; CALL LD_IS('JBAR',JBAR) ; CALL LD_IS('KBAR',KBAR) ; CALL LD_IS('NWALL',NW)
N=0 ; IF (OPEN_WIND_BOUNDARY) N=1
CALL LD_IS('OPEN_WIND',N)
CALL LD_RS('T',T) ; CALL LD_RS('DT',DT) ; CALL LD_RS('T_BEGIN',T_BEGIN) ; CALL LD_RS('U0',U0) ; CALL LD_RS('V0',V0) ; CALL LD_RS('W0',W0)
CALL LD_R3('HP',HP) ; CALL LD_R3('KRES',KRES) ; CALL LD_R3('UU',UU) ; CALL LD_R3('VV',VV) ; CALL LD_R3('WW',WW)
CALL LD_R3('FVX',FVX) ; CALL LD_R3('FVY',FVY) ; CALL LD_R3('FVZ',FVZ)
CALL LD_R1('HX',HX(0:IBP1)) ; CALL LD_R1('HY',HY(0:JBP1)) ; CALL LD_R1('HZ',HZ(0:KBP1))
CALL LD_R1('DX',DX(1:IBAR)) ; CALL LD_R1('DY',DY(1:JBAR)) ; CALL LD_R1('DZ',DZ(1:KBAR))
CALL LD_R1('RDXN',RDXN(0:IBAR)) ; CALL LD_R1('RDYN',RDYN(0:JBAR)) ; CALL LD_R1('RDZN',RDZN(0:KBAR))
CALL LD_R1('U_WIND',U_WIND(0:KBP1)) ; CALL LD_R1('V_WIND',V_WIND(0:KBP1)) ; CALL LD_R1('W_WIND',W_WIND(0:KBP1))
CALL LD_R1('WALL_WORK1',W_WORK1)
CALL LD_R2('BXS_IN',S_BXS) ; CALL LD_R2('BXF_IN',S_BXF) ; CALL LD_R2('BYS_IN',S_BYS) ; CALL LD_R2('BYF_IN',S_BYF)
CALL LD_R2('BZS_IN',S_BZS) ; CALL LD_R2('BZF_IN',S_BZF)
CALL LD_I1('W_I',W_I) ; CALL LD_I1('W_J',W_J) ; CALL LD_I1('W_K',W_K) ; CALL LD_I1('W_IOR',W_IOR)
CALL LD_I1('W_PBC',W_PBC) ; CALL LD_I1('W_BT',W_BT)
CALL LD_R1('W_DUNDT',W_DUNDT) ; CALL LD_R1('W_TIGN',W_TIGN) ; CALL LD_R1('W_RHOF',W_RHOF) ; CALL LD_R1('W_OTHERD',W_OTHERD)
CALL LD_I1('WV_RAMP',WV_RAMP) ; CALL LD_I1('WV_NEDDY',WV_NEDDY) ; CALL LD_I1('WV_IOR',WV_IOR) ; CALL LD_R1('WV_DYNP',WV_DYNP)
CALL LD_IS('N_RAMP',NOPEN)
IF (NOPEN>0) THEN
   CALL LD_R1('RAMPF_SEQ',RAMPF(1:NOPEN)) ; CALL LD_R1('TSI_SEQ',TSIS(1:NOPEN))
ELSE
   CALL LD_R1('RAMPF_SEQ',(/0._EB/)) ; CALL LD_R1('TSI_SEQ',(/0._EB/))
ENDIF
CALL LD_R2('BXS_OUT',BXS) ; CALL LD_R2('BXF_OUT',BXF) ; CALL LD_R2('BYS_OUT',BYS) ; CALL LD_R2('BYF_OUT',BYF)
CALL LD_R2('BZS_OUT',BZS) ; CALL LD_R2('BZF_OUT',BZF)
CLOSE(LD_LU)
ENDIF
END SUBROUTINE LD_RHS_POST

! called inside PRESSURE_SOLVER_FFT just before the H boundary fill (single thread) and after it
SUBROUTINE LD_HBC_PRE(NM)
INTEGER, INTENT(IN) :: NM
REAL(EB), POINTER, DIMENSION(:,:,:) :: HP
IF (.NOT.LD_ACTIVE()) RETURN
IF (PREDICTOR) THEN ; HP=>H ; ELSE ; HP=>HS ; ENDIF
IF (ALLOCATED(S_H)) DEALLOCATE(S_H)
ALLOCATE(S_H(0:IBP1,0:JBP1,0:KBP1)) ; S_H=HP
END SUBROUTINE LD_HBC_PRE
SUBROUTINE LD_HBC_POST(NM)
INTEGER, INTENT(IN) :: NM
REAL(EB), POINTER, DIMENSION(:,:,:) :: HP
IF (.NOT.LD_ACTIVE()) RETURN
IF (PREDICTOR) THEN ; HP=>H ; ELSE ; HP=>HS ; ENDIF
CALL LD_OPEN('HBC',NM)
CALL LD_IS('IBAR',IBAR) ; CALL LD_IS('JBAR',JBAR) ; CALL LD_IS('KBAR',KBAR)
CALL LD_IS('LBC',LBC) ; CALL LD_IS('MBC',MBC) ; CALL LD_IS('NBC',NBC)
CALL LD_RS('DXI',DXI) ; CALL LD_RS('DETA',DETA) ; CALL LD_RS('DZETA',DZETA)
CALL LD_R2('BXS',BXS) ; CALL LD_R2('BXF',BXF) ; CALL LD_R2('BYS',BYS) ; CALL LD_R2('BYF',BYF) ; CALL LD_R2('BZS',BZS) ; CALL LD_R2('BZF',BZF)
CALL LD_R3('H_IN',S_H) ; CALL LD_R3('H_OUT',HP)
CLOSE(LD_LU)
END SUBROUTINE LD_HBC_POST

! called in PRESSURE_SOLVER_CHECK_RESIDUALS right after the loop that forms P
SUBROUTINE LD_P_POST(NM,RHOP,HP,PP)
INTEGER, INTENT(IN) :: NM
REAL(EB), POINTER, DIMENSION(:,:,:) :: RHOP,HP,PP
IF (.NOT.LD_ACTIVE()) RETURN
CALL LD_OPEN('L1207',NM)
CALL LD_IS('IBAR',IBAR) ; CALL LD_IS('JBAR',JBAR) ; CALL LD_IS('KBAR',KBAR)
CALL LD_R3('RHO',RHOP(-1:IBP1+1,-1:JBP1+1,-1:KBP1+1)) ; CALL LD_R3('H',HP) ; CALL LD_R3('KRES',KRES) ; CALL LD_R3('P_OUT',PP)
CLOSE(LD_LU)
END SUBROUTINE LD_P_POST
END MODULE LDUMP_MOD

'''

rep("\nMODULE PRES\n", "\n" + MODULE + "MODULE PRES\n")
# the module PRES gets the USE through its USE list
rep("MODULE PRES\n\nUSE PRECISION_PARAMETERS\nUSE MESH_POINTERS\n", "MODULE PRES\n\nUSE PRECISION_PARAMETERS\nUSE MESH_POINTERS\nUSE LDUMP_MOD\n")

# COMPUTE_RHS: pre call after the pointer selection, post call before T_USED
rep("""ELSE
   UU => US
   VV => VS
   WW => WS
   HP => HS
   RHOP => RHOS
ENDIF

!$OMP PARALLEL
""", """ELSE
   UU => US
   VV => VS
   WW => WS
   HP => HS
   RHOP => RHOS
ENDIF

CALL LD_RHS_PRE(NM)

!$OMP PARALLEL
""")
rep("""ENDDO WALL_CELL_LOOP
!$OMP END DO
""", """ENDDO WALL_CELL_LOOP
!$OMP END DO

!$OMP BARRIER
!$OMP MASTER
CALL LD_RHS_POST(NM,T,DT,1)
!$OMP END MASTER
!$OMP BARRIER
""")
rep("""!$OMP END PARALLEL

T_USED(5)=T_USED(5)+CURRENT_TIME()-TNOW
END SUBROUTINE PRESSURE_SOLVER_COMPUTE_RHS""", """!$OMP END PARALLEL

CALL LD_RHS_POST(NM,T,DT,2)

T_USED(5)=T_USED(5)+CURRENT_TIME()-TNOW
END SUBROUTINE PRESSURE_SOLVER_COMPUTE_RHS""")
# FFT: single-thread dump around the H boundary fill
rep("""! Apply boundary conditions to H

!$OMP DO
DO K=1,KBAR
   DO J=1,JBAR
      IF (LBC==3""", """! Apply boundary conditions to H

!$OMP BARRIER
!$OMP MASTER
CALL LD_HBC_PRE(NM)
!$OMP END MASTER
!$OMP BARRIER

!$OMP DO
DO K=1,KBAR
   DO J=1,JBAR
      IF (LBC==3""")
rep("""ENDDO
!$OMP END DO

!$OMP END PARALLEL

T_USED(5)=T_USED(5)+CURRENT_TIME()-TNOW
END SUBROUTINE PRESSURE_SOLVER_FFT""", """ENDDO
!$OMP END DO

!$OMP MASTER
CALL LD_HBC_POST(NM)
!$OMP END MASTER

!$OMP END PARALLEL

T_USED(5)=T_USED(5)+CURRENT_TIME()-TNOW
END SUBROUTINE PRESSURE_SOLVER_FFT""")
# CHECK_RESIDUALS
rep("""            P(I,J,K) = RHOP(I,J,K)*(HP(I,J,K)-KRES(I,J,K))
         ENDDO
      ENDDO
   ENDDO
   !$OMP END DO
""", """            P(I,J,K) = RHOP(I,J,K)*(HP(I,J,K)-KRES(I,J,K))
         ENDDO
      ENDDO
   ENDDO
   !$OMP END DO

   !$OMP MASTER
   CALL LD_P_POST(NM,RHOP,HP,P)
   !$OMP END MASTER
   !$OMP BARRIER
""")
open(p, "w").write(s)
print("hooked", p)
