!> (b) Only uniform Cartesian metrics are used: R(I)/RRN(I) stay as the FDS set-up made them (=1); CYLINDRICAL and TRN* meshes are rejected at
!>     level-0 assembly, so VELOCITY_FLUX_CYLINDRICAL is never called.
