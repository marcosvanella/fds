   CASE('CE_EDGE_INDEX')   ! CELL(CELL_INDEX(I,J,K))%EDGE_INDEX(1:12) flattened to (0:IBP1,0:JBP1,0:KBP1,12), integers as REAL (harness casts to i32)
      IF (ALLOCATED(M%CELL_INDEX)) THEN
