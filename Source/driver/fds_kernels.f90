!>     level-0 assembly, so VELOCITY_FLUX_CYLINDRICAL is never called.
!>
!> Kernels wrapped: COMPUTE_VISCOSITY, MASS_FINITE_DIFFERENCES+DENSITY (unmodified) and MASS_FINITE_DIFFERENCES+DENSITY_PRE_CLIP / DENSITY_POST_CLIP
!> (fds_density_split.f90, for the D-031 gather clip), VELOCITY_FLUX, DIVERGENCE_PART_1, DIVERGENCE_PART_2, VELOCITY_PREDICTOR, VELOCITY_CORRECTOR.
