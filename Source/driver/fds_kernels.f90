END FUNCTION DIFF

SUBROUTINE X3(P)
REAL(EB), POINTER, INTENT(IN) :: P(:,:,:)
INTEGER :: I,J,K
INTEGER(C_LONG) :: IDX
DO K=LB(3),UB(3) ; DO J=LB(2),UB(2) ; DO I=LB(1),UB(1)
   IDX = (I-LB(1)) + INT(UB(1)-LB(1)+1,C_LONG)*((J-LB(2)) + INT(UB(2)-LB(2)+1,C_LONG)*(K-LB(3))) + 1
   IF (I<LBOUND(P,1) .OR. I>UBOUND(P,1) .OR. J<LBOUND(P,2) .OR. J>UBOUND(P,2) .OR. K<LBOUND(P,3) .OR. K>UBOUND(P,3)) THEN ; IERR = 3 ; RETURN ; ENDIF
   NCNT = NCNT+1
   IF (MODE==MODE_LOAD) THEN ; P(I,J,K) = DATA(IDX) ; ELSEIF (MODE==MODE_READ) THEN ; DATA(IDX) = P(I,J,K) ; ELSE ; IF (DIFF(P(I,J,K),DATA(IDX))) THEN ; NBAD = NBAD+1 ; IF (NBAD<=8 .AND. VERBOSE_DIFF) WRITE(0,'(A,3I4,2ES24.16)') '   first difference at',I,J,K,P(I,J,K),DATA(IDX) ; ENDIF ; ENDIF
ENDDO ; ENDDO ; ENDDO
END SUBROUTINE X3

SUBROUTINE X4(P)
REAL(EB), POINTER, INTENT(IN) :: P(:,:,:,:)
