   NCNT = NCNT+1
   IF (MODE==MODE_LOAD) THEN ; A(I,J) = DATA(IDX) ; ELSEIF (MODE==MODE_READ) THEN ; DATA(IDX) = A(I,J) ; ELSE ; IF (DIFF(A(I,J),DATA(IDX))) NBAD = NBAD+1 ; ENDIF
ENDDO ; ENDDO
END SUBROUTINE XT2

