!> \brief bind(C) wrappers that call the UNMODIFIED FDS kernels on one box (= one MESHES(NM) entry) and the data-transfer routines used by the
!> kernel check (M2a, S3). The kernels find their data through POINT_TO_MESH(NM), i.e. through MESHES(NM)%X: field arrays bound from AMReX FABs
!> by FDS_BOX_SHIM (native FAB, native bounds; no strided window) and the FDS-owned side data built by the FDS set-up.
!>
!> Kernel-facing file rules (M2a):
!> (a) Passive scalars (N_TOTAL_SCALARS beyond the tracked species) are handled by Fields.cpp: ZZ/ZZS carry ncomp=N_TOTAL_SCALARS as the last
