   IF (I<LBOUND(A,1) .OR. I>UBOUND(A,1)) THEN ; IERR = 3 ; RETURN ; ENDIF
   NCNT = NCNT+1
   IF (MODE==MODE_LOAD) THEN ; A(I) = DATA(I-LB(1)+1) ; ELSEIF (MODE==MODE_READ) THEN ; DATA(I-LB(1)+1) = A(I) ; ELSE ; IF (DIFF(A(I),DATA(I-LB(1)+1))) NBAD = NBAD+1 ; ENDIF
ENDDO
END SUBROUTINE XT1

SUBROUTINE XT2(A)   !< species tables CP_Z(0:I_MAX_TEMP,N_SPECIES) etc. (module arrays; LB/UB in the table's own indices)
