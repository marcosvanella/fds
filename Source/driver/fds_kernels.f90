!> W2 (leaf rule): remove the particles of level-0 mesh NM whose cell is covered by a finer level (COVERED(I,J,K)/=0, valid cells, I fastest)
SUBROUTINE FDS_K_DROP_COVERED(NM,COVERED) BIND(C,NAME='fds_k_drop_covered')
USE MEMORY_FUNCTIONS, ONLY: NULLIFY_PARTICLE
USE TYPES, ONLY: BOUNDARY_COORD_TYPE,LAGRANGIAN_PARTICLE_TYPE
INTEGER(C_INT), VALUE :: NM
INTEGER(C_INT), INTENT(IN) :: COVERED(*)
TYPE(MESH_TYPE), POINTER :: M
TYPE(BOUNDARY_COORD_TYPE), POINTER :: BC
TYPE(LAGRANGIAN_PARTICLE_TYPE), POINTER :: LQ
INTEGER :: IP
M => MESHES(NM)
DO IP=M%NLP,1,-1
   BC => M%BOUNDARY_COORD(M%LAGRANGIAN_PARTICLE(IP)%BC_INDEX)
   IF (COVERED(BC%IIG+M%IBAR*((BC%JJG-1)+M%JBAR*(BC%KKG-1)))==0) CYCLE
   CALL NULLIFY_PARTICLE(NM,IP)
   IF (IP<M%NLP) M%LAGRANGIAN_PARTICLE(IP) = M%LAGRANGIAN_PARTICLE(M%NLP)
   LQ => M%LAGRANGIAN_PARTICLE(M%NLP)
   LQ%BC_INDEX = 0 ; LQ%OD_INDEX = 0 ; LQ%B1_INDEX = 0 ; LQ%B2_INDEX = 0 ; LQ%BR_INDEX = 0
   M%NLP = M%NLP - 1
ENDDO
END SUBROUTINE FDS_K_DROP_COVERED

!> GET_IJK tables of read.f90 for the uniform fine box M (GINV is the identity), once per box
SUBROUTINE IJK_TABLES(M)
TYPE(MESH_TYPE), INTENT(INOUT) :: M
IF (ALLOCATED(M%CELLSI)) RETURN
CALL CELLS(M%CELLSI,M%CELLSI_LO,M%CELLSI_HI,M%RDXINT,M%IBAR,M%XS,M%XF)
CALL CELLS(M%CELLSJ,M%CELLSJ_LO,M%CELLSJ_HI,M%RDYINT,M%JBAR,M%YS,M%YF)
CALL CELLS(M%CELLSK,M%CELLSK_LO,M%CELLSK_HI,M%RDZINT,M%KBAR,M%ZS,M%ZF)
END SUBROUTINE IJK_TABLES

SUBROUTINE CELLS(C,LO,HI,RINT,N,X0,X1)
REAL(EB), ALLOCATABLE :: C(:)
INTEGER :: LO,HI,I
INTEGER, INTENT(IN) :: N
REAL(EB) :: RINT
REAL(EB), INTENT(IN) :: X0,X1
RINT = REAL(500*N,EB)/(X1-X0) ; LO = -500 ; HI = 500*N+500
ALLOCATE(C(LO:HI))
DO I=LO,HI
   C(I) = (REAL(I,EB)/RINT)*(REAL(N,EB)/(X1-X0))
   IF (ABS(C(I)-REAL(NINT(C(I)),EB)) < 1.E-14_EB) C(I) = REAL(NINT(C(I)),EB)
   C(I) = MIN(MAX(C(I),-0.9_EB),REAL(N)+0.9_EB)
ENDDO
END SUBROUTINE CELLS

!> W8 (PV-9) regrid migration: the whole records of the particles of box NM (any level) in index order, packed by stock PACK_PARTICLE as main.f90 sends them
!> (code 11). Returns the number of doubles; when NB covers it, BUF gets per particle [length, class, X, Y, Z, NR, NI, NL, reals, integers, logicals] and the box
!> is emptied (a fine box is destroyed by the unbind that follows, so only level-0 storage is released).
INTEGER(C_LONG) FUNCTION FDS_K_PART_STASH(NM,NB,BUF) BIND(C,NAME='fds_k_part_stash')
USE MESH_VARIABLES, ONLY: MESH_OBJ
USE MEMORY_FUNCTIONS, ONLY: PACK_PARTICLE,NULLIFY_PARTICLE
USE TYPES, ONLY: STORAGE_TYPE,LAGRANGIAN_PARTICLE_TYPE,BOUNDARY_COORD_TYPE
INTEGER(C_INT), VALUE :: NM
INTEGER(C_LONG), VALUE :: NB
REAL(C_DOUBLE), INTENT(INOUT) :: BUF(*)
TYPE(MESH_TYPE), POINTER :: M
TYPE(STORAGE_TYPE), POINTER :: OS
TYPE(LAGRANGIAN_PARTICLE_TYPE), POINTER :: LP
TYPE(BOUNDARY_COORD_TYPE), POINTER :: BC
INTEGER :: IP,RC,IC,LC
INTEGER(C_LONG) :: Q
M => BOX_OBJ(NM)
IF (NM>NMESHES) MESH_OBJ => M
ALLOCATE(OS)
Q = 0
DO IP=1,M%NLP
   LP => M%LAGRANGIAN_PARTICLE(IP)
   RC=0 ; IC=0 ; LC=0
   CALL PACK_PARTICLE(NM,OS,LP,LP%CLASS_INDEX,RC,IC,LC,UNPACK_IT=.FALSE.,COUNT_ONLY=.TRUE.,CHECK_BOUNDS=.FALSE.)
   IF (NB>=Q+8+RC+IC+LC) THEN
      ALLOCATE(OS%REALS(RC),OS%INTEGERS(IC),OS%LOGICALS(LC))
      RC=0 ; IC=0 ; LC=0
      CALL PACK_PARTICLE(NM,OS,LP,LP%CLASS_INDEX,RC,IC,LC,UNPACK_IT=.FALSE.,COUNT_ONLY=.FALSE.,CHECK_BOUNDS=.FALSE.)
      BC => M%BOUNDARY_COORD(LP%BC_INDEX)
      BUF(Q+1:Q+8) = [REAL(8+RC+IC+LC,EB),REAL(LP%CLASS_INDEX,EB),BC%X,BC%Y,BC%Z,REAL(RC,EB),REAL(IC,EB),REAL(LC,EB)]
      BUF(Q+9:Q+8+RC) = OS%REALS
      BUF(Q+9+RC:Q+8+RC+IC) = REAL(OS%INTEGERS,EB)
      BUF(Q+9+RC+IC:Q+8+RC+IC+LC) = MERGE(1._EB,0._EB,OS%LOGICALS)
      DEALLOCATE(OS%REALS,OS%INTEGERS,OS%LOGICALS)
   ENDIF
   Q = Q+8+RC+IC+LC
ENDDO
DEALLOCATE(OS)
MESH_OBJ => NULL()
FDS_K_PART_STASH = Q
IF (NB<Q) RETURN
DO IP=1,M%NLP
   IF (NM<=NMESHES) CALL NULLIFY_PARTICLE(NM,IP)
   LP => M%LAGRANGIAN_PARTICLE(IP)
   LP%BC_INDEX = 0 ; LP%OD_INDEX = 0 ; LP%B1_INDEX = 0 ; LP%B2_INDEX = 0 ; LP%BR_INDEX = 0
ENDDO
M%NLP = 0
END FUNCTION FDS_K_PART_STASH

!> W8: append the NR records of BUF (layout of FDS_K_PART_STASH) to box NM as main.f90 receives particles (code 11): storage, stock unpack, unstick, then the
!> cell and RVC of the new box (the packed cell indices and RVC belong to the old box; DX/DY/DZ are kept).
SUBROUTINE FDS_K_PART_PLACE(NM,NR,BUF) BIND(C,NAME='fds_k_part_place')
USE MESH_VARIABLES, ONLY: MESH_OBJ
USE MEMORY_FUNCTIONS, ONLY: PACK_PARTICLE,ALLOCATE_STORAGE
USE TRAN, ONLY: GET_IJK
USE PART, ONLY: GET_RVC
USE TYPES, ONLY: STORAGE_TYPE,LAGRANGIAN_PARTICLE_TYPE,BOUNDARY_COORD_TYPE,LAGRANGIAN_PARTICLE_CLASS
INTEGER(C_INT), VALUE :: NM,NR
REAL(C_DOUBLE), INTENT(IN) :: BUF(*)
TYPE(MESH_TYPE), POINTER :: M
TYPE(STORAGE_TYPE), POINTER :: OS
TYPE(LAGRANGIAN_PARTICLE_TYPE), POINTER :: LP
TYPE(BOUNDARY_COORD_TYPE), POINTER :: BC
INTEGER :: N,IPC,RC,IC,LC,Q
REAL(EB) :: XI,YJ,ZK
M => BOX_OBJ(NM)
IF (NM>NMESHES) MESH_OBJ => M
IF (NM>NMESHES) CALL IJK_TABLES(M)
ALLOCATE(OS)
Q = 0
DO N=1,NR
   IPC = NINT(BUF(Q+2)) ; RC = NINT(BUF(Q+6)) ; IC = NINT(BUF(Q+7)) ; LC = NINT(BUF(Q+8))
   ALLOCATE(OS%REALS(RC),OS%INTEGERS(IC),OS%LOGICALS(LC))
   OS%REALS = BUF(Q+9:Q+8+RC)
   OS%INTEGERS = NINT(BUF(Q+9+RC:Q+8+RC+IC))
   OS%LOGICALS = BUF(Q+9+RC+IC:Q+8+RC+IC+LC)>0.5_EB
   Q = Q+NINT(BUF(Q+1))
   CALL ALLOCATE_STORAGE(NM,LP_INDEX=M%NLP+1,LPC_INDEX=IPC,SURF_INDEX=LAGRANGIAN_PARTICLE_CLASS(IPC)%SURF_INDEX)
   M%NLP = M%NLP+1
   LP => M%LAGRANGIAN_PARTICLE(M%NLP)
   RC=0 ; IC=0 ; LC=0
   CALL PACK_PARTICLE(NM,OS,LP,IPC,RC,IC,LC,UNPACK_IT=.TRUE.,COUNT_ONLY=.FALSE.,CHECK_BOUNDS=.TRUE.)
   DEALLOCATE(OS%REALS,OS%INTEGERS,OS%LOGICALS)
   LP%WALL_INDEX = 0
   IF (LP%CFACE_INDEX/=EXTERNAL_CFACE) LP%CFACE_INDEX = 0
   BC => M%BOUNDARY_COORD(LP%BC_INDEX)
   CALL GET_IJK(BC%X,BC%Y,BC%Z,NM,XI,YJ,ZK,BC%IIG,BC%JJG,BC%KKG)
   BC%II = BC%IIG ; BC%JJ = BC%JJG ; BC%KK = BC%KKG
   CALL GET_RVC(NM,BC%IIG,BC%JJG,BC%KKG,LP%RVC)
ENDDO
DEALLOCATE(OS)
MESH_OBJ => NULL()
END SUBROUTINE FDS_K_PART_PLACE

!> W8 deposit-only step (Role 3 design section 4): SGN times the D_SOURCE and M_DOT_PPP terms of wall.f90 DEPOSIT_PARTICLE_MASS for the particles of box NM, from
!> the rates the last corrector WALL_BC stored in B1 (not recomputed) and the current RVC; Q_DOT, M_DOT and the particle mass are not touched.
SUBROUTINE FDS_K_PART_DEPOSIT(NM,SGN) BIND(C,NAME='fds_k_part_deposit')
USE TYPES, ONLY: LAGRANGIAN_PARTICLE_TYPE,LAGRANGIAN_PARTICLE_CLASS_TYPE,BOUNDARY_COORD_TYPE,BOUNDARY_PROP1_TYPE,SURFACE_TYPE,&
                 LAGRANGIAN_PARTICLE_CLASS,SURFACE,SPECIES_MIXTURE
USE PHYSICAL_FUNCTIONS, ONLY: GET_SPECIFIC_HEAT,GET_SPECIFIC_GAS_CONSTANT
INTEGER(C_INT), VALUE :: NM
REAL(C_DOUBLE), VALUE :: SGN
TYPE(MESH_TYPE), POINTER :: M
TYPE(LAGRANGIAN_PARTICLE_TYPE), POINTER :: LP
TYPE(LAGRANGIAN_PARTICLE_CLASS_TYPE), POINTER :: LPC
TYPE(BOUNDARY_COORD_TYPE), POINTER :: BC
TYPE(BOUNDARY_PROP1_TYPE), POINTER :: B1
TYPE(SURFACE_TYPE), POINTER :: SF
INTEGER :: IP,NS
REAL(EB) :: M_GAS,RSUM_G,CP,H_G
M => BOX_OBJ(NM)
DO IP=1,M%NLP
   LP => M%LAGRANGIAN_PARTICLE(IP) ; LPC => LAGRANGIAN_PARTICLE_CLASS(LP%CLASS_INDEX) ; SF => SURFACE(LPC%SURF_INDEX)
   IF (.NOT.LPC%SOLID_PARTICLE .OR. LPC%MASSLESS_TARGET) CYCLE
   IF (ABS(SF%INNER_RADIUS+MERGE(LP%RADIUS,SF%THICKNESS,SF%PYROLYSIS_MODEL==PYROLYSIS_PREDICTED))<TWENTY_EPSILON_EB) CYCLE
   BC => M%BOUNDARY_COORD(LP%BC_INDEX) ; B1 => M%BOUNDARY_PROP1(LP%B1_INDEX)
   M_GAS = B1%RHO_G/LP%RVC
   CALL GET_SPECIFIC_GAS_CONSTANT(B1%ZZ_G(1:N_TRACKED_SPECIES),RSUM_G)
   DO NS=1,N_TRACKED_SPECIES
      IF (ABS(B1%M_DOT_G_PP_ADJUST(NS))<=TWENTY_EPSILON_EB) CYCLE
      M%D_SOURCE(BC%IIG,BC%JJG,BC%KKG) = M%D_SOURCE(BC%IIG,BC%JJG,BC%KKG) + &
         SGN*(LP%PWT*B1%M_DOT_G_PP_ADJUST(NS)*B1%AREA)*(SPECIES_MIXTURE(NS)%RCON/RSUM_G/M_GAS)
      M%M_DOT_PPP(BC%IIG,BC%JJG,BC%KKG,NS) = M%M_DOT_PPP(BC%IIG,BC%JJG,BC%KKG,NS) + SGN*(LP%PWT*B1%M_DOT_G_PP_ADJUST(NS)*B1%AREA)*LP%RVC
   ENDDO
   CALL GET_SPECIFIC_HEAT(B1%ZZ_G(1:N_TRACKED_SPECIES),CP,B1%TMP_G)
   H_G = CP*B1%TMP_G*M_GAS
   M%D_SOURCE(BC%IIG,BC%JJG,BC%KKG) = M%D_SOURCE(BC%IIG,BC%JJG,BC%KKG) - SGN*(B1%Q_DOT_G_PP*B1%AREA/H_G*LP%PWT)
   M%D_SOURCE(BC%IIG,BC%JJG,BC%KKG) = M%D_SOURCE(BC%IIG,BC%JJG,BC%KKG) - SGN*(B1%Q_CON_F*B1%AREA/H_G*LP%PWT)
ENDDO
END SUBROUTINE FDS_K_PART_DEPOSIT

