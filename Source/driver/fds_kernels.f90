!> main.f90 particle calls on a level-0 mesh. MODE 1: INSERT_ALL_PARTICLES (predictor start); 2: PARTICLE_MOMENTUM_TRANSFER (after WALL_BC);
!> 3: PARTICLE_MASS_ENERGY_TRANSFER and MOVE_PARTICLES (corrector, before WALL_BC)
SUBROUTINE FDS_K_PART(MODE,T,DT,NM) BIND(C,NAME='fds_k_part')
USE MESH_VARIABLES, ONLY: MESH_OBJ
INTEGER(C_INT), VALUE :: MODE,NM
REAL(C_DOUBLE), VALUE :: T,DT
CALL FDS_HOOK_FINE_GUARD('fds_k_part',NM,NMESHES)
SELECT CASE(MODE)
   CASE(1) ; CALL INSERT_ALL_PARTICLES(T,NM)
   CASE(2) ; CALL PARTICLE_MOMENTUM_TRANSFER(NM)
   CASE(3)
      IF (NM>NMESHES) MESH_OBJ => BOX_OBJ(NM)   ! fine box of the bed level (as FDS_K_BED_INSERT)
      CALL PARTICLE_MASS_ENERGY_TRANSFER(T,DT,NM) ; CALL MOVE_PARTICLES(T,DT,NM)
      MESH_OBJ => NULL()
END SELECT
END SUBROUTINE FDS_K_PART

!> W2: stock INSERT_ALL_PARTICLES on fine box NM of the particle bed level, once at t=0 (MESH_OBJ is the box). The per-mesh insertion
!> clocks and flags (sized NMESHES by read.f90) are extended to NM with the read.f90 start values.
SUBROUTINE FDS_K_BED_INSERT(T,NM) BIND(C,NAME='fds_k_bed_insert')
USE MESH_VARIABLES, ONLY: MESH_OBJ
USE TYPES, ONLY: INITIALIZATION,SURFACE
REAL(C_DOUBLE), VALUE :: T
INTEGER(C_INT), VALUE :: NM
INTEGER :: I
DO I=1,N_INIT
   IF (ALLOCATED(INITIALIZATION(I)%ALREADY_INSERTED)) CALL GROW_L(INITIALIZATION(I)%ALREADY_INSERTED)
   IF (ALLOCATED(INITIALIZATION(I)%PARTICLE_INSERT_CLOCK)) CALL GROW_R(INITIALIZATION(I)%PARTICLE_INSERT_CLOCK,T_BEGIN)
ENDDO
DO I=0,N_SURF
   IF (ALLOCATED(SURFACE(I)%PARTICLE_INSERT_CLOCK)) CALL GROW_R(SURFACE(I)%PARTICLE_INSERT_CLOCK,SURFACE(I)%PARTICLE_INSERT_CLOCK(1))
ENDDO
MESH_OBJ => BOX_OBJ(NM)
MESH_OBJ%N_NEIGHBORING_MESHES = 0   ! a fine box has no OMESH exchange
CALL IJK_TABLES(MESH_OBJ)
CALL INSERT_ALL_PARTICLES(T,NM)
MESH_OBJ => NULL()
CONTAINS
SUBROUTINE GROW_L(A)
LOGICAL, ALLOCATABLE :: A(:),B(:)
IF (SIZE(A)>=NM) RETURN
ALLOCATE(B(NM)) ; B = .FALSE. ; B(1:SIZE(A)) = A ; CALL MOVE_ALLOC(B,A)
END SUBROUTINE GROW_L
SUBROUTINE GROW_R(A,V)
REAL(EB), ALLOCATABLE :: A(:),B(:)
REAL(EB), INTENT(IN) :: V
REAL(EB) :: V0
IF (SIZE(A)>=NM) RETURN
V0 = V ; ALLOCATE(B(NM)) ; B = V0 ; B(1:SIZE(A)) = A ; CALL MOVE_ALLOC(B,A)
END SUBROUTINE GROW_R
END SUBROUTINE FDS_K_BED_INSERT

!> Particles of box NM (any level): count, and with N >= count X,Y,Z and PWT*MASS of each in BUF(4,*)
