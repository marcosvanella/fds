!> the 3-D/4-D field arrays through LB/UB already given in BOX indices). Walls/edges (W_*, E_*) use the WMATCH/EMATCH tables.
!> Region: the box indices LB:UB (or their intersection with the allocated bounds). Returns the number of elements loaded/compared, and
