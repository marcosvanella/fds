   CASE('ZZS') ; IF (ALLOCATED(M%ZZS)) P4=>M%ZZS
   CASE('DEL_RHO_D_DEL_Z') ; IF (ALLOCATED(M%DEL_RHO_D_DEL_Z)) P4=>M%DEL_RHO_D_DEL_Z
   CASE('SWORK4') ; IF (ALLOCATED(M%SWORK4)) P4=>M%SWORK4
   CASE('FX') ; IF (ALLOCATED(M%FX)) P4=>M%FX
   CASE('FY') ; IF (ALLOCATED(M%FY)) P4=>M%FY
   CASE('FZ') ; IF (ALLOCATED(M%FZ)) P4=>M%FZ
   CASE('DSUM') ; IF (ALLOCATED(DSUM)) CALL XSUM(DSUM) ; RETURN
   CASE('USUM') ; IF (ALLOCATED(USUM)) CALL XSUM(USUM) ; RETURN
   CASE('PSUM') ; IF (ALLOCATED(PSUM)) CALL XSUM(PSUM) ; RETURN
   CASE('PBAR') ; IF (ALLOCATED(M%PBAR)) P2=>M%PBAR
   CASE('PBAR_S') ; IF (ALLOCATED(M%PBAR_S)) P2=>M%PBAR_S
   CASE('D_PBAR_DT') ; IF (ALLOCATED(M%D_PBAR_DT)) P1=>M%D_PBAR_DT
   CASE('D_PBAR_DT_S') ; IF (ALLOCATED(M%D_PBAR_DT_S)) P1=>M%D_PBAR_DT_S
   CASE DEFAULT
      IF (NM_(1:2)=='W_') THEN ; CALL XFER_WALL(TRIM(NM_),MODE,DATA,NCNT,NBAD,IERR) ; RETURN ; ENDIF
      IF (NM_(1:2)=='E_') THEN ; CALL XFER_EDGE(TRIM(NM_),MODE,DATA,NCNT,NBAD,IERR) ; RETURN ; ENDIF
      IERR = 1 ; RETURN
END SELECT
IF (MODE==2) THEN   ! query: bounds of the allocation in LB/UB
   IERR = 2
   IF (ASSOCIATED(P3)) THEN ; LB(1:3)=LBOUND(P3) ; UB(1:3)=UBOUND(P3) ; IERR=0 ; ENDIF
   IF (ASSOCIATED(P4)) THEN ; LB(1:4)=LBOUND(P4) ; UB(1:4)=UBOUND(P4) ; IERR=0 ; ENDIF
   IF (ASSOCIATED(P2)) THEN ; LB(1:2)=LBOUND(P2) ; UB(1:2)=UBOUND(P2) ; IERR=0 ; ENDIF
   IF (ASSOCIATED(P1)) THEN ; LB(1:1)=LBOUND(P1) ; UB(1:1)=UBOUND(P1) ; IERR=0 ; ENDIF
   RETURN
ENDIF
IF (RNK==3 .AND. ASSOCIATED(P3)) THEN
   CALL X3(P3)
ELSEIF (RNK==4 .AND. ASSOCIATED(P4)) THEN
   CALL X4(P4)
ELSEIF (RNK==2 .AND. ASSOCIATED(P2)) THEN
   CALL X2(P2)
ELSEIF (RNK==1 .AND. ASSOCIATED(P1)) THEN
   CALL X1(P1)
ELSE
   IERR = 2   ! not allocated (or rank mismatch)
ENDIF

