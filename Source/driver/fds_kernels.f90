IF (ALLOCATED(MT(NM)%W)) DEALLOCATE(MT(NM)%W)
IF (ALLOCATED(MT(NM)%E)) DEALLOCATE(MT(NM)%E)
ALLOCATE(MT(NM)%W(NBW),MT(NM)%E(NBE))
MT(NM)%W = 0 ; MT(NM)%E = 0 ; MT(NM)%NWD = NW ; MT(NM)%NED = NE
DO IW=1,NBW
   ASSOCIATE (BC=>M%BOUNDARY_COORD(M%WALL(IW)%BC_INDEX))
   IF (IW<=NW) THEN   ! fast path: same order (box = whole dump mesh)
      IF (NINT(IOR(IW))==BC%IOR .AND. NINT(IIG(IW))==BC%IIG+OFF(1) .AND. NINT(JJG(IW))==BC%JJG+OFF(2) .AND. NINT(KKG(IW))==BC%KKG+OFF(3)) THEN
         MT(NM)%W(IW) = IW ; CYCLE
      ENDIF
   ENDIF
   DO K=1,NW
      IF (NINT(IOR(K))==BC%IOR .AND. NINT(IIG(K))==BC%IIG+OFF(1) .AND. NINT(JJG(K))==BC%JJG+OFF(2) .AND. NINT(KKG(K))==BC%KKG+OFF(3)) THEN
         MT(NM)%W(IW) = K ; EXIT
      ENDIF
   ENDDO
   END ASSOCIATE
ENDDO
DO IE=1,NBE
   IF (IE<=NE) THEN
      IF (NINT(IJKA(IE,1))==M%EDGE(IE)%I+OFF(1) .AND. NINT(IJKA(IE,2))==M%EDGE(IE)%J+OFF(2) .AND. NINT(IJKA(IE,3))==M%EDGE(IE)%K+OFF(3) &
          .AND. NINT(IJKA(IE,4))==M%EDGE(IE)%AXIS) THEN
         MT(NM)%E(IE) = IE ; CYCLE
      ENDIF
   ENDIF
   DO K=1,NE
      IF (NINT(IJKA(K,1))==M%EDGE(IE)%I+OFF(1) .AND. NINT(IJKA(K,2))==M%EDGE(IE)%J+OFF(2) .AND. NINT(IJKA(K,3))==M%EDGE(IE)%K+OFF(3) &
          .AND. NINT(IJKA(K,4))==M%EDGE(IE)%AXIS) THEN
         MT(NM)%E(IE) = K ; EXIT
      ENDIF
   ENDDO
ENDDO
END SUBROUTINE FDS_K_MATCH


!> Interface walls of a split (WMATCH=0): make their boundary data neutral, so that the wall-correction terms of the kernels vanish (the
!> single-mesh run has no wall there): UVW_SAVE = own face velocity, RHO_F/TMP_F/ZZ_F = the adjacent cell values, U_NORMAL(_S) from the face.
!> Returns the number of walls treated.
FUNCTION FDS_K_NEUTRALIZE(NM) BIND(C,NAME='fds_k_neutralize') RESULT(NN)
INTEGER(C_INT), VALUE :: NM
INTEGER(C_INT) :: NN
TYPE(MESH_TYPE), POINTER :: M
INTEGER :: IW
REAL(EB) :: UN
CALL FDS_HOOK_FINE_GUARD('fds_k_neutralize',NM,NMESHES)
M => MESHES(NM)
NN = 0
IF (.NOT.ALLOCATED(MT)) RETURN
IF (.NOT.ALLOCATED(MT(NM)%W)) RETURN
DO IW=1,M%N_EXTERNAL_WALL_CELLS
   IF (MT(NM)%W(IW)/=0) CYCLE
   NN = NN+1
   ASSOCIATE (BC=>M%BOUNDARY_COORD(M%WALL(IW)%BC_INDEX),B1=>M%BOUNDARY_PROP1(M%WALL(IW)%B1_INDEX))
   IF (PREDICTOR) THEN   ! DENSITY restores the face velocity U (predictor) or US (corrector) from UVW_SAVE (mass.f90:426, 598)
      SELECT CASE(BC%IOR)
         CASE( 1) ; UN = M%U(BC%IIG-1,BC%JJG,BC%KKG)
         CASE(-1) ; UN = M%U(BC%IIG  ,BC%JJG,BC%KKG)
         CASE( 2) ; UN = M%V(BC%IIG,BC%JJG-1,BC%KKG)
         CASE(-2) ; UN = M%V(BC%IIG,BC%JJG  ,BC%KKG)
         CASE( 3) ; UN = M%W(BC%IIG,BC%JJG,BC%KKG-1)
         CASE(-3) ; UN = M%W(BC%IIG,BC%JJG,BC%KKG  )
      END SELECT
   ELSE
      SELECT CASE(BC%IOR)
         CASE( 1) ; UN = M%US(BC%IIG-1,BC%JJG,BC%KKG)
         CASE(-1) ; UN = M%US(BC%IIG  ,BC%JJG,BC%KKG)
         CASE( 2) ; UN = M%VS(BC%IIG,BC%JJG-1,BC%KKG)
         CASE(-2) ; UN = M%VS(BC%IIG,BC%JJG  ,BC%KKG)
         CASE( 3) ; UN = M%WS(BC%IIG,BC%JJG,BC%KKG-1)
         CASE(-3) ; UN = M%WS(BC%IIG,BC%JJG,BC%KKG  )
      END SELECT
   ENDIF
   M%WALL(IW)%BOUNDARY_TYPE = NULL_BOUNDARY   ! in the single mesh this face is interior: no wall, so the kernels must skip it (they all CYCLE on NULL_BOUNDARY)
   M%CELL(M%CELL_INDEX(BC%IIG,BC%JJG,BC%KKG))%WALL_INDEX(-BC%IOR) = 0   ! and the cell face is not a wall face (DIVERGENCE_PART_1 tests CELL%WALL_INDEX==0)
   M%UVW_SAVE(IW) = UN
   B1%RHO_F = M%RHO(BC%IIG,BC%JJG,BC%KKG)
   B1%TMP_F = M%TMP(BC%IIG,BC%JJG,BC%KKG)
   B1%ZZ_F(1:N_TOTAL_SCALARS) = M%ZZ(BC%IIG,BC%JJG,BC%KKG,1:N_TOTAL_SCALARS)
   END ASSOCIATE
ENDDO
END FUNCTION FDS_K_NEUTRALIZE


!> Load (MODE=0), compare bitwise (MODE=1) or query the allocation bounds into LB/UB (MODE=2) of array NAME of box NM. DATA holds the dump array with bounds LB:UB (dump index space shifted by
!> OFF: box index I corresponds to dump index I+OFF in the dimensions with a cell/face index; the shift is applied by the caller for
!> the 3-D/4-D field arrays through LB/UB already given in BOX indices). Walls/edges (W_*, E_*) use the WMATCH/EMATCH tables.
!> Region: the box indices LB:UB (or their intersection with the allocated bounds). Returns the number of elements loaded/compared, and
!> NBAD = number of bitwise-different elements (MODE=1); IERR/=0: name unknown or array not allocated.
!> The elements of the region OMIT(1:3) (lower/upper cut, see the caller) are the caller's business: this routine treats LB:UB only.
SUBROUTINE FDS_K_XFER(NM,NAME,RNK,LB,UB,DATA,MODE,NCNT,NBAD,IERR) BIND(C,NAME='fds_k_xfer')
INTEGER(C_INT), VALUE :: NM,RNK,MODE
