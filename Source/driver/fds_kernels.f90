!> Make the FDS arrays that the kernels index by mesh number (DT_NEW, CHANGE_TIME_STEP_INDEX, EDGE_COUNT, CELL_COUNT*) large enough for mesh numbers up to NTOT, so that the kernels can run
!> on fine-level box numbers (NM > NMESHES, D-056 option B). Existing entries are kept; new ones are zero. Idempotent; the level-0 kernels are not affected.
SUBROUTINE FDS_K_RESERVE_BOXES(NTOT) BIND(C,NAME='fds_k_reserve_boxes')
INTEGER(C_INT), VALUE :: NTOT
REAL(EB), ALLOCATABLE :: R1(:)
REAL(EB), ALLOCATABLE :: R2(:,:)
LOGICAL, ALLOCATABLE :: L1(:)
INTEGER, ALLOCATABLE :: I1(:)
IF (.NOT.ALLOCATED(DT_NEW_K)) ALLOCATE(DT_NEW_K(NMESHES))
IF (SIZE(DT_NEW_K)<NTOT) THEN
   ALLOCATE(R1(NTOT)) ; R1 = 0._EB ; R1(1:SIZE(DT_NEW_K)) = DT_NEW_K ; CALL MOVE_ALLOC(R1,DT_NEW_K)
ENDIF
CALL GROW_I(CHANGE_TIME_STEP_INDEX,NTOT) ; CALL GROW_I(EDGE_COUNT,NTOT) ; CALL GROW_I(CELL_COUNT,NTOT)
CALL GROW_I(CELL_COUNT_INTEGERS,NTOT) ; CALL GROW_I(CELL_COUNT_LOGICALS,NTOT)
IF (UBOUND(RADF_COUNTER,1)<NTOT) THEN   ! COMPUTE_RADIATION reads RADF_COUNTER(NM) (RADF output clock) even when N_RADF=0; new boxes copy the first entry
   ALLOCATE(I1(LBOUND(RADF_COUNTER,1):NTOT)) ; I1 = RADF_COUNTER(LBOUND(RADF_COUNTER,1)) ; I1(:UBOUND(RADF_COUNTER,1)) = RADF_COUNTER ; CALL MOVE_ALLOC(I1,RADF_COUNTER)
ENDIF
IF (.NOT.ALLOCATED(RTE_BOX)) ALLOCATE(RTE_BOX(2,0))
IF (SIZE(RTE_BOX,2)<NTOT) THEN ; ALLOCATE(R2(2,NTOT)) ; R2 = 0._EB ; CALL MOVE_ALLOC(R2,RTE_BOX) ; ENDIF
IF (SIZE(RADIATION_COMPLETED)<NTOT) THEN   ! COMPUTE_RADIATION sets RADIATION_COMPLETED(NM)
   ALLOCATE(L1(NTOT)) ; L1 = .TRUE. ; L1(1:SIZE(RADIATION_COMPLETED)) = RADIATION_COMPLETED ; CALL MOVE_ALLOC(L1,RADIATION_COMPLETED)
ENDIF
END SUBROUTINE FDS_K_RESERVE_BOXES

SUBROUTINE GROW_I(A,N)
INTEGER, ALLOCATABLE, INTENT(INOUT) :: A(:)
INTEGER, INTENT(IN) :: N
INTEGER, ALLOCATABLE :: B(:)
IF (.NOT.ALLOCATED(A)) THEN ; ALLOCATE(A(N)) ; A = 0 ; RETURN ; ENDIF
IF (SIZE(A)>=N) RETURN
ALLOCATE(B(N)) ; B = 0 ; B(1:SIZE(A)) = A ; CALL MOVE_ALLOC(B,A)
END SUBROUTINE GROW_I

!> MODE 0: save EDGE%OMEGA, %TAU of mesh NM; MODE 1: put them back on the edges that have no other mesh (NOM_1 = NOM_2 = 0), so that a redo of the
!> boundary conditions changes only the mesh-interface edges (the solid and vegetation-drag edges keep FDS's own initial values).
SUBROUTINE FDS_K_EDGE_KEEP(NM,MODE) BIND(C,NAME='fds_k_edge_keep')
INTEGER(C_INT), VALUE :: NM,MODE
INTEGER :: IE,NE
LOGICAL :: CORNER
TYPE(MESH_TYPE), POINTER :: M
TYPE(EDGE_TYPE), POINTER :: ED
M => MESHES(NM)
IF (.NOT.ALLOCATED(M%EDGE)) RETURN
NE = UBOUND(M%EDGE,1)   ! EDGE(0:N): entries 1..N (SIZE overran by one)
IF (.NOT.ALLOCATED(EK)) ALLOCATE(EK(NMESHES))
IF (MODE==0) THEN
   IF (ALLOCATED(EK(NM)%OM)) DEALLOCATE(EK(NM)%OM,EK(NM)%TA)
   ALLOCATE(EK(NM)%OM(-2:2,NE),EK(NM)%TA(-2:2,NE))
   DO IE=1,NE ; EK(NM)%OM(:,IE) = M%EDGE(IE)%OMEGA ; EK(NM)%TA(:,IE) = M%EDGE(IE)%TAU ; ENDDO
ELSE
   IF (.NOT.ALLOCATED(EK(NM)%OM)) RETURN
   DO IE=1,NE
      ED => M%EDGE(IE)
      IF (ED%NOM_1/=0 .AND. ED%NOM_2/=0) CYCLE
      IF (ED%NOM_1/=0 .OR. ED%NOM_2/=0) THEN   ! an interface edge keeps its data only where it is also on the ground or a wall (mesh corner)
         SELECT CASE(ED%AXIS)
            CASE(1) ; CORNER = (ED%J==0 .OR. ED%J==M%JBAR) .AND. (ED%K==0 .OR. ED%K==M%KBAR)
            CASE(2) ; CORNER = (ED%I==0 .OR. ED%I==M%IBAR) .AND. (ED%K==0 .OR. ED%K==M%KBAR)
            CASE DEFAULT ; CORNER = (ED%I==0 .OR. ED%I==M%IBAR) .AND. (ED%J==0 .OR. ED%J==M%JBAR)
         END SELECT
         IF (.NOT.CORNER) CYCLE
      ENDIF
      M%EDGE(IE)%OMEGA = EK(NM)%OM(:,IE) ; M%EDGE(IE)%TAU = EK(NM)%TA(:,IE)
   ENDDO
   DEALLOCATE(EK(NM)%OM,EK(NM)%TA)
ENDIF
END SUBROUTINE FDS_K_EDGE_KEEP

