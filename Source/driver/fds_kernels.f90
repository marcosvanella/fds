M => MESHES(NM)
NBW = M%N_EXTERNAL_WALL_CELLS+M%N_INTERNAL_WALL_CELLS
NBE = UBOUND(M%EDGE,1)   ! EDGE is allocated (0:N1): SIZE would run one past the last edge
