   IDX = (I-LB(1)) + E1*((J-LB(2)) + E2*((K-LB(3)) + E3*(L-LB(4)))) + 1
   IF (I<LBOUND(P,1) .OR. I>UBOUND(P,1) .OR. J<LBOUND(P,2) .OR. J>UBOUND(P,2) .OR. K<LBOUND(P,3) .OR. K>UBOUND(P,3) .OR. &
       L<LBOUND(P,4) .OR. L>UBOUND(P,4)) THEN ; IERR = 3 ; RETURN ; ENDIF
   NCNT = NCNT+1
   IF (MODE==MODE_LOAD) THEN ; P(I,J,K,L) = DATA(IDX) ; ELSEIF (MODE==MODE_READ) THEN ; DATA(IDX) = P(I,J,K,L) ; ELSE ; IF (DIFF(P(I,J,K,L),DATA(IDX))) THEN ; NBAD = NBAD+1 ; IF (NBAD<=8 .AND. VERBOSE_DIFF) WRITE(0,'(A,4I4,2ES24.16)') '   first difference at',I,J,K,L,P(I,J,K,L),DATA(IDX) ; ENDIF ; ENDIF
ENDDO ; ENDDO ; ENDDO ; ENDDO
END SUBROUTINE X4

