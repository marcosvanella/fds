INTEGER(C_INT), INTENT(OUT) :: IERR
TYPE(MESH_TYPE), POINTER :: M
REAL(EB), POINTER :: P1(:),P2(:,:),P3(:,:,:),P4(:,:,:,:)
REAL(EB), ALLOCATABLE, TARGET :: TE2(:,:),TE4(:,:,:,:)   ! flat edge tables for the WP1b dump (CE_EDGE_INDEX, ED_OMEGA, ED_TAU)
INTEGER :: I,IE_,IC_,KE_,JE_,IEL
CHARACTER(LEN=32) :: NM_
CALL FDS_HOOK_FINE_GUARD('fds_k_xfer',NM,NMESHES)
NCNT = 0 ; NBAD = 0 ; IERR = 0
M => MESHES(NM)
NM_ = ' '
DO I=1,32
   IF (NAME(I)==C_NULL_CHAR) EXIT
   NM_(I:I) = NAME(I)
ENDDO
NULLIFY(P1,P2,P3,P4)
SELECT CASE(TRIM(NM_))
   CASE('RHO') ; IF (ALLOCATED(M%RHO)) P3=>M%RHO
   CASE('RHOS') ; IF (ALLOCATED(M%RHOS)) P3=>M%RHOS
   CASE('TMP') ; IF (ALLOCATED(M%TMP)) P3=>M%TMP
   CASE('U') ; IF (ALLOCATED(M%U)) P3=>M%U
   CASE('V') ; IF (ALLOCATED(M%V)) P3=>M%V
   CASE('W') ; IF (ALLOCATED(M%W)) P3=>M%W
   CASE('US') ; IF (ALLOCATED(M%US)) P3=>M%US
   CASE('VS') ; IF (ALLOCATED(M%VS)) P3=>M%VS
   CASE('WS') ; IF (ALLOCATED(M%WS)) P3=>M%WS
   CASE('H') ; IF (ALLOCATED(M%H)) P3=>M%H
   CASE('HS') ; IF (ALLOCATED(M%HS)) P3=>M%HS
   CASE('KRES') ; IF (ALLOCATED(M%KRES)) P3=>M%KRES
   CASE('D') ; IF (ALLOCATED(M%D)) P3=>M%D
   CASE('DS') ; IF (ALLOCATED(M%DS)) P3=>M%DS
   CASE('DDDT') ; IF (ALLOCATED(M%DDDT)) P3=>M%DDDT
   CASE('MU') ; IF (ALLOCATED(M%MU)) P3=>M%MU
   CASE('MU_DNS') ; IF (ALLOCATED(M%MU_DNS)) P3=>M%MU_DNS
   CASE('RSUM') ; IF (ALLOCATED(M%RSUM)) P3=>M%RSUM
   CASE('FVX') ; IF (ALLOCATED(M%FVX)) P3=>M%FVX
   CASE('FVY') ; IF (ALLOCATED(M%FVY)) P3=>M%FVY
   CASE('FVZ') ; IF (ALLOCATED(M%FVZ)) P3=>M%FVZ
   CASE('STRAIN_RATE') ; IF (ALLOCATED(M%STRAIN_RATE)) P3=>M%STRAIN_RATE
   CASE('D_Z_MAX') ; IF (ALLOCATED(M%D_Z_MAX)) P3=>M%D_Z_MAX
   CASE('WORK1') ; IF (ALLOCATED(M%WORK1)) P3=>M%WORK1
   CASE('WORK2') ; IF (ALLOCATED(M%WORK2)) P3=>M%WORK2
   CASE('WORK3') ; IF (ALLOCATED(M%WORK3)) P3=>M%WORK3
   CASE('WORK4') ; IF (ALLOCATED(M%WORK4)) P3=>M%WORK4
   CASE('WORK5') ; IF (ALLOCATED(M%WORK5)) P3=>M%WORK5
   CASE('WORK6') ; IF (ALLOCATED(M%WORK6)) P3=>M%WORK6
   CASE('WORK7') ; IF (ALLOCATED(M%WORK7)) P3=>M%WORK7
   CASE('WORK8') ; IF (ALLOCATED(M%WORK8)) P3=>M%WORK8
   CASE('WORK9') ; IF (ALLOCATED(M%WORK9)) P3=>M%WORK9
   CASE('SWORK1') ; IF (ALLOCATED(M%SWORK1)) P4=>M%SWORK1
   CASE('SWORK2') ; IF (ALLOCATED(M%SWORK2)) P4=>M%SWORK2
   CASE('SWORK3') ; IF (ALLOCATED(M%SWORK3)) P4=>M%SWORK3
   CASE('RDX') ; IF (ALLOCATED(M%RDX)) P1=>M%RDX
   CASE('RDY') ; IF (ALLOCATED(M%RDY)) P1=>M%RDY
   CASE('RDZ') ; IF (ALLOCATED(M%RDZ)) P1=>M%RDZ
   CASE('RDXN') ; IF (ALLOCATED(M%RDXN)) P1=>M%RDXN
   CASE('RDYN') ; IF (ALLOCATED(M%RDYN)) P1=>M%RDYN
   CASE('RDZN') ; IF (ALLOCATED(M%RDZN)) P1=>M%RDZN
   CASE('R') ; IF (ALLOCATED(M%R)) P1=>M%R
   CASE('RRN') ; IF (ALLOCATED(M%RRN)) P1=>M%RRN
   CASE('MU_RSQMW_Z') ; IF (ALLOCATED(MU_RSQMW_Z)) CALL XT2(MU_RSQMW_Z) ; RETURN
   CASE('K_RSQMW_Z') ; IF (ALLOCATED(K_RSQMW_Z)) CALL XT2(K_RSQMW_Z) ; RETURN
   CASE('CP_Z') ; IF (ALLOCATED(CP_Z)) CALL XT2(CP_Z) ; RETURN
   CASE('H_SENS_Z') ; IF (ALLOCATED(H_SENS_Z)) CALL XT2(H_SENS_Z) ; RETURN
   CASE('RSQ_MW_Z') ; IF (ALLOCATED(RSQ_MW_Z)) CALL XT1(RSQ_MW_Z) ; RETURN
   CASE('MW') ; CALL XMW ; RETURN   ! SPECIES_MIXTURE(1:N_SPECIES)%MW (read or compare only)
   CASE('MWR_Z') ; IF (ALLOCATED(MWR_Z)) CALL XT1(MWR_Z) ; RETURN
   CASE('ED_OMEGA','ED_TAU')   ! EDGE(IE)%OMEGA / %TAU (-2:2) flattened to (0:NEDGE,-2:2); NEDGE = UBOUND(EDGE)
      IF (ALLOCATED(M%EDGE)) THEN
         ALLOCATE(TE2(LBOUND(M%EDGE,1):UBOUND(M%EDGE,1),-2:2))
         DO IE_=LBOUND(M%EDGE,1),UBOUND(M%EDGE,1)
            IF (TRIM(NM_)=='ED_OMEGA') THEN ; TE2(IE_,:)=M%EDGE(IE_)%OMEGA(:) ; ELSE ; TE2(IE_,:)=M%EDGE(IE_)%TAU(:) ; ENDIF
