END SUBROUTINE CMPONLY

!> wall arrays: DATA is the dump array (length NWD, or NWD x NS for W_ZZ_F, W_RHO_D_F, W_RHO_D_DZDN_F); only walls with a counterpart
SUBROUTINE XFER_WALL(NAME_W,MODE_W,DATA_W,NC,NB,IE)
CHARACTER(*), INTENT(IN) :: NAME_W
INTEGER, INTENT(IN) :: MODE_W
REAL(C_DOUBLE), INTENT(INOUT) :: DATA_W(*)
INTEGER(C_LONG), INTENT(INOUT) :: NC,NB
INTEGER(C_INT), INTENT(INOUT) :: IE
INTEGER :: IW,KD,N,NSC
REAL(EB) :: V
LOGICAL :: PER_SCALAR
IF (.NOT.ALLOCATED(MT)) THEN ; IE = 4 ; RETURN ; ENDIF
IF (.NOT.ALLOCATED(MT(NM)%W)) THEN ; IE = 4 ; RETURN ; ENDIF
NSC = N_TOTAL_SCALARS
PER_SCALAR = (NAME_W=='W_ZZ_F' .OR. NAME_W=='W_RHO_D_F' .OR. NAME_W=='W_RHO_D_DZDN_F')
DO IW=1,SIZE(MT(NM)%W)
   KD = MT(NM)%W(IW)
   IF (KD==0) CYCLE
   ASSOCIATE (BC=>M%BOUNDARY_COORD(M%WALL(IW)%BC_INDEX),B1=>M%BOUNDARY_PROP1(M%WALL(IW)%B1_INDEX))
   IF (PER_SCALAR) THEN
      DO N=1,NSC
         SELECT CASE(NAME_W)
            CASE('W_ZZ_F') ; CALL ONE(B1%ZZ_F(N),DATA_W(KD+MT(NM)%NWD*(N-1)))
            CASE('W_RHO_D_F') ; CALL ONE(B1%RHO_D_F(N),DATA_W(KD+MT(NM)%NWD*(N-1)))
            CASE('W_RHO_D_DZDN_F') ; CALL ONE(B1%RHO_D_DZDN_F(N),DATA_W(KD+MT(NM)%NWD*(N-1)))
         END SELECT
      ENDDO
   ELSE
      SELECT CASE(NAME_W)
         CASE('W_UVW_SAVE') ; IF (IW<=M%N_EXTERNAL_WALL_CELLS) CALL ONE(M%UVW_SAVE(IW),DATA_W(KD))
         CASE('W_U_NORMAL') ; CALL ONE(B1%U_NORMAL,DATA_W(KD))
         CASE('W_U_NORMAL_S') ; CALL ONE(B1%U_NORMAL_S,DATA_W(KD))
         CASE('W_RHO_F') ; CALL ONE(B1%RHO_F,DATA_W(KD))
         CASE('W_TMP_F') ; CALL ONE(B1%TMP_F,DATA_W(KD))
         CASE('W_K_G') ; CALL ONE(B1%K_G,DATA_W(KD))
         CASE('W_Q_CON_F') ; CALL ONE(B1%Q_CON_F,DATA_W(KD))
         CASE('W_Q_LEAK') ; CALL ONE(B1%Q_LEAK,DATA_W(KD))
         CASE('W_U_GHOST') ; IF (IW<=M%N_EXTERNAL_WALL_CELLS) CALL ONE(M%U_GHOST(IW),DATA_W(KD))
         CASE('W_V_GHOST') ; IF (IW<=M%N_EXTERNAL_WALL_CELLS) CALL ONE(M%V_GHOST(IW),DATA_W(KD))
         CASE('W_W_GHOST') ; IF (IW<=M%N_EXTERNAL_WALL_CELLS) CALL ONE(M%W_GHOST(IW),DATA_W(KD))
         CASE('W_IOR') ; V = REAL(BC%IOR,EB) ; CALL CMPONLY(V,DATA_W(KD))
         CASE('W_IIG','W_JJG','W_KKG') ; CONTINUE   ! identification only (shifted by the box origin in a split)
         CASE DEFAULT ; IE = 5 ; RETURN
      END SELECT
   ENDIF
   END ASSOCIATE
ENDDO
END SUBROUTINE XFER_WALL

!> edge arrays: E_OMEGA, E_TAU (NED x 5, index -2..2 in columns 1..5)
SUBROUTINE XFER_EDGE(NAME_E,MODE_E,DATA_E,NC,NB,IE)
CHARACTER(*), INTENT(IN) :: NAME_E
INTEGER, INTENT(IN) :: MODE_E
REAL(C_DOUBLE), INTENT(INOUT) :: DATA_E(*)
INTEGER(C_LONG), INTENT(INOUT) :: NC,NB
INTEGER(C_INT), INTENT(INOUT) :: IE
INTEGER :: IED,KD,L
IF (.NOT.ALLOCATED(MT)) THEN ; IE = 4 ; RETURN ; ENDIF
IF (.NOT.ALLOCATED(MT(NM)%E)) THEN ; IE = 4 ; RETURN ; ENDIF
IF (NAME_E=='E_IJKA') RETURN
IF (NAME_E/='E_OMEGA' .AND. NAME_E/='E_TAU') THEN ; IE = 5 ; RETURN ; ENDIF
IF (MODE_E==MODE_LOAD) THEN   ! start from the FDS default (unset) so that edges without a counterpart stay "unset"
   DO IED=1,SIZE(MT(NM)%E)
      IF (NAME_E=='E_OMEGA') THEN ; M%EDGE(IED)%OMEGA = -1.E6_EB ; ELSE ; M%EDGE(IED)%TAU = -1.E6_EB ; ENDIF
   ENDDO
ENDIF
DO IED=1,SIZE(MT(NM)%E)
   KD = MT(NM)%E(IED)
   IF (KD==0) CYCLE
   DO L=-2,2
      NC = NC+1
      IF (NAME_E=='E_OMEGA') THEN
         IF (MODE_E==MODE_LOAD) THEN ; M%EDGE(IED)%OMEGA(L) = DATA_E(KD+MT(NM)%NED*(L+2)) ; ELSEIF (DIFF(M%EDGE(IED)%OMEGA(L),DATA_E(KD+MT(NM)%NED*(L+2)))) THEN ; NB = NB+1 ; ENDIF
      ELSE
         IF (MODE_E==MODE_LOAD) THEN ; M%EDGE(IED)%TAU(L) = DATA_E(KD+MT(NM)%NED*(L+2)) ; ELSEIF (DIFF(M%EDGE(IED)%TAU(L),DATA_E(KD+MT(NM)%NED*(L+2)))) THEN ; NB = NB+1 ; ENDIF
      ENDIF
   ENDDO
ENDDO
END SUBROUTINE XFER_EDGE

