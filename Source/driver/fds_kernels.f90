   BUF(:,IP) = [M%BOUNDARY_COORD(LP%BC_INDEX)%X,M%BOUNDARY_COORD(LP%BC_INDEX)%Y,M%BOUNDARY_COORD(LP%BC_INDEX)%Z,LP%PWT*LP%MASS]
