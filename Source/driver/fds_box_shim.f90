   CASE(15) ; P3 => MP_RHO
   CASE(16) ; P3 => MP_RHOS
   CASE(17) ; P3 => MP_MU
   CASE(18) ; P3 => MP_TMP
   CASE(19) ; P3 => MP_Q
   CASE(20) ; P3 => MP_RSUM
   CASE(21) ; P4 => MP_ZZ
   CASE(22) ; P4 => MP_ZZS
   CASE DEFAULT ; IERR = 1 ; RETURN
END SELECT
IF (WHICH<21) THEN
   IF (.NOT.ASSOCIATED(P3)) THEN ; IERR = 3 ; RETURN ; ENDIF
   LB(1:3) = LBOUND(P3) ; UB(1:3) = UBOUND(P3)
   IF (DOSET/=0) THEN ; P3(I,J,K) = VAL ; ELSE ; VAL = P3(I,J,K) ; ENDIF
   ADDR = C_LOC(P3(I,J,K))
ELSE
   IF (.NOT.ASSOCIATED(P4)) THEN ; IERR = 3 ; RETURN ; ENDIF
   LB = LBOUND(P4) ; UB = UBOUND(P4)
   IF (DOSET/=0) THEN ; P4(I,J,K,N) = VAL ; ELSE ; VAL = P4(I,J,K,N) ; ENDIF
   ADDR = C_LOC(P4(I,J,K,N))
ENDIF
END FUNCTION FDS_SHIM_BV_ACCESS

!> \brief 1 when the MESH_POINTERS pointer of field WHICH (3-D fields, FDS_HOOK_SET_VIEW numbering) after POINT_TO_BOX(NM) is the very array MESHES(NM)%X
!> (a field without a view keeps the POINT_TO_MESH target), 0 when it is not, -1 for an unknown field or box.
FUNCTION FDS_SHIM_BV_IS_MESH(NM,WHICH) BIND(C,NAME='fds_shim_bv_is_mesh') RESULT(IS)
INTEGER(C_INT), VALUE :: NM,WHICH
INTEGER(C_INT) :: IS
TYPE(MESH_TYPE), POINTER :: M
IS = -1
IF (NM<1 .OR. NM>NMESHES) RETURN
M => MESHES(NM)
CALL POINT_TO_BOX(NM)
SELECT CASE(WHICH)
   CASE( 1) ; IS = MERGE(1,0,ASSOCIATED(MP_U,M%U))
   CASE( 7) ; IS = MERGE(1,0,ASSOCIATED(MP_D,M%D))
   CASE( 9) ; IS = MERGE(1,0,ASSOCIATED(MP_H,M%H))
   CASE(15) ; IS = MERGE(1,0,ASSOCIATED(MP_RHO,M%RHO))
   CASE(18) ; IS = MERGE(1,0,ASSOCIATED(MP_TMP,M%TMP))
END SELECT
END FUNCTION FDS_SHIM_BV_IS_MESH

