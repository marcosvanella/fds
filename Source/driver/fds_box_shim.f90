IERR = 0
ADDR = C_NULL_PTR
IF (NM<1 .OR. NM>NMESHES) THEN ; IERR = 2 ; RETURN ; ENDIF
M => MESHES(NM)
SELECT CASE(TRIM(CSTR(NAME)))
   CASE('RHO')
