! Write-only reference dump for the S3 kernel checks (scratch build of UNPATCHED FDS, outside src). Format: Source/driver/README.md.
! Hooks: REFDUMP_BEGIN(kernel) before and REFDUMP_END(kernel) after a kernel call; REFDUMP_STEP once per time step.
! Nothing in the FDS state is modified except in REFDUMP_STRESS, which restores every array it touches.
MODULE REFDUMP
USE PRECISION_PARAMETERS
USE MESH_VARIABLES
USE GLOBAL_CONSTANTS
IMPLICIT NONE
PRIVATE
PUBLIC :: REFDUMP_INIT,REFDUMP_BEGIN,REFDUMP_END,REFDUMP_STEP,REFDUMP_PASS,REFDUMP_FINISH,REFDUMP_ACTIVE
INTEGER, PARAMETER :: MAXA=80
TYPE ARR_T
   CHARACTER(16) :: NAME=' '
   INTEGER :: RANK=0,LB(4)=0,UB(4)=0
   REAL(EB), ALLOCATABLE :: D(:)
END TYPE
TYPE(ARR_T) :: BEF(MAXA),AFT(MAXA)
INTEGER :: NB=0,NA=0,LU=91,NREC=0
INTEGER, PARAMETER :: MAXM=64
INTEGER :: NREC_M(MAXM)=0
LOGICAL :: OPENED(MAXM)=.FALSE.
CHARACTER(256) :: FNAME=' '
INTEGER :: CURM=1
LOGICAL :: ON=.FALSE.,INIT_DONE=.FALSE.,STRESS=.FALSE.
INTEGER :: STEPS(64)=-1,NSTEPS=0
CHARACTER(16) :: KNAME=' '
REAL(EB) :: KT,KDT,KRMIN,KRMAX
INTEGER :: KVAR=0,KPRED=0,KFIRST=0,NPASS_CUR=0
CONTAINS

LOGICAL FUNCTION REFDUMP_ACTIVE()
REFDUMP_ACTIVE = ON
END FUNCTION

SUBROUTINE REFDUMP_INIT
CHARACTER(256) :: S,FN
INTEGER :: ST,I,J,K
IF (INIT_DONE) RETURN
INIT_DONE = .TRUE.
CALL GET_ENVIRONMENT_VARIABLE('FDSREF_FILE',FN,STATUS=ST)
IF (ST/=0) RETURN
CALL GET_ENVIRONMENT_VARIABLE('FDSREF_STEPS',S,STATUS=ST)   ! comma separated ICYC list (default 3)
IF (ST/=0) S='2,3'
K=1 ; NSTEPS=0
DO I=1,LEN_TRIM(S)+1
   IF (I>LEN_TRIM(S) .OR. S(I:I)==',') THEN
      IF (I>K) THEN ; NSTEPS=NSTEPS+1 ; READ(S(K:I-1),*) STEPS(NSTEPS) ; ENDIF
      K=I+1
   ENDIF
ENDDO
CALL GET_ENVIRONMENT_VARIABLE('FDSREF_STRESS',S,STATUS=ST)
STRESS = (ST==0)
CALL GET_ENVIRONMENT_VARIABLE('FDSREF_RHOMIN',S,STATUS=ST)   ! optional override of the density clip limits (clip stress reference)
IF (ST==0) READ(S,*) RHOMIN
CALL GET_ENVIRONMENT_VARIABLE('FDSREF_RHOMAX',S,STATUS=ST)
IF (ST==0) READ(S,*) RHOMAX
ON = .TRUE.
FNAME=FN
END SUBROUTINE

SUBROUTINE OPEN_MESH(NM)
INTEGER, INTENT(IN) :: NM
CHARACTER(256) :: FN
INTEGER :: J
CURM=NM ; LU=100+NM
IF (OPENED(NM)) RETURN
OPENED(NM)=.TRUE.
FN=TRIM(FNAME) ; IF (NM>1) WRITE(FN,'(A,A,I0)') TRIM(FNAME),'.',NM
OPEN(LU,FILE=TRIM(FN),FORM='UNFORMATTED',ACCESS='STREAM',STATUS='REPLACE')
WRITE(LU) 'FDSDUMP1'
J=0 ; WRITE(LU) J   ! number of records, patched at the end
END SUBROUTINE

LOGICAL FUNCTION WANT(NM)
INTEGER, INTENT(IN) :: NM
WANT = ON .AND. NM<=MAXM .AND. ANY(STEPS(1:NSTEPS)==ICYC)
END FUNCTION

SUBROUTINE PUT(LIST,N,NAME,RANK,LB,UB,SRC)
TYPE(ARR_T), INTENT(INOUT) :: LIST(MAXA)
INTEGER, INTENT(INOUT) :: N
CHARACTER(*), INTENT(IN) :: NAME
INTEGER, INTENT(IN) :: RANK,LB(4),UB(4)
REAL(EB), INTENT(IN) :: SRC(*)
INTEGER :: NN,I
N=N+1 ; LIST(N)%NAME=NAME ; LIST(N)%RANK=RANK ; LIST(N)%LB=LB ; LIST(N)%UB=UB
NN=1 ; DO I=1,RANK ; NN=NN*(UB(I)-LB(I)+1) ; ENDDO
IF (ALLOCATED(LIST(N)%D)) DEALLOCATE(LIST(N)%D)
ALLOCATE(LIST(N)%D(NN)) ; LIST(N)%D = SRC(1:NN)
END SUBROUTINE

SUBROUTINE SNAP(LIST,N,NM)
INTEGER, INTENT(IN) :: NM
TYPE(ARR_T), INTENT(INOUT) :: LIST(MAXA)
INTEGER, INTENT(OUT) :: N
TYPE(MESH_TYPE), POINTER :: M
INTEGER :: IW,NW,NS,I
REAL(EB), ALLOCATABLE :: TMPW(:),TMPW2(:,:),TMPE(:,:)
INTEGER :: NE,K
N=0
M=>MESHES(NM)
IF (ALLOCATED(M%RHO)) CALL PUT(LIST,N,'RHO',3,[LBOUND(M%RHO),1],[UBOUND(M%RHO),1],M%RHO)
IF (ALLOCATED(M%RHOS)) CALL PUT(LIST,N,'RHOS',3,[LBOUND(M%RHOS),1],[UBOUND(M%RHOS),1],M%RHOS)
IF (ALLOCATED(M%TMP)) CALL PUT(LIST,N,'TMP',3,[LBOUND(M%TMP),1],[UBOUND(M%TMP),1],M%TMP)
IF (ALLOCATED(M%U)) CALL PUT(LIST,N,'U',3,[LBOUND(M%U),1],[UBOUND(M%U),1],M%U)
IF (ALLOCATED(M%V)) CALL PUT(LIST,N,'V',3,[LBOUND(M%V),1],[UBOUND(M%V),1],M%V)
IF (ALLOCATED(M%W)) CALL PUT(LIST,N,'W',3,[LBOUND(M%W),1],[UBOUND(M%W),1],M%W)
IF (ALLOCATED(M%US)) CALL PUT(LIST,N,'US',3,[LBOUND(M%US),1],[UBOUND(M%US),1],M%US)
IF (ALLOCATED(M%VS)) CALL PUT(LIST,N,'VS',3,[LBOUND(M%VS),1],[UBOUND(M%VS),1],M%VS)
IF (ALLOCATED(M%WS)) CALL PUT(LIST,N,'WS',3,[LBOUND(M%WS),1],[UBOUND(M%WS),1],M%WS)
IF (ALLOCATED(M%H)) CALL PUT(LIST,N,'H',3,[LBOUND(M%H),1],[UBOUND(M%H),1],M%H)
IF (ALLOCATED(M%HS)) CALL PUT(LIST,N,'HS',3,[LBOUND(M%HS),1],[UBOUND(M%HS),1],M%HS)
IF (ALLOCATED(M%KRES)) CALL PUT(LIST,N,'KRES',3,[LBOUND(M%KRES),1],[UBOUND(M%KRES),1],M%KRES)
IF (ALLOCATED(M%D)) CALL PUT(LIST,N,'D',3,[LBOUND(M%D),1],[UBOUND(M%D),1],M%D)
IF (ALLOCATED(M%DS)) CALL PUT(LIST,N,'DS',3,[LBOUND(M%DS),1],[UBOUND(M%DS),1],M%DS)
IF (ALLOCATED(M%DDDT)) CALL PUT(LIST,N,'DDDT',3,[LBOUND(M%DDDT),1],[UBOUND(M%DDDT),1],M%DDDT)
IF (ALLOCATED(M%MU)) CALL PUT(LIST,N,'MU',3,[LBOUND(M%MU),1],[UBOUND(M%MU),1],M%MU)
IF (ALLOCATED(M%MU_DNS)) CALL PUT(LIST,N,'MU_DNS',3,[LBOUND(M%MU_DNS),1],[UBOUND(M%MU_DNS),1],M%MU_DNS)
IF (ALLOCATED(M%RSUM)) CALL PUT(LIST,N,'RSUM',3,[LBOUND(M%RSUM),1],[UBOUND(M%RSUM),1],M%RSUM)
IF (ALLOCATED(M%FVX)) CALL PUT(LIST,N,'FVX',3,[LBOUND(M%FVX),1],[UBOUND(M%FVX),1],M%FVX)
IF (ALLOCATED(M%FVY)) CALL PUT(LIST,N,'FVY',3,[LBOUND(M%FVY),1],[UBOUND(M%FVY),1],M%FVY)
IF (ALLOCATED(M%FVZ)) CALL PUT(LIST,N,'FVZ',3,[LBOUND(M%FVZ),1],[UBOUND(M%FVZ),1],M%FVZ)
CALL PUT(LIST,N,'CLIPFL',1,[0,1,1,1],[0,1,1,1],[REAL(MERGE(1,0,M%CLIP_RHOMIN)+MERGE(2,0,M%CLIP_RHOMAX),EB)])   ! per-mesh clip flags (bit0 MIN, bit1 MAX)
CALL PUT(LIST,N,'DTRC',1,[0,1,1,1],[0,1,1,1],[REAL(M%DT_RESTRICT_COUNT,EB)])   ! DT_RESTRICT_COUNT of the mesh
IF (N_ZONE>0 .AND. ALLOCATED(DSUM)) THEN   ! zone sums of the divergence (global, already summed over meshes/ranks when DIV2 runs)
   CALL PUT(LIST,N,'DSUM',1,[1,1,1,1],[N_ZONE,1,1,1],DSUM)
   CALL PUT(LIST,N,'USUM',1,[1,1,1,1],[N_ZONE,1,1,1],USUM)
   CALL PUT(LIST,N,'PSUM',1,[1,1,1,1],[N_ZONE,1,1,1],PSUM)
ENDIF
IF (ALLOCATED(M%WORK1)) CALL PUT(LIST,N,'WORK1',3,[LBOUND(M%WORK1),1],[UBOUND(M%WORK1),1],M%WORK1)   ! scratch read whole-array by DIVERGENCE_PART_2 (DDDT ghosts)
IF (ALLOCATED(M%D_Z_MAX)) CALL PUT(LIST,N,'D_Z_MAX',3,[LBOUND(M%D_Z_MAX),1],[UBOUND(M%D_Z_MAX),1],M%D_Z_MAX)
IF (ALLOCATED(M%STRAIN_RATE)) CALL PUT(LIST,N,'STRAIN_RATE',3,[LBOUND(M%STRAIN_RATE),1],[UBOUND(M%STRAIN_RATE),1],M%STRAIN_RATE)
IF (ALLOCATED(M%ZZ)) CALL PUT(LIST,N,'ZZ',4,LBOUND(M%ZZ),UBOUND(M%ZZ),M%ZZ)
IF (ALLOCATED(M%ZZS)) CALL PUT(LIST,N,'ZZS',4,LBOUND(M%ZZS),UBOUND(M%ZZS),M%ZZS)
IF (ALLOCATED(M%DEL_RHO_D_DEL_Z)) CALL PUT(LIST,N,'DEL_RHO_D_DEL_Z',4,LBOUND(M%DEL_RHO_D_DEL_Z),UBOUND(M%DEL_RHO_D_DEL_Z),M%DEL_RHO_D_DEL_Z)
IF (ALLOCATED(M%SWORK4)) CALL PUT(LIST,N,'SWORK4',4,LBOUND(M%SWORK4),UBOUND(M%SWORK4),M%SWORK4)
IF (ALLOCATED(M%FX)) CALL PUT(LIST,N,'FX',4,LBOUND(M%FX),UBOUND(M%FX),M%FX)
IF (ALLOCATED(M%FY)) CALL PUT(LIST,N,'FY',4,LBOUND(M%FY),UBOUND(M%FY),M%FY)
IF (ALLOCATED(M%FZ)) CALL PUT(LIST,N,'FZ',4,LBOUND(M%FZ),UBOUND(M%FZ),M%FZ)
IF (ALLOCATED(M%PBAR))      CALL PUT(LIST,N,'PBAR',2,[LBOUND(M%PBAR),1,1],[UBOUND(M%PBAR),1,1],M%PBAR)
IF (ALLOCATED(M%PBAR_S))    CALL PUT(LIST,N,'PBAR_S',2,[LBOUND(M%PBAR_S),1,1],[UBOUND(M%PBAR_S),1,1],M%PBAR_S)
IF (ALLOCATED(M%D_PBAR_DT)) CALL PUT(LIST,N,'D_PBAR_DT',1,[LBOUND(M%D_PBAR_DT),1,1,1],[UBOUND(M%D_PBAR_DT),1,1,1],M%D_PBAR_DT)
IF (ALLOCATED(M%D_PBAR_DT_S)) CALL PUT(LIST,N,'D_PBAR_DT_S',1,[LBOUND(M%D_PBAR_DT_S),1,1,1],[UBOUND(M%D_PBAR_DT_S),1,1,1],M%D_PBAR_DT_S)
! wall data (one entry per WALL cell)
NW=M%N_EXTERNAL_WALL_CELLS+M%N_INTERNAL_WALL_CELLS ; NS=N_TOTAL_SCALARS
IF (NW>0) THEN
   ALLOCATE(TMPW(NW),TMPW2(NW,NS))
   TMPW = [(M%UVW_SAVE(MIN(I,M%N_EXTERNAL_WALL_CELLS)),I=1,NW)] ; IF (M%N_EXTERNAL_WALL_CELLS==0) TMPW=0._EB
   CALL PUT(LIST,N,'W_UVW_SAVE',1,[1,1,1,1],[NW,1,1,1],TMPW)
   DO IW=1,NW ; TMPW(IW)=M%BOUNDARY_PROP1(M%WALL(IW)%B1_INDEX)%U_NORMAL ; ENDDO ; CALL PUT(LIST,N,'W_U_NORMAL',1,[1,1,1,1],[NW,1,1,1],TMPW)
   DO IW=1,NW ; TMPW(IW)=M%BOUNDARY_PROP1(M%WALL(IW)%B1_INDEX)%U_NORMAL_S ; ENDDO ; CALL PUT(LIST,N,'W_U_NORMAL_S',1,[1,1,1,1],[NW,1,1,1],TMPW)
   DO IW=1,NW ; TMPW(IW)=M%BOUNDARY_PROP1(M%WALL(IW)%B1_INDEX)%RHO_F ; ENDDO ; CALL PUT(LIST,N,'W_RHO_F',1,[1,1,1,1],[NW,1,1,1],TMPW)
   DO IW=1,NW ; TMPW(IW)=M%BOUNDARY_PROP1(M%WALL(IW)%B1_INDEX)%TMP_F ; ENDDO ; CALL PUT(LIST,N,'W_TMP_F',1,[1,1,1,1],[NW,1,1,1],TMPW)
   DO IW=1,NW ; TMPW2(IW,:)=M%BOUNDARY_PROP1(M%WALL(IW)%B1_INDEX)%ZZ_F(1:NS) ; ENDDO
   CALL PUT(LIST,N,'W_ZZ_F',2,[1,1,1,1],[NW,NS,1,1],TMPW2)
   DO IW=1,NW ; TMPW2(IW,:)=M%BOUNDARY_PROP1(M%WALL(IW)%B1_INDEX)%RHO_D_DZDN_F(1:NS) ; ENDDO
   CALL PUT(LIST,N,'W_RHO_D_DZDN_F',2,[1,1,1,1],[NW,NS,1,1],TMPW2)
   DO IW=1,NW ; TMPW2(IW,:)=M%BOUNDARY_PROP1(M%WALL(IW)%B1_INDEX)%RHO_D_F(1:NS) ; ENDDO
   CALL PUT(LIST,N,'W_RHO_D_F',2,[1,1,1,1],[NW,NS,1,1],TMPW2)
   DO IW=1,NW ; TMPW(IW)=M%BOUNDARY_PROP1(M%WALL(IW)%B1_INDEX)%K_G ; ENDDO ; CALL PUT(LIST,N,'W_K_G',1,[1,1,1,1],[NW,1,1,1],TMPW)
   DO IW=1,NW ; TMPW(IW)=M%BOUNDARY_PROP1(M%WALL(IW)%B1_INDEX)%Q_CON_F ; ENDDO ; CALL PUT(LIST,N,'W_Q_CON_F',1,[1,1,1,1],[NW,1,1,1],TMPW)
   DO IW=1,NW ; TMPW(IW)=M%BOUNDARY_PROP1(M%WALL(IW)%B1_INDEX)%Q_LEAK ; ENDDO ; CALL PUT(LIST,N,'W_Q_LEAK',1,[1,1,1,1],[NW,1,1,1],TMPW)
   DO IW=1,NW ; TMPW(IW)=REAL(M%BOUNDARY_COORD(M%WALL(IW)%BC_INDEX)%IOR,EB) ; ENDDO ; CALL PUT(LIST,N,'W_IOR',1,[1,1,1,1],[NW,1,1,1],TMPW)
   DO IW=1,NW ; TMPW(IW)=REAL(M%BOUNDARY_COORD(M%WALL(IW)%BC_INDEX)%IIG,EB) ; ENDDO ; CALL PUT(LIST,N,'W_IIG',1,[1,1,1,1],[NW,1,1,1],TMPW)
   DO IW=1,NW ; TMPW(IW)=REAL(M%BOUNDARY_COORD(M%WALL(IW)%BC_INDEX)%JJG,EB) ; ENDDO ; CALL PUT(LIST,N,'W_JJG',1,[1,1,1,1],[NW,1,1,1],TMPW)
   DO IW=1,NW ; TMPW(IW)=REAL(M%BOUNDARY_COORD(M%WALL(IW)%BC_INDEX)%KKG,EB) ; ENDDO ; CALL PUT(LIST,N,'W_KKG',1,[1,1,1,1],[NW,1,1,1],TMPW)
   ! ghost-cell velocities of external walls (zero padded to NW) and edge data
   TMPW=0._EB ; TMPW(1:M%N_EXTERNAL_WALL_CELLS)=M%U_GHOST ; CALL PUT(LIST,N,'W_U_GHOST',1,[1,1,1,1],[NW,1,1,1],TMPW)
   TMPW=0._EB ; TMPW(1:M%N_EXTERNAL_WALL_CELLS)=M%V_GHOST ; CALL PUT(LIST,N,'W_V_GHOST',1,[1,1,1,1],[NW,1,1,1],TMPW)
   TMPW=0._EB ; TMPW(1:M%N_EXTERNAL_WALL_CELLS)=M%W_GHOST ; CALL PUT(LIST,N,'W_W_GHOST',1,[1,1,1,1],[NW,1,1,1],TMPW)
   DEALLOCATE(TMPW,TMPW2)
ENDIF
NE=SIZE(M%EDGE)
IF (NE>0) THEN
   ALLOCATE(TMPE(NE,5))
   DO K=1,NE ; TMPE(K,1)=REAL(M%EDGE(K)%I,EB) ; TMPE(K,2)=REAL(M%EDGE(K)%J,EB) ; TMPE(K,3)=REAL(M%EDGE(K)%K,EB) ; TMPE(K,4)=REAL(M%EDGE(K)%AXIS,EB) ; ENDDO
   CALL PUT(LIST,N,'E_IJKA',2,[1,1,1,1],[NE,4,1,1],TMPE)
   DO I=1,5 ; DO K=1,NE ; TMPE(K,I)=M%EDGE(K)%OMEGA(I-3) ; ENDDO ; ENDDO
   CALL PUT(LIST,N,'E_OMEGA',2,[1,1,1,1],[NE,5,1,1],TMPE)
   DO I=1,5 ; DO K=1,NE ; TMPE(K,I)=M%EDGE(K)%TAU(I-3) ; ENDDO ; ENDDO
   CALL PUT(LIST,N,'E_TAU',2,[1,1,1,1],[NE,5,1,1],TMPE)
   DEALLOCATE(TMPE)
ENDIF
END SUBROUTINE

SUBROUTINE REFDUMP_BEGIN(NAME,NM,T,DT)
CHARACTER(*), INTENT(IN) :: NAME
INTEGER, INTENT(IN) :: NM
REAL(EB), INTENT(IN) :: T,DT
IF (.NOT.WANT(NM)) RETURN
KNAME=NAME ; KT=T ; KDT=DT ; KRMIN=RHOMIN ; KRMAX=RHOMAX
KVAR=0
KPRED=MERGE(1,0,PREDICTOR) ; KFIRST=MERGE(1,0,FIRST_PASS)
CALL OPEN_MESH(NM)
CALL SNAP(BEF,NB,NM)
END SUBROUTINE

! write the record: changed arrays only in the "after" list
SUBROUTINE REFDUMP_END(NAME,NM,DTNEW,ICHG)
CHARACTER(*), INTENT(IN) :: NAME
INTEGER, INTENT(IN) :: NM
REAL(EB), INTENT(IN), OPTIONAL :: DTNEW
INTEGER, INTENT(IN), OPTIONAL :: ICHG
INTEGER :: I,J,K
LOGICAL :: SAME
LOGICAL :: KEEP(MAXA)
REAL(EB) :: X(4)
IF (.NOT.WANT(NM)) RETURN
KVAR=0 ; IF (MESHES(NM)%CLIP_RHOMIN) KVAR=KVAR+1 ; IF (MESHES(NM)%CLIP_RHOMAX) KVAR=KVAR+2   ! clip flags after the kernel
CALL OPEN_MESH(NM)
CALL SNAP(AFT,NA,NM)
KEEP=.FALSE.
DO I=1,NA
   SAME=.FALSE.
   DO J=1,NB
      IF (BEF(J)%NAME==AFT(I)%NAME) THEN
         SAME = ALL(BEF(J)%D==AFT(I)%D) .AND. ALL(BEF(J)%LB==AFT(I)%LB) .AND. ALL(BEF(J)%UB==AFT(I)%UB)
         EXIT
      ENDIF
   ENDDO
   KEEP(I)=.NOT.SAME
ENDDO
X=0._EB
IF (PRESENT(DTNEW)) X(1)=DTNEW
IF (PRESENT(ICHG)) X(2)=REAL(ICHG,EB)
X(3)=MESHES(NM)%CFL ; X(4)=MESHES(NM)%VN
CALL WRITE_REC(NAME,COUNT(KEEP),KEEP,X,NM)
END SUBROUTINE

SUBROUTINE WRITE_REC(NAME,NKEEP,KEEP,X,NM)
INTEGER, INTENT(IN) :: NM
CHARACTER(*), INTENT(IN) :: NAME
INTEGER, INTENT(IN) :: NKEEP
LOGICAL, INTENT(IN) :: KEEP(MAXA)
REAL(EB), INTENT(IN) :: X(4)
INTEGER :: I,K
CHARACTER(16) :: CN
CN=NAME
LU=100+NM
WRITE(LU) CN,ICYC,KPRED,KFIRST,KVAR,KT,KDT,KRMIN,KRMAX,X,NB,NKEEP
DO I=1,NB ; CALL WARR(BEF(I)) ; ENDDO
K=0
DO I=1,NA ; IF (KEEP(I)) CALL WARR(AFT(I)) ; ENDDO
NREC_M(NM)=NREC_M(NM)+1
END SUBROUTINE

SUBROUTINE WARR(A)
TYPE(ARR_T), INTENT(IN) :: A
WRITE(LU) A%NAME,A%RANK,A%LB,A%UB
WRITE(LU) A%D
END SUBROUTINE

! one PASS record per pass of the CHANGE_TIME_STEP loop (T, DT used, DT_NEW and change index of mesh 1 after the predictor velocity update)
SUBROUTINE REFDUMP_PASS(TT,DTT,DTNEW,ICHG)
REAL(EB), INTENT(IN) :: TT,DTT,DTNEW
INTEGER, INTENT(IN) :: ICHG
CHARACTER(16) :: CN='PASS'
REAL(EB) :: X(4)
IF (.NOT.ON) RETURN
IF (LOWER_MESH_INDEX>1) RETURN
CALL OPEN_MESH(1)
NPASS_CUR=NPASS_CUR+1
X=[DTNEW,REAL(ICHG,EB),REAL(NPASS_CUR,EB),0._EB]
WRITE(LU) CN,ICYC,0,MERGE(1,0,FIRST_PASS),0,TT,DTT,RHOMIN,RHOMAX,X,0,0
NREC_M(1)=NREC_M(1)+1
END SUBROUTINE

! one STEP record per time step: T (before advance) and DT used, DT_NEW and change index of mesh 1 of the final pass, number of passes
SUBROUTINE REFDUMP_STEP(TT,DTT,DTNEW,ICHG,NPASS)
REAL(EB), INTENT(IN) :: TT,DTT,DTNEW
INTEGER, INTENT(IN) :: ICHG,NPASS
CHARACTER(16) :: CN='STEP'
REAL(EB) :: X(4)
IF (.NOT.ON) RETURN
IF (LOWER_MESH_INDEX>1) RETURN
CALL OPEN_MESH(1)
X=[DTNEW,REAL(ICHG,EB),REAL(NPASS_CUR,EB),0._EB]
KT=TT ; KDT=DTT ; KRMIN=RHOMIN ; KRMAX=RHOMAX ; KVAR=0 ; KPRED=0 ; KFIRST=0
NB=0 ; NA=0
WRITE(LU) CN,ICYC,KPRED,KFIRST,KVAR,KT,KDT,KRMIN,KRMAX,X,0,0
NREC_M(1)=NREC_M(1)+1
NPASS_CUR=0
END SUBROUTINE

SUBROUTINE REFDUMP_FINISH
INTEGER :: NM
IF (.NOT.ON) RETURN
DO NM=1,MAXM
   IF (OPENED(NM)) THEN ; WRITE(100+NM,POS=9) NREC_M(NM) ; CLOSE(100+NM) ; ENDIF
ENDDO
ON=.FALSE.
END SUBROUTINE
END MODULE REFDUMP
