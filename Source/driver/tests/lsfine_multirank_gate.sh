#!/bin/bash
# lsfine_multirank_gate.sh: multi-rank --ls-fine gate (V&V Lead, 2026-10-19). Matrix: vv-lsfine-multirank-matrix.md (same dir / Source/driver/notes).
# Runs CSIRO C064 level-set crude (12x12x4 L0, the driver test case) as 1, 2 and 4 L0 meshes on 1, 2 and 4 ranks (ranks <= meshes), --ls-fine,
# 1 level (--run) and 2 levels (--nofine 0 and --nofine 1), and compares every configuration with 1 mesh / 1 rank of the same flags
# (lsfine_compare.py: every output csv, front x, leaf-cell PHI, run gates). Prints PASS/FAIL per row; exit 1 on any FAIL.
#
# Env (portable; any machine):
#   FDS_AMR      binary (default /workspace/fds-amr/scratch/b611/fds_amr)
#   MPIRUN       launcher (default "mpirun"; add e.g. "mpirun --allow-run-as-root --oversubscribe")
#   OMP_NUM_THREADS (default 1)
#   OUT          run dir (default ./lsfine_gate_out)
#   T_END        end time, s (default 30; long option 120 with TIMES=40,80,120)
#   TIMES        front-x times (default 10,20,30)
#   INPUT_1M / INPUT_2M / INPUT_4M   C064 inputs with 1/2/4 L0 meshes (Integration: scratch/mr-ls/integration/). If unset, 1M = the driver
#                case Source/driver/tests/cases/levelset_tag_phi_ground.fds (SRC_CASE) and 2M/4M are generated by splitting its mesh (2: x halves; 4: 2x2).
#   RANKS        rank counts to run (default "1 2 4"); MESHES (default "1 2 4"); LEVELS (default "1 2"); NOFINE (default "0 1")
#   MULTIMESH_EXPECT  "blocked" (default: at e821a0884c --ls-fine supports one L0 mesh; LS_INIT_FROM_MESH builds the LS grid from mesh 1):
#                2/4-mesh rows that stop are XFAIL (not counted), rows that run are compared normally (XPASS if they pass). "pass" counts them.
#   REPEAT=1     (default) rerun 1 mesh / 1 rank and require bit-identity with the reference (run-to-run determinism; the only multi-config check
#                that can pass on one core today).  LONG=1 (default) adds one 120 s row (2 levels, --nofine 0, 1 mesh/1 rank, front x 40/80/120 s).
#   Tolerance AGREED (Role 1, 2026-10-19): same mesh count on more ranks = strict bit-identity vs the 1-rank run of that mesh count;
#                any mesh count vs 1 mesh / 1 rank = identical front x, identical gate verdict, mean HRR (t >= HRR_MEAN_T0, default 10 s)
#                within HRR_MEAN_TOL (default 0.02). No cross-mesh-count csv/PHI tolerance (printed as INFO).
#   PERTURB=1    calibration: rerun each 1-mesh / 1-rank reference with TMPA + PERTURB_DT (default 0.01 C) and report the mean-HRR spread
#                (INFO; WARN if the spread exceeds HRR_MEAN_TOL). (lsfine_compare.py); BITID_SAME_MESH=1 (default) demands bit-identity between
#                rank counts at the same mesh count (compared against the 1-rank run of that mesh count, in addition to the 1/1 reference).
#   SEAM_ROW=1   (default) burner seam row SEAM_burner_L2_m4r4: simple_test (Verification/Adaptive_Mesh_Refinement, SEAM_CASE) as 4 L0 meshes (2x2, seam y=1.2 m
#                through the burner and the fine level), 2 levels, burner on level 1 (--nofine -1), 12 steps, 4 ranks vs 1 rank of the same 4 meshes:
#                same level-1 layouts (HIER) and every _hrr.csv / multi_level.csv column within RANK_SUMMARY_TOL (1e-11 rel, RANK_ABS_FLOOR abs).
#   OPEN_STEP=1  (default) run_open_step_check.sh (TESTS) twice: one level-1 box (--maxsize 16) and four level-1 boxes (MAXSIZE=8: seams cross the OPEN sides,
#                top and ground; Integration's edge rule b1a806cfdc), each 2L vs 1L within 1e-10. The 4-box row is KNOWN-FAIL (open item) with baseline
#                DEVC 4.612e-7, fields 6.297e-6, D 1.712e-9: not counted while every metric is at or below it (+0.1%), FAIL above.
#   SEAM_EDGE_RANKS=1  (default) run_fine_seam_edge_ranks_check.sh (TESTS): 4 L0 meshes, fine boxes over regrids, 1 rank vs 2 ranks byte-identical csv (MPIRUN).
#   RUN_EXISTING=1  also run the existing gates: run_ls_fine_drive_check.sh, run_levelset_tag_phi_check.sh, run_regrid_transfer_ground_check.sh,
#                and run_l0_bitcheck.sh (needs L0_OLD_BIN = binary before the change and L0_CASE = absolute .fds). BUILD_DIR defaults to dirname FDS_AMR; TESTS = Source/driver/tests.
set -u
HERE=$(cd "$(dirname "$0")" && pwd)
FDS_AMR=${FDS_AMR:-/workspace/fds-amr/scratch/b611/fds_amr}
MPIRUN=${MPIRUN:-mpirun}
export OMP_NUM_THREADS=${OMP_NUM_THREADS:-1}
OUT=${OUT:-$PWD/lsfine_gate_out}; T_END=${T_END:-30}; TIMES=${TIMES:-10,20,30}
RANKS=${RANKS:-"1 2 4"}; MESHES=${MESHES:-"1 2 4"}; LEVELS=${LEVELS:-"1 2"}; NOFINE=${NOFINE:-"0 1"}
TESTS=${TESTS:-$HERE}
SRC_CASE=${SRC_CASE:-$TESTS/cases/levelset_tag_phi_ground.fds}
BITID_SAME_MESH=${BITID_SAME_MESH:-1}
MULTIMESH_EXPECT=${MULTIMESH_EXPECT:-blocked}; REPEAT=${REPEAT:-1}; LONG=${LONG:-1}
export RANK_SUMMARY_TOL_ALL=${RANK_SUMMARY_TOL_ALL:-1}   # Ruling 2026-10-20, extended: all c_hrr/c_multi_level columns + leaf PHI <= RANK_SUMMARY_TOL across ranks (0 = previous behaviour)
export RANK_SUMMARY_TOL=${RANK_SUMMARY_TOL:-1e-11}
export RANK_ABS_FLOOR=${RANK_ABS_FLOOR:-1e-12}   # round-off floor (ruling: 1e-12, was 1e-13) (multi_level mass_rel_change, div*)
export HRR_Q_RANK_EXTRA=${HRR_Q_RANK_EXTRA:-HRR}
export HRR_Q_RANK_TOL=${HRR_Q_RANK_TOL:-2e-11}   # ruling (a): _hrr.csv Q_* sums across rank counts   # Owner ruling 2026-10-20 (c_hrr Q_* columns, same-mesh rank comparisons only)
export HRR_MEAN_TOL=${HRR_MEAN_TOL:-0.02} HRR_MEAN_T0=${HRR_MEAN_T0:-10}; PERTURB=${PERTURB:-0}; PERTURB_DT=${PERTURB_DT:-0.01}
CMP="python3 $HERE/lsfine_compare.py"
TWO_FLAGS="--two-level-run --levels 2 --init-patch --patch 5 9 0 11 --blocking 2 --maxsize 8 --regrid-every 2 --tag-phi --ls-fine --plotfile pf --plot-every 1000000"
[ -x "$FDS_AMR" ] || { echo "FAIL: FDS_AMR not executable: $FDS_AMR"; exit 2; }
mkdir -p "$OUT/inputs"; nfail=0; nruling=0; summary=()

# ---- inputs: 1 mesh = driver case; 2/4 meshes = Integration inputs if given, else split
make_input() {   # $1 = mesh count (or 4np2) -> $OUT/inputs/c_<n>m.fds
  local n=$1 dst=$OUT/inputs/c_${1}m.fds var=INPUT_${1}M
  if [ -n "${!var:-}" ]; then cp "${!var}" "$dst"
  else python3 - "$SRC_CASE" "$dst" "$n" <<'PY'
import sys, re
src, dst, n = sys.argv[1], sys.argv[2], int(sys.argv[3])
t = open(src).read()
m = re.search(r'&MESH IJK=(\d+),(\d+),(\d+), XB=([^/]+)/', t)
I, J, K = map(int, m.group(1, 2, 3)); x0, x1, y0, y1, z0, z1 = [float(v) for v in m.group(4).split(',')]
splits = {1: (1, 1), 2: (2, 1), 4: (2, 2)}[n]
mesh = []
for jy in range(splits[1]):
    for ix in range(splits[0]):
        dx = (x1 - x0) / splits[0]; dy = (y1 - y0) / splits[1]
        mesh.append(f"&MESH IJK={I//splits[0]},{J//splits[1]},{K}, XB={x0+ix*dx:g},{x0+(ix+1)*dx:g},{y0+jy*dy:g},{y0+(jy+1)*dy:g},{z0:g},{z1:g} /")
open(dst, 'w').write(t[:m.start()] + "\n".join(mesh) + t[m.end():])
PY
  fi
  sed -i "s/^&HEAD CHID=[^,]*,/\&HEAD CHID='c',/;s/T_END=[0-9.]*/T_END=${T_END}./" "$dst"
  sed -i '/^&AMR /d' "$dst"
  sed -i "s/SIG_FIGS=4, SIG_FIGS_EXP=2/SIG_FIGS=15, SIG_FIGS_EXP=3/" "$dst"   # full-precision csv: bit-identity must not be hidden by 4 significant figures
  if grep -q "CFL_VELOCITY_NORM *= *3" "$dst"; then sed -i "s/, *CFL_VELOCITY_NORM *= *3//;s/CFL_VELOCITY_NORM *= *3, *//" "$dst"; echo "NOTE: removed CFL_VELOCITY_NORM=3 (now rejected) from $dst"; fi
}
for n in $MESHES; do make_input $n; done
# 4 meshes on 2 ranks needs MPI_PROCESS on the MESH lines (else ERROR(115)): INPUT_4NP2M (Integration C064_4mesh_np2.fds), else generated from 4M
if [ -n "${INPUT_4NP2M:-}" ]; then make_input 4NP2
elif [ -f "$OUT/inputs/c_4m.fds" ]; then awk 'BEGIN{n=0} /^&MESH /{sub(/ *\/ *$/, sprintf(", MPI_PROCESS=%d /", int(n/2))); n++} {print}' "$OUT/inputs/c_4m.fds" > "$OUT/inputs/c_4NP2m.fds"; fi

run_case() {   # $1 tag, $2 meshes, $3 ranks, $4 levels, $5 nofine
  local tag=$1 m=$2 r=$3 lev=$4 nf=$5 d=$OUT/$1
  local mi=$m; [ "$m" = 4 ] && [ "$r" = 2 ] && mi=4NP2
  rm -rf "$d"; mkdir -p "$d"; cp "$OUT/inputs/c_${mi}m.fds" "$d/c.fds"
  if [ "$lev" = 1 ]; then sed -i '1a &AMR MAX_LEVEL=0, BLOCKING_FACTOR=2, MAX_GRID_SIZE=24 /' "$d/c.fds"; FL="--run --ls-fine"
  else sed -i '1a &AMR MAX_LEVEL=1, BLOCKING_FACTOR=2, MAX_GRID_SIZE=24 /' "$d/c.fds"; FL="$TWO_FLAGS --nofine $nf"; fi
  local s=$SECONDS
  (cd "$d" && $MPIRUN -np "$r" "$FDS_AMR" c.fds $FL --outdir . --chid c > run.log 2>&1); local rc=$?
  echo "$((SECONDS - s))" > "$d/wall_s"; return $rc
}

for lev in $LEVELS; do
  nfs="x"; [ "$lev" = 2 ] && nfs=$NOFINE
  for nf in $nfs; do
    sfx="L${lev}"; [ "$lev" = 2 ] && sfx="L2_nf${nf}"
    ref=ref_${sfx}_m1r1
    echo "== $sfx reference (1 mesh, 1 rank)"
    if ! run_case $ref 1 1 $lev ${nf/x/0}; then echo "FAIL $ref: run rc!=0 (see $OUT/$ref/run.log)"; nfail=$((nfail+1)); summary+=("FAIL $ref run"); continue; fi
    echo "   wall $(cat $OUT/$ref/wall_s) s"
    if [ "$REPEAT" = 1 ]; then
      echo "== ${sfx}_m1r1_repeat (determinism)"
      if run_case ${sfx}_m1r1_repeat 1 1 $lev ${nf/x/0} && $CMP "$OUT/$ref" "$OUT/${sfx}_m1r1_repeat" --mode bitid --times "$TIMES"; then summary+=("PASS ${sfx}_m1r1_repeat BITID"); else summary+=("FAIL ${sfx}_m1r1_repeat BITID"); nfail=$((nfail+1)); fi
    fi
    if [ "$PERTURB" = 1 ]; then
      pt=${sfx}_m1r1_perturb; echo "== $pt (TMPA + $PERTURB_DT, calibration)"
      cp "$OUT/inputs/c_1m.fds" "$OUT/inputs/c_1m.keep"
      python3 - "$OUT/inputs/c_1m.fds" "$PERTURB_DT" <<'PY'
import sys, re
p, dt = sys.argv[1], float(sys.argv[2]); t = open(p).read()
t2, n = re.subn(r'TMPA\s*=\s*([-0-9.Ee+]+)', lambda m: f"TMPA={float(m.group(1)) + dt:.6g}", t)
if n == 0: t2 = re.sub(r'&MISC ', f'&MISC TMPA={20.0 + dt:.6g}, ', t, count=1)
open(p, 'w').write(t2)
PY
      run_case $pt 1 1 $lev ${nf/x/0}; mv "$OUT/inputs/c_1m.keep" "$OUT/inputs/c_1m.fds"
      spread=$(python3 - "$OUT/$ref/c_hrr.csv" "$OUT/$pt/c_hrr.csv" "$HRR_MEAN_T0" <<'PY'
import sys, numpy as np
a = np.genfromtxt(sys.argv[1], delimiter=',', skip_header=2); b = np.genfromtxt(sys.argv[2], delimiter=',', skip_header=2); t0 = float(sys.argv[3])
ma, mb = a[a[:, 0] >= t0, 1].mean(), b[b[:, 0] >= t0, 1].mean(); print(f"{abs(mb - ma) / abs(ma):.4e} (ref {ma:.5g} kW, perturbed {mb:.5g} kW)")
PY
)
      w=""; python3 -c "import sys; sys.exit(0 if float('${spread%% *}') <= $HRR_MEAN_TOL else 1)" || w=" WARN: spread > HRR_MEAN_TOL"
      echo "   INFO perturbed mean-HRR spread $spread$w"; summary+=("INFO $pt mean-HRR spread ${spread%% *}$w")
    fi
    for m in $MESHES; do for r in $RANKS; do
      [ "$r" -gt "$m" ] && continue                       # FDS: ranks <= meshes
      [ "$m" = 1 ] && [ "$r" = 1 ] && continue
      tag=${sfx}_m${m}r${r}
      echo "== $tag"
      if ! run_case $tag $m $r $lev ${nf/x/0}; then
        why=$(grep -a -m1 -E "ERROR|Abort|STOP 1" "$OUT/$tag/run.log" | cut -c1-160)
        if [ "$m" -gt 1 ] && [ "$MULTIMESH_EXPECT" = blocked ]; then echo "XFAIL $tag: blocked, multi-mesh --ls-fine not landed (${why:-see run.log})"; summary+=("XFAIL $tag (blocked: $why)"); continue; fi
        echo "FAIL $tag: run rc!=0 (${why:-see run.log})"; nfail=$((nfail+1)); summary+=("FAIL $tag run: $why"); continue; fi
      echo "   wall $(cat $OUT/$tag/wall_s) s; vs 1/1 reference:"
      if $CMP "$OUT/$ref" "$OUT/$tag" --mode crossmesh --times "$TIMES"; then summary+=("PASS $tag")
      elif [ "$m" -gt 1 ] && [ "$MULTIMESH_EXPECT" = blocked ]; then summary+=("XFAIL $tag vs ref (multi-mesh blocked; not counted)")
      else summary+=("FAIL $tag vs ref"); nfail=$((nfail+1)); fi
      base=${sfx}_m${m}r1
      if [ "$lev" = 2 ] && [ "$r" -gt 1 ] && [ -d "$OUT/$base" ]; then   # hierarchy: box and cell counts at the start and at every regrid identical to 1 rank (same mesh count)
        hier() { grep -a -E 'level 1 = |mid-regrid' "$OUT/$1/run.log" | sed 's/.*finest/finest/'; }
        if [ -n "$(hier $tag)" ] && [ "$(hier $tag)" = "$(hier $base)" ]; then summary+=("PASS $tag HIER vs $base ($(hier $tag | wc -l) layouts)")
        else summary+=("FAIL $tag HIER vs $base"); nfail=$((nfail+1)); fi
      fi
      if [ "$BITID_SAME_MESH" = 1 ] && [ "$r" -gt 1 ] && [ -d "$OUT/$base" ]; then
        echo "   bit-identity vs $base (same mesh count):"
        $CMP "$OUT/$base" "$OUT/$tag" --mode bitid --times "$TIMES"; crc=$?
        if [ $crc = 3 ]; then summary+=("NEEDS-RULING $tag BITID vs $base (not counted as FAIL; blocks push)"); nruling=$((nruling+1))
        elif [ $crc = 0 ]; then summary+=("PASS $tag BITID vs $base")
        elif [ "$MULTIMESH_EXPECT" = blocked ]; then summary+=("XFAIL $tag BITID vs $base (multi-mesh blocked; not counted)")
        else summary+=("FAIL $tag BITID vs $base"); nfail=$((nfail+1)); fi
      fi
    done; done
  done
done

if [ "$LONG" = 1 ]; then
  echo "== LONG L2_nf0_m1r1_T120 (120 s; about 26 s wall at 1 rank / 2 threads per Role 1)"
  sv=$T_END; T_END=120; make_input 1; mv "$OUT/inputs/c_1m.fds" "$OUT/inputs/c_1m_T120.fds"; T_END=$sv; make_input 1
  cp "$OUT/inputs/c_1m.fds" "$OUT/inputs/c_1m_T${sv}.fds"; cp "$OUT/inputs/c_1m_T120.fds" "$OUT/inputs/c_1m.fds"
  if run_case L2_nf0_m1r1_T120 1 1 2 0 && grep -aq "LEVEL RUN PASS" "$OUT/L2_nf0_m1r1_T120/run.log"; then
    echo "   wall $(cat $OUT/L2_nf0_m1r1_T120/wall_s) s; front x (40/80/120 s): $(python3 - "$OUT/L2_nf0_m1r1_T120/c_devc.csv" <<'PY'
import sys, numpy as np
d = np.genfromtxt(sys.argv[1], delimiter=',', skip_header=2)
print(' '.join(f"{d[d[:,0] <= t + 1e-9][-1,1]:g}" for t in (40, 80, 120)))
PY
)"; summary+=("PASS L2_nf0_m1r1_T120 (gate; multi-config comparison at 120 s: rerun with T_END=120 TIMES=40,80,120)")
  else summary+=("FAIL L2_nf0_m1r1_T120"); nfail=$((nfail+1)); fi
  cp "$OUT/inputs/c_1m_T${sv}.fds" "$OUT/inputs/c_1m.fds"
fi

if [ "${RUN_EXISTING:-0}" = 1 ]; then
  BUILD_DIR=${BUILD_DIR:-$(dirname "$FDS_AMR")}
  for g in run_ls_fine_drive_check.sh run_levelset_tag_phi_check.sh run_regrid_transfer_ground_check.sh; do
    echo "== existing gate $g"
    if bash "$TESTS/$g" "$BUILD_DIR" "$OUT/existing_${g%.sh}" > "$OUT/existing_${g%.sh}.log" 2>&1; then summary+=("PASS existing $g")
    else summary+=("FAIL existing $g"); nfail=$((nfail+1)); fi
    tail -3 "$OUT/existing_${g%.sh}.log"
  done
fi

  # run_l0_bitcheck.sh <new-bin> <old-bin> <abs case>: needs L0_OLD_BIN (binary before the change) and L0_CASE (absolute .fds); runs in its own dir
  if [ "${RUN_EXISTING:-0}" = 1 ]; then
    if [ -n "${L0_OLD_BIN:-}" ] && [ -n "${L0_CASE:-}" ]; then
      mkdir -p "$OUT/existing_l0_bitcheck"; r=$(cd "$OUT/existing_l0_bitcheck" && bash "$TESTS/run_l0_bitcheck.sh" "$FDS_AMR" "$L0_OLD_BIN" "$L0_CASE" 2>&1 | tail -1)
      echo "== existing gate run_l0_bitcheck.sh: $r"
      case "$r" in *", 0 differ"*) summary+=("PASS existing run_l0_bitcheck.sh ($r)");; *) summary+=("FAIL existing run_l0_bitcheck.sh ($r)"); nfail=$((nfail+1));; esac
    else summary+=("SKIP existing run_l0_bitcheck.sh (set L0_OLD_BIN and L0_CASE)"); fi
  fi

if [ "${SEAM_ROW:-1}" = 1 ]; then   # burner seam row (see header)
  SEAM_CASE=${SEAM_CASE:-$TESTS/../../../Verification/Adaptive_Mesh_Refinement/simple_test.fds}
  sd=$OUT/SEAM_burner_L2; rm -rf "$sd"; mkdir -p "$sd"
  if [ ! -f "$SEAM_CASE" ]; then summary+=("FAIL SEAM_burner_L2_m4r4 (no SEAM_CASE $SEAM_CASE)"); nfail=$((nfail+1)); else
  for r in 1 4; do mkdir -p "$sd/r$r"; python3 - "$SEAM_CASE" "$sd/r$r/s.fds" "$r" <<'PY'
import sys, re
s = open(sys.argv[1]).read().replace('T_END=5.0', 'T_END=0.6'); np_ = int(sys.argv[3])
m = re.search(r"&MESH[^/]*/", s).group(0); k = 0; four = []
for x0, x1 in ((0.0, 1.8), (1.8, 3.6)):
    for y0, y1 in ((0.0, 1.2), (1.2, 2.4)):
        four.append("&MESH IJK=18,12,24, XB=%s,%s,%s,%s,0.0,2.4, MPI_PROCESS=%d /" % (x0, x1, y0, y1, k * np_ // 4)); k += 1
s = s.replace(m, "\n".join(four) + "\n&RADI RADIATION=.FALSE. /\n&DUMP SIG_FIGS=15, SIG_FIGS_EXP=3 /")
open(sys.argv[2], 'w').write(s)
PY
    (cd "$sd/r$r" && $MPIRUN -np $r "$FDS_AMR" s.fds --two-level-run --levels 2 --patch 0 7 0 7 --nofine -1 --steps 12 > run.log 2>&1) || echo "rc!=0" >> "$sd/r$r/run.log"
  done
  hs() { grep -a -E 'level 1 = |mid-regrid' "$sd/$1/run.log" | sed 's/.*finest/finest/'; }
  why=$(python3 - "$sd/r1" "$sd/r4" <<'PY'
import sys, csv, glob, os
tol = float(os.environ.get('RANK_SUMMARY_TOL', '1e-11')); flo = float(os.environ.get('RANK_ABS_FLOOR', '1e-12')); bad = []; ruling = []   # mass / mass_rel_change round-off: NEEDS-RULING, as lsfine_compare.py
for d in sys.argv[1:]:
    t = open(d + '/run.log', errors='replace').read()
    if 'rc!=0' in t or 'RESULT gate PASS' not in t: bad.append(os.path.basename(d) + ' run/gate')
for pat in ('*_hrr.csv', '*multi_level.csv'):
    fa, fb = glob.glob(sys.argv[1] + '/' + pat), glob.glob(sys.argv[2] + '/' + pat)
    if not fa or not fb: bad.append('missing ' + pat); continue
    ra, rb = list(csv.reader(open(fa[0]))), list(csv.reader(open(fb[0])))
    if len(ra) != len(rb): bad.append(pat + ' rows'); continue
    hdr = ra[1] if pat == '*_hrr.csv' else ra[0]
    for x, y in zip(ra, rb):
        for i, (u, v) in enumerate(zip(x, y)):
            try: u, v = float(u), float(v)
            except ValueError: continue
            nm = hdr[i].strip() if i < len(hdr) else str(i)
            if abs(u - v) > max((float(os.environ.get('HRR_Q_RANK_TOL', '2e-11')) if pat == '*_hrr.csv' and nm.startswith('Q_') else tol) * abs(u), flo):
                msg = '%s %s %.3e vs %.3e' % (pat, nm, u, v)
                if pat == '*multi_level.csv' and nm in ('mass', 'mass_rel_change'): ruling.append(msg) if not ruling else None
                elif not any(b.startswith(pat + ' ' + nm + ' ') for b in bad): bad.append(msg)
print('; '.join(bad[:3]) if bad else ('RULING ' + ruling[0] if ruling else ''))
PY
)
  if [ -z "$(hs r1)" ] || [ "$(hs r1)" != "$(hs r4)" ]; then why="HIER differs (r1: $(hs r1 | head -1 | cut -c1-60); r4: $(hs r4 | head -1 | cut -c1-60)) ${why}"; fi
  if [ -z "$why" ]; then summary+=("PASS SEAM_burner_L2_m4r4 vs m4r1 (HIER + csv 1e-11)")
  elif [ "${why#RULING }" != "$why" ]; then summary+=("NEEDS-RULING SEAM_burner_L2_m4r4 vs m4r1 (HIER and every other column pass; ${why#RULING }) (not counted as FAIL; blocks push)"); nruling=$((nruling+1)); else summary+=("FAIL SEAM_burner_L2_m4r4 vs m4r1: $why"); nfail=$((nfail+1)); fi
  echo "== SEAM_burner_L2_m4r4: ${why:-PASS}"
  fi
fi

if [ "${OPEN_STEP:-1}" = 1 ]; then   # open_step 1 box and 4 boxes (see header)
  for ms in 16 8; do
    nb=1; [ $ms = 8 ] && nb=4
    o=$(MAXSIZE=$ms bash "$TESTS/run_open_step_check.sh" "$FDS_AMR" "$OUT/open_step_${nb}box" 2>&1); r=$(echo "$o" | tail -1); echo "== open_step ${nb} box(es): $r"
    case "$r" in "PASS open_step"*) summary+=("PASS open_step_${nb}box (maxsize $ms)"); continue;; esac
    if [ $nb = 4 ]; then   # KNOWN-FAIL (open item: 4-box open_step defect): not counted while every metric stays at or below its baseline (b1a806cfdc / 2c12ae8401)
      kf=$(echo "$o" | python3 -c "
import re,sys
t=sys.stdin.read(); base={'DEVC':4.612e-07,'fields':6.297e-06,'D':1.712e-09}; out=[]
for k,b in base.items():
    m=re.search(r'^ *'+k+r' worst .*? ([0-9.]+e[-+][0-9]+)',t,re.M)
    if not m: print('FAIL no '+k); sys.exit()
    v=float(m.group(1)); out.append('%s %.3e/%.3e'%(k,v,b))
