!> MAIN_LOOP zeroes the per-step energy and mass balance arrays (Q_DOT, M_DOT) at the start of the corrector, after T = T + DT. UPDATE_HRR accumulates into them
!> at the end of the step, so the driver must do the same or the HRR file sums over all previous steps.
!> Composite Q_ENTH (driver writers): S = sum RHO*H_S*VC of UPDATE_HRR (ENTHALPY_SUM) of box NM restricted to the cells with MASK/=0 (MASK(1:IBAR,1:JBAR,1:KBAR), I fastest).
!> No wall terms: a fine box has no wall cells (fds_fine_level.f90), so Q_CONV/Q_COND/Q_DIFF stay the level-0 sums.
SUBROUTINE FDS_P_ESUMS(NM,MASK,S) BIND(C,NAME='fds_p_esums')
USE PHYSICAL_FUNCTIONS, ONLY: GET_SENSIBLE_ENTHALPY
USE MESH_POINTERS, ONLY: POINT_TO_BOX,IBAR,JBAR,KBAR,DX,DY,DZ,CELL,CELL_INDEX,RHO,TMP,ZZ
INTEGER(C_INT), VALUE :: NM
INTEGER(C_INT), INTENT(IN) :: MASK(*)
REAL(C_DOUBLE), INTENT(OUT) :: S
INTEGER :: I,J,K
REAL(EB) :: ZZ_GET(1:N_TRACKED_SPECIES),H_S
S = 0._EB
CALL POINT_TO_BOX(NM)
DO K=1,KBAR
   DO J=1,JBAR
      DO I=1,IBAR
         IF (MASK(I+IBAR*((J-1)+JBAR*(K-1)))==0) CYCLE
         IF (CELL(CELL_INDEX(I,J,K))%SOLID) CYCLE
         ZZ_GET = ZZ(I,J,K,1:N_TRACKED_SPECIES)
         CALL GET_SENSIBLE_ENTHALPY(ZZ_GET,H_S,TMP(I,J,K))
         S = S + RHO(I,J,K)*H_S*DX(I)*DY(J)*DZ(K)
      ENDDO
   ENDDO
ENDDO
END SUBROUTINE FDS_P_ESUMS

!> Q_COND test (run_qcond_open_check.sh): sum of Q_CON_F*AREA over the OPEN walls of level-0 mesh NM, the OPEN part of UPDATE_HRR's Q_DOT(5) (W, without the sign)
SUBROUTINE FDS_P_QOPEN(NM,S) BIND(C,NAME='fds_p_qopen')
INTEGER(C_INT), VALUE :: NM
REAL(C_DOUBLE), INTENT(OUT) :: S
INTEGER :: IW
TYPE(MESH_TYPE), POINTER :: M
M => MESHES(NM)
S = 0._EB
DO IW=1,M%N_EXTERNAL_WALL_CELLS
   IF (M%WALL(IW)%BOUNDARY_TYPE==OPEN_BOUNDARY) S = S + M%BOUNDARY_PROP1(M%WALL(IW)%B1_INDEX)%Q_CON_F*M%BOUNDARY_PROP1(M%WALL(IW)%B1_INDEX)%AREA
ENDDO
END SUBROUTINE FDS_P_QOPEN

!> Masked mass sums of box NM of any level, the cell sum of UPDATE_MASS (no cut cells): S(0) = sum RHO*VC, S(1:N_SPECIES) = RHO*Y*VC, S(N_SPECIES+1:) = RHO*ZZ*VC.
SUBROUTINE FDS_P_MSUMS(NM,MASK,S) BIND(C,NAME='fds_p_msums')
USE PHYSICAL_FUNCTIONS, ONLY: GET_MASS_FRACTION_ALL
USE MESH_POINTERS, ONLY: POINT_TO_BOX,IBAR,JBAR,KBAR,DX,DY,DZ,CELL,CELL_INDEX,RHO,ZZ
INTEGER(C_INT), VALUE :: NM
INTEGER(C_INT), INTENT(IN) :: MASK(*)
REAL(C_DOUBLE), INTENT(OUT) :: S(0:N_SPECIES+N_TRACKED_SPECIES)
INTEGER :: I,J,K
REAL(EB) :: ZZ_GET(1:N_TRACKED_SPECIES),Y_MF(1:N_SPECIES),VC
S = 0._EB
CALL POINT_TO_BOX(NM)
DO K=1,KBAR
   DO J=1,JBAR
      DO I=1,IBAR
         IF (MASK(I+IBAR*((J-1)+JBAR*(K-1)))==0) CYCLE
         IF (CELL(CELL_INDEX(I,J,K))%SOLID) CYCLE
         VC = DX(I)*DY(J)*DZ(K)
         ZZ_GET = ZZ(I,J,K,1:N_TRACKED_SPECIES)
         CALL GET_MASS_FRACTION_ALL(ZZ_GET,Y_MF)
         S(0) = S(0) + VC*RHO(I,J,K)
         S(1:N_SPECIES) = S(1:N_SPECIES) + RHO(I,J,K)*Y_MF*VC
         S(N_SPECIES+1:) = S(N_SPECIES+1:) + RHO(I,J,K)*ZZ_GET*VC
      ENDDO
   ENDDO
ENDDO
END SUBROUTINE FDS_P_MSUMS

