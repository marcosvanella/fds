!> \brief bind(C) wrappers of the S5 time loop (M2a): the pieces of PRESSURE_ITERATION_SCHEME / MAIN_LOOP that are Fortran-owned state or unmodified FDS routines,
!> and the state getters the C++ time loop needs. Nothing here changes FDS data except through the unmodified FDS routines it calls, the pressure step
!> (H ghost assignment copied from PRESSURE_SOLVER_FFT, the part that follows the Poisson solve) and the divergence integrals (DSUM, PSUM, USUM).
!>
!> Kernel-facing file rules (M2a):
!> (a) Passive scalars (N_TOTAL_SCALARS beyond the tracked species) are handled by Fields.cpp: ZZ/ZZS carry ncomp=N_TOTAL_SCALARS as the last extent; the copy-out
!>     here passes that extent through, whatever its size.
!> (b) Only uniform Cartesian metrics are used; R(I)/RRN(I) are not involved (CYLINDRICAL and TRN* meshes are rejected at level-0 assembly, IR-002, and the
!>     time loop rejects CYLINDRICAL).
!> Scope of the time loop that these wrappers serve (TimeLoop.cpp): gas phase only, FFT pressure flag, no complex geometry, HVAC, radiation, particles, reactions,
!> level set, tunnel preconditioner. FDS_P_PARAMS returns the flags so that the driver can refuse a case outside this scope.
!> Boundary table entries: README.md, "Fortran/C++ boundary".
