!> Copy array NAME of mesh NM out, column-major with its own (FDS) bounds. NTOT = expected element count. IERR 1 unknown, 2 not allocated, 3 size mismatch.
SUBROUTINE FDS_P_GET(NM,NAME,BUF,NTOT,IERR) BIND(C,NAME='fds_p_get')
INTEGER(C_INT), VALUE :: NM
CHARACTER(KIND=C_CHAR), INTENT(IN) :: NAME(*)
REAL(C_DOUBLE), INTENT(OUT) :: BUF(*)
INTEGER(C_LONG), VALUE :: NTOT
INTEGER(C_INT), INTENT(OUT) :: IERR
TYPE(MESH_TYPE), POINTER :: M
CHARACTER(LEN=32) :: NM_
INTEGER :: I
M => MESHES(NM)
NM_ = ' '
DO I=1,32
   IF (NAME(I)==C_NULL_CHAR) EXIT
   NM_(I:I) = NAME(I)
ENDDO
IERR = 0
SELECT CASE(TRIM(NM_))
   CASE('RHO')  ; CALL C3(M%RHO)
   CASE('RHOS') ; CALL C3(M%RHOS)
   CASE('TMP')  ; CALL C3(M%TMP)
   CASE('U')    ; CALL C3(M%U)
   CASE('V')    ; CALL C3(M%V)
   CASE('W')    ; CALL C3(M%W)
   CASE('US')   ; CALL C3(M%US)
   CASE('VS')   ; CALL C3(M%VS)
   CASE('WS')   ; CALL C3(M%WS)
   CASE('H')    ; CALL C3(M%H)
   CASE('HS')   ; CALL C3(M%HS)
   CASE('KRES') ; CALL C3(M%KRES)
   CASE('D')    ; CALL C3(M%D)
   CASE('DS')   ; CALL C3(M%DS)
   CASE('DDDT') ; CALL C3(M%DDDT)
   CASE('MU')   ; CALL C3(M%MU)
   CASE('RSUM') ; CALL C3(M%RSUM)
   CASE('FVX')  ; CALL C3(M%FVX)
   CASE('FVY')  ; CALL C3(M%FVY)
   CASE('FVZ')  ; CALL C3(M%FVZ)
   CASE('ZZ')   ; CALL C4(M%ZZ)
   CASE('ZZS')  ; CALL C4(M%ZZS)
   CASE DEFAULT ; IERR = 1
END SELECT
CONTAINS
SUBROUTINE C3(A)
REAL(EB), ALLOCATABLE, INTENT(IN) :: A(:,:,:)
IF (.NOT.ALLOCATED(A)) THEN ; IERR = 2 ; RETURN ; ENDIF
IF (SIZE(A,KIND=C_LONG)/=NTOT) THEN ; IERR = 3 ; RETURN ; ENDIF
BUF(1:NTOT) = RESHAPE(A,(/NTOT/))
END SUBROUTINE C3
SUBROUTINE C4(A)
REAL(EB), ALLOCATABLE, INTENT(IN) :: A(:,:,:,:)
IF (.NOT.ALLOCATED(A)) THEN ; IERR = 2 ; RETURN ; ENDIF
IF (SIZE(A,KIND=C_LONG)/=NTOT) THEN ; IERR = 3 ; RETURN ; ENDIF
BUF(1:NTOT) = RESHAPE(A,(/NTOT/))
END SUBROUTINE C4
END SUBROUTINE FDS_P_GET

