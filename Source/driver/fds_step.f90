END SUBROUTINE FDS_P_MFD

!> Mass rate (kg/s) that DENSITY moves through the leaf wall faces in this stage, kept per box and stage (a repeated call overwrites): level-0 mesh NM (<=NMESHES) the walls without hidden fine
!> children, fine box NM its hidden fine walls (the face velocity and area of the box, the state RHO_F, ZZ_F, RHO_D_DZDN_F of the parent wall). Per wall: advective RHO_F*ZZ_F*u_in (the FX
!> override of MASS_FINITE_DIFFERENCES, UU = U or US) and diffusive -RHO_D_DZDN_F, times the face area.
SUBROUTINE BND_STAGE_RATE(NM)
USE MESH_POINTERS, ONLY: POINT_TO_BOX,PU=>U,PV=>V,PW=>W,PUS=>US,PVS=>VS,PWS=>WS,PDX=>DX,PDY=>DY,PDZ=>DZ,PFX=>FX,PFY=>FY,PFZ=>FZ
USE TYPES, ONLY: WALL_TYPE,BOUNDARY_COORD_TYPE,BOUNDARY_PROP1_TYPE
INTEGER, INTENT(IN) :: NM
INTEGER :: IW,ST,NMP,K,IWP,NBX
REAL(EB) :: V
REAL(EB), POINTER, DIMENSION(:,:,:) :: UU,VV,WW
REAL(EB), POINTER, DIMENSION(:) :: DXP,DYP,DZP
TYPE(MESH_TYPE), POINTER :: M
TYPE(WALL_TYPE), POINTER :: WCF
TYPE(BOUNDARY_COORD_TYPE), POINTER :: BCF
TYPE(BOUNDARY_PROP1_TYPE), POINTER :: B1F
IF (.NOT.ALLOCATED(BND_RATE)) THEN ; ALLOCATE(BND_RATE(0:N_TRACKED_SPECIES+1,NMESHES,2),BND_STAMP(NMESHES,2)) ; BND_RATE = 0._EB ; BND_STAMP = 0 ; ENDIF
IF (NM>SIZE(BND_RATE,2)) THEN   ! a fine box: grow the table
   BLOCK
   REAL(EB), ALLOCATABLE :: R2(:,:,:)
   INTEGER, ALLOCATABLE :: S2(:,:)
   ALLOCATE(R2(0:N_TRACKED_SPECIES+1,NM,2),S2(NM,2)) ; R2 = 0._EB ; S2 = 0
   R2(:,1:SIZE(BND_RATE,2),:) = BND_RATE ; S2(1:SIZE(BND_RATE,2),:) = BND_STAMP
   CALL MOVE_ALLOC(R2,BND_RATE) ; CALL MOVE_ALLOC(S2,BND_STAMP)
   END BLOCK
ENDIF
ST = MERGE(1,2,PREDICTOR)
BND_RATE(:,NM,ST) = 0._EB
IF (NM>NMESHES) BND_STAMP(NM,ST) = ICYC
IF (PEND_ICYC(ST)/=ICYC) THEN ; NPEND(ST) = 0 ; PEND_ICYC(ST) = ICYC ; ENDIF   ! the lists of this step and stage start empty at the first call
IF (PUB_ICYC(ST)/=ICYC) THEN ; NPUB(ST) = 0 ; PUB_ICYC(ST) = ICYC ; ENDIF
IF (FDS_P_DENS_SKIP()/=0) RETURN   ! DENSITY moves no mass this stage (first step ICYC<=1 etc.): no wall inflow either
IF (NM<=NMESHES) THEN
   M => MESHES(NM)
   IF (PREDICTOR) THEN ; UU=>M%U ; VV=>M%V ; WW=>M%W ; ELSE ; UU=>M%US ; VV=>M%VS ; WW=>M%WS ; ENDIF
   DO IW=1,M%N_EXTERNAL_WALL_CELLS+M%N_INTERNAL_WALL_CELLS
      IF (ASSOCIATED(LEAF_WALL_COVERED_PROC)) THEN
         IF (LEAF_WALL_COVERED_PROC(NM,IW)) THEN   ! its hidden fine walls carry this share; a fine wall on another rank needs the state: publish it
            IF (N_MPI_PROCESSES>1) CALL PUBLISH(M,IW)
            CYCLE
         ENDIF
      ENDIF
      CALL ONE_WALL(M,IW,M%BOUNDARY_COORD(M%WALL(IW)%BC_INDEX),M%DX,M%DY,M%DZ)
   ENDDO
ELSE
   IF (.NOT.ASSOCIATED(LEAF_WALL_COUNT_PROC)) RETURN
   CALL POINT_TO_BOX(NM)
   IF (PREDICTOR) THEN ; UU=>PU ; VV=>PV ; WW=>PW ; ELSE ; UU=>PUS ; VV=>PVS ; WW=>PWS ; ENDIF
   DXP=>PDX ; DYP=>PDY ; DZP=>PDZ
   IF (ASSOCIATED(LEAF_BOXWALL_COUNT_PROC)) THEN   ! leaf walls of this box only (indexed once per regrid)
      DO K=1,LEAF_BOXWALL_COUNT_PROC(NM)
         CALL LEAF_BOXWALL_PROC(NM,K,BCF,NMP,IWP,B1F)
         IF (NMP<1) CYCLE
         IF (IWP<0) THEN   ! exempt burner face (PV-13): DENSITY applies its own M_DOT_G_PP_ADJUST over its own area
            BND_RATE(0,NM,ST) = BND_RATE(0,NM,ST) + B1F%AREA*SUM(B1F%M_DOT_G_PP_ADJUST(1:N_TRACKED_SPECIES))
            BND_RATE(1:N_TRACKED_SPECIES,NM,ST) = BND_RATE(1:N_TRACKED_SPECIES,NM,ST) + B1F%AREA*B1F%M_DOT_G_PP_ADJUST(1:N_TRACKED_SPECIES)
            BND_RATE(N_TRACKED_SPECIES+1,NM,ST) = BND_RATE(N_TRACKED_SPECIES+1,NM,ST) + B1F%AREA*SUM(B1F%M_DOT_G_PP_ADJUST(1:N_TRACKED_SPECIES))
         ELSEIF (IWP>0) THEN ; CALL ONE_WALL(MESHES(NMP),IWP,BCF,DXP,DYP,DZP)
         ELSEIF (PROCESS(NMP)/=MY_RANK) THEN ; CALL PEND_WALL(NMP,BCF,DXP,DYP,DZP)   ! the parent wall is on another rank
         ENDIF
      ENDDO
   ENDIF
ENDIF

CONTAINS

   !> Rate through the face of wall IW of level-0 mesh MP (its state B1, type, thin-obstruction test) with the geometry BCG (BC%IOR, IIG.. in the box of UU/VV/WW and DXP.. cell sizes).
   SUBROUTINE ONE_WALL(MP,IW,BCG,DXP,DYP,DZP)
   TYPE(MESH_TYPE), INTENT(IN) :: MP
   INTEGER, INTENT(IN) :: IW
   TYPE(BOUNDARY_COORD_TYPE), INTENT(IN) :: BCG
   REAL(EB), INTENT(IN) :: DXP(0:),DYP(0:),DZP(0:)
   INTEGER :: IC
   REAL(EB) :: UIN,A,FXN(N_TRACKED_SPECIES)
   ASSOCIATE(WC=>MP%WALL(IW),BCP=>MP%BOUNDARY_COORD(MP%WALL(IW)%BC_INDEX),B1=>MP%BOUNDARY_PROP1(MP%WALL(IW)%B1_INDEX))
   IF (WC%BOUNDARY_TYPE/=SOLID_BOUNDARY .AND. WC%BOUNDARY_TYPE/=OPEN_BOUNDARY) RETURN
   IC = MP%CELL_INDEX(BCP%II,BCP%JJ,BCP%KK)
   IF (WC%BOUNDARY_TYPE==SOLID_BOUNDARY .AND. .NOT.MP%CELL(IC)%SOLID .AND. .NOT.MP%CELL(IC)%EXTERIOR) RETURN   ! thin obstruction: FX = 0
   SELECT CASE(BCG%IOR)
      CASE( 1) ; UIN =  UU(BCG%IIG-1,BCG%JJG,BCG%KKG) ; A = DYP(BCG%JJG)*DZP(BCG%KKG)
      CASE(-1) ; UIN = -UU(BCG%IIG,BCG%JJG,BCG%KKG)   ; A = DYP(BCG%JJG)*DZP(BCG%KKG)
      CASE( 2) ; UIN =  VV(BCG%IIG,BCG%JJG-1,BCG%KKG) ; A = DXP(BCG%IIG)*DZP(BCG%KKG)
      CASE(-2) ; UIN = -VV(BCG%IIG,BCG%JJG,BCG%KKG)   ; A = DXP(BCG%IIG)*DZP(BCG%KKG)
      CASE( 3) ; UIN =  WW(BCG%IIG,BCG%JJG,BCG%KKG-1) ; A = DXP(BCG%IIG)*DYP(BCG%JJG)
      CASE(-3) ; UIN = -WW(BCG%IIG,BCG%JJG,BCG%KKG)   ; A = DXP(BCG%IIG)*DYP(BCG%JJG)
   END SELECT
   IF (NM>NMESHES .AND. WC%BOUNDARY_TYPE==OPEN_BOUNDARY) THEN   ! open face of a fine box: DENSITY applies the box's own face flux FX (limiter on the box's cells and ghosts), not the parent wall's RHO_F
      SELECT CASE(BCG%IOR)
         CASE( 1) ; FXN = PFX(BCG%IIG-1,BCG%JJG,BCG%KKG,1:N_TRACKED_SPECIES)
         CASE(-1) ; FXN = PFX(BCG%IIG,BCG%JJG,BCG%KKG,1:N_TRACKED_SPECIES)
         CASE( 2) ; FXN = PFY(BCG%IIG,BCG%JJG-1,BCG%KKG,1:N_TRACKED_SPECIES)
         CASE(-2) ; FXN = PFY(BCG%IIG,BCG%JJG,BCG%KKG,1:N_TRACKED_SPECIES)
         CASE( 3) ; FXN = PFZ(BCG%IIG,BCG%JJG,BCG%KKG-1,1:N_TRACKED_SPECIES)
         CASE(-3) ; FXN = PFZ(BCG%IIG,BCG%JJG,BCG%KKG,1:N_TRACKED_SPECIES)
      END SELECT
      BND_RATE(0,NM,ST) = BND_RATE(0,NM,ST) + A*SUM(FXN)*UIN
      BND_RATE(1:N_TRACKED_SPECIES,NM,ST) = BND_RATE(1:N_TRACKED_SPECIES,NM,ST) + A*(FXN*UIN)
      BND_RATE(N_TRACKED_SPECIES+1,NM,ST) = BND_RATE(N_TRACKED_SPECIES+1,NM,ST) + A*SUM(FXN)*ABS(UIN)
   ELSEIF (NM>NMESHES .AND. WC%BOUNDARY_TYPE==SOLID_BOUNDARY .AND. ANY(B1%M_DOT_G_PP_ADJUST(1:N_TRACKED_SPECIES)/=0._EB)) THEN   ! hidden fine burner face: DENSITY applies the parent's M_DOT_G_PP_ADJUST (burner_overrides)
      BND_RATE(0,NM,ST) = BND_RATE(0,NM,ST) + A*SUM(B1%M_DOT_G_PP_ADJUST(1:N_TRACKED_SPECIES))
      BND_RATE(1:N_TRACKED_SPECIES,NM,ST) = BND_RATE(1:N_TRACKED_SPECIES,NM,ST) + A*B1%M_DOT_G_PP_ADJUST(1:N_TRACKED_SPECIES)
      BND_RATE(N_TRACKED_SPECIES+1,NM,ST) = BND_RATE(N_TRACKED_SPECIES+1,NM,ST) + A*SUM(B1%M_DOT_G_PP_ADJUST(1:N_TRACKED_SPECIES))
   ELSE
   BND_RATE(0,NM,ST) = BND_RATE(0,NM,ST) + A*B1%RHO_F*UIN
   BND_RATE(1:N_TRACKED_SPECIES,NM,ST) = BND_RATE(1:N_TRACKED_SPECIES,NM,ST) + A*(B1%RHO_F*B1%ZZ_F*UIN - B1%RHO_D_DZDN_F)
   IF (WC%BOUNDARY_TYPE==OPEN_BOUNDARY .OR. SURFACE(B1%SURF_INDEX)%SPECIES_BC_INDEX==SPECIFIED_MASS_FLUX) &
      BND_RATE(N_TRACKED_SPECIES+1,NM,ST) = BND_RATE(N_TRACKED_SPECIES+1,NM,ST) + A*B1%RHO_F*ABS(UIN)   ! through-flow (in plus out) of OPEN and mass-flux walls: > 0 marks an open case
   ENDIF
   END ASSOCIATE
   END SUBROUTINE ONE_WALL

   !> Key of the level-0 wall face (mesh NM0, gas cell I,J,K, IOR) as an exactly representable number.
   REAL(EB) FUNCTION WKEY(NM0,I,J,K,IOR)
   INTEGER, INTENT(IN) :: NM0,I,J,K,IOR
   WKEY = REAL((((INT(NM0,8)*1000_8+I)*1000_8+J)*1000_8+K)*8_8+IOR+3,EB)
   END FUNCTION WKEY

   !> Level-0 wall IW of local mesh MP, covered by a finer level: its stage state, for the fine rank (see PUB).
   SUBROUTINE PUBLISH(MP,IW)
   TYPE(MESH_TYPE), INTENT(IN) :: MP
   INTEGER, INTENT(IN) :: IW
   INTEGER :: IC,NF
   NF = 4+3*N_TRACKED_SPECIES
   ASSOCIATE(WC=>MP%WALL(IW),BCP=>MP%BOUNDARY_COORD(MP%WALL(IW)%BC_INDEX),B1=>MP%BOUNDARY_PROP1(MP%WALL(IW)%B1_INDEX))
   IF (WC%BOUNDARY_TYPE/=SOLID_BOUNDARY .AND. WC%BOUNDARY_TYPE/=OPEN_BOUNDARY) RETURN
   IC = MP%CELL_INDEX(BCP%II,BCP%JJ,BCP%KK)
   IF (WC%BOUNDARY_TYPE==SOLID_BOUNDARY .AND. .NOT.MP%CELL(IC)%SOLID .AND. .NOT.MP%CELL(IC)%EXTERIOR) RETURN
   CALL GROW(PUB,NPUB(ST),NF,ST)
   NPUB(ST) = NPUB(ST)+1
   PUB(1,NPUB(ST),ST) = WKEY(NM,BCP%IIG,BCP%JJG,BCP%KKG,BCP%IOR)
   PUB(2,NPUB(ST),ST) = B1%RHO_F
   PUB(3,NPUB(ST),ST) = MERGE(1._EB,0._EB,WC%BOUNDARY_TYPE==OPEN_BOUNDARY .OR. SURFACE(B1%SURF_INDEX)%SPECIES_BC_INDEX==SPECIFIED_MASS_FLUX)
   PUB(4:3+N_TRACKED_SPECIES,NPUB(ST),ST) = B1%ZZ_F(1:N_TRACKED_SPECIES)
   PUB(4+N_TRACKED_SPECIES:3+2*N_TRACKED_SPECIES,NPUB(ST),ST) = B1%RHO_D_DZDN_F(1:N_TRACKED_SPECIES)
   PUB(4+2*N_TRACKED_SPECIES:3+3*N_TRACKED_SPECIES,NPUB(ST),ST) = B1%M_DOT_G_PP_ADJUST(1:N_TRACKED_SPECIES)   ! burner face: the fine rank counts A*M_DOT as ONE_WALL does
   PUB(NF,NPUB(ST),ST) = MERGE(1._EB,0._EB,WC%BOUNDARY_TYPE==SOLID_BOUNDARY)
   END ASSOCIATE
   END SUBROUTINE PUBLISH

   !> Fine wall BCG whose level-0 parent mesh NMP is on another rank: record A*UIN and A with the key of the parent face (gas cell of mesh NMP on the gas side of the face, IOR).
   SUBROUTINE PEND_WALL(NMP,BCG,DXP,DYP,DZP)
   INTEGER, INTENT(IN) :: NMP
   TYPE(BOUNDARY_COORD_TYPE), INTENT(IN) :: BCG
   REAL(EB), INTENT(IN) :: DXP(0:),DYP(0:),DZP(0:)
   INTEGER :: I,J,K,NZ
   REAL(EB) :: UIN,A,X,Y,Z,D0(3),FXN(N_TRACKED_SPECIES)
   ASSOCIATE(MP=>MESHES(NMP))
   D0 = (/(MP%XF-MP%XS)/MP%IBAR,(MP%YF-MP%YS)/MP%JBAR,(MP%ZF-MP%ZS)/MP%KBAR/)
   X = BCG%X ; Y = BCG%Y ; Z = BCG%Z
   SELECT CASE(BCG%IOR)   ! IOR points into the gas: the gas cell is on the +IOR side of the face
      CASE( 1) ; UIN =  UU(BCG%IIG-1,BCG%JJG,BCG%KKG) ; A = DYP(BCG%JJG)*DZP(BCG%KKG) ; X = X+0.5_EB*D0(1)
      CASE(-1) ; UIN = -UU(BCG%IIG,BCG%JJG,BCG%KKG)   ; A = DYP(BCG%JJG)*DZP(BCG%KKG) ; X = X-0.5_EB*D0(1)
      CASE( 2) ; UIN =  VV(BCG%IIG,BCG%JJG-1,BCG%KKG) ; A = DXP(BCG%IIG)*DZP(BCG%KKG) ; Y = Y+0.5_EB*D0(2)
      CASE(-2) ; UIN = -VV(BCG%IIG,BCG%JJG,BCG%KKG)   ; A = DXP(BCG%IIG)*DZP(BCG%KKG) ; Y = Y-0.5_EB*D0(2)
      CASE( 3) ; UIN =  WW(BCG%IIG,BCG%JJG,BCG%KKG-1) ; A = DXP(BCG%IIG)*DYP(BCG%JJG) ; Z = Z+0.5_EB*D0(3)
      CASE(-3) ; UIN = -WW(BCG%IIG,BCG%JJG,BCG%KKG)   ; A = DXP(BCG%IIG)*DYP(BCG%JJG) ; Z = Z-0.5_EB*D0(3)
   END SELECT
   I = FLOOR((X-MP%XS)/D0(1))+1 ; J = FLOOR((Y-MP%YS)/D0(2))+1 ; K = FLOOR((Z-MP%ZS)/D0(3))+1
   END ASSOCIATE
   SELECT CASE(BCG%IOR)   ! the box's own face flux, used if the parent is an OPEN wall (ONE_WALL: DENSITY applies FX, not the parent's RHO_F)
      CASE( 1) ; FXN = PFX(BCG%IIG-1,BCG%JJG,BCG%KKG,1:N_TRACKED_SPECIES)
      CASE(-1) ; FXN = PFX(BCG%IIG,BCG%JJG,BCG%KKG,1:N_TRACKED_SPECIES)
      CASE( 2) ; FXN = PFY(BCG%IIG,BCG%JJG-1,BCG%KKG,1:N_TRACKED_SPECIES)
      CASE(-2) ; FXN = PFY(BCG%IIG,BCG%JJG,BCG%KKG,1:N_TRACKED_SPECIES)
      CASE( 3) ; FXN = PFZ(BCG%IIG,BCG%JJG,BCG%KKG-1,1:N_TRACKED_SPECIES)
      CASE(-3) ; FXN = PFZ(BCG%IIG,BCG%JJG,BCG%KKG,1:N_TRACKED_SPECIES)
   END SELECT
   NZ = N_TRACKED_SPECIES
   CALL GROW(PEND,NPEND(ST),4+NZ,ST)
   NPEND(ST) = NPEND(ST)+1
   PEND(1,NPEND(ST),ST) = WKEY(NMP,I,J,K,BCG%IOR) ; PEND(2,NPEND(ST),ST) = A*UIN ; PEND(3,NPEND(ST),ST) = A
   PEND(4:3+NZ,NPEND(ST),ST) = A*(FXN*UIN) ; PEND(4+NZ,NPEND(ST),ST) = A*SUM(FXN)*ABS(UIN)
   END SUBROUTINE PEND_WALL

   SUBROUTINE GROW(AR,N,NF,ST)
   REAL(EB), ALLOCATABLE, INTENT(INOUT) :: AR(:,:,:)
   INTEGER, INTENT(IN) :: N,NF,ST
   REAL(EB), ALLOCATABLE :: T(:,:,:)
   IF (.NOT.ALLOCATED(AR)) THEN ; ALLOCATE(AR(NF,1024,2)) ; AR = 0._EB ; ENDIF
   IF (N+1>SIZE(AR,2)) THEN
      ALLOCATE(T(NF,2*SIZE(AR,2),2)) ; T = 0._EB ; T(:,1:SIZE(AR,2),:) = AR ; CALL MOVE_ALLOC(T,AR)
   ENDIF
   END SUBROUTINE GROW

END SUBROUTINE BND_STAGE_RATE

!> Leaf wall inflow rate of the last step (kg/s, rank-local): the mean of the predictor and corrector rates (DENSITY averages the two stages);
!> R(0) total, R(N) tracked species N = 1..NS (0 beyond N_TRACKED_SPECIES), R(NS+1) through-flow (inflow plus outflow). The driver multiplies by DT.
SUBROUTINE FDS_P_BND_RATE(NS,R) BIND(C,NAME='fds_p_bnd_rate')
INTEGER(C_INT), VALUE :: NS
REAL(C_DOUBLE), INTENT(OUT) :: R(0:NS+1)
INTEGER :: NM
R = 0._EB
IF (.NOT.ALLOCATED(BND_RATE)) RETURN
DO NM=LOWER_MESH_INDEX,SIZE(BND_RATE,2)   ! level-0 meshes of this rank, then the fine boxes called in this step (both stages)
   IF (NM>UPPER_MESH_INDEX .AND. NM<=NMESHES) CYCLE
   IF (NM>NMESHES .AND. ANY(BND_STAMP(NM,:)/=ICYC)) CYCLE
   R(NS+1) = R(NS+1) + 0.5_EB*(BND_RATE(N_TRACKED_SPECIES+1,NM,1)+BND_RATE(N_TRACKED_SPECIES+1,NM,2))
   R(0:MIN(NS,N_TRACKED_SPECIES)) = R(0:MIN(NS,N_TRACKED_SPECIES)) + 0.5_EB*(BND_RATE(0:MIN(NS,N_TRACKED_SPECIES),NM,1)+BND_RATE(0:MIN(NS,N_TRACKED_SPECIES),NM,2))
ENDDO
IF (N_MPI_PROCESSES>1) CALL REMOTE_PARENT_RATE()   ! collective: every rank calls FDS_P_BND_RATE once per step

CONTAINS

!> Rate of the fine walls whose parent mesh is on another rank: both stages, state of the parent wall from the gathered PUB records.
SUBROUTINE REMOTE_PARENT_RATE()
USE MPI_F08
INTEGER :: ST,I,J,N,NF,IERR,NTOT
INTEGER, ALLOCATABLE :: CNT(:),DSP(:)
REAL(EB), ALLOCATABLE :: SB(:,:),RB(:,:),RS(:)
REAL(EB) :: KEY,UA,A
INTEGER :: NQ
NF = 4+3*N_TRACKED_SPECIES
ALLOCATE(CNT(0:N_MPI_PROCESSES-1),DSP(0:N_MPI_PROCESSES-1),RS(0:NS+1))
DO ST=1,2
   N = 0 ; IF (ALLOCATED(PUB) .AND. PUB_ICYC(ST)==ICYC) N = NPUB(ST)
   ALLOCATE(SB(NF,MAX(1,N)))
   IF (N>0) SB(:,1:N) = PUB(:,1:N,ST)
   CNT = 0 ; CNT(MY_RANK) = N*NF
   CALL MPI_ALLGATHER(MPI_IN_PLACE,1,MPI_INTEGER,CNT,1,MPI_INTEGER,MPI_COMM_WORLD,IERR)
   DSP(0) = 0 ; DO I=1,N_MPI_PROCESSES-1 ; DSP(I) = DSP(I-1)+CNT(I-1) ; ENDDO
   NTOT = SUM(CNT)/NF
   ALLOCATE(RB(NF,MAX(1,NTOT)))
   CALL MPI_ALLGATHERV(SB,N*NF,MPI_DOUBLE_PRECISION,RB,CNT,DSP,MPI_DOUBLE_PRECISION,MPI_COMM_WORLD,IERR)
   IF (ALLOCATED(PEND) .AND. PEND_ICYC(ST)==ICYC) THEN
      DO I=1,NPEND(ST)
         KEY = PEND(1,I,ST) ; UA = PEND(2,I,ST) ; A = PEND(3,I,ST)
         DO J=1,NTOT   ! linear search: the number of covered walls with a fine child on another rank is small
            IF (RB(1,J)/=KEY) CYCLE
            RS = 0._EB
            IF (RB(NF,J)==0._EB) THEN   ! OPEN parent: the fine box's own face flux (as ONE_WALL)
               RS(0) = SUM(PEND(4:3+N_TRACKED_SPECIES,I,ST))
               DO NQ=1,MIN(NS,N_TRACKED_SPECIES) ; RS(NQ) = PEND(3+NQ,I,ST) ; ENDDO
               RS(NS+1) = PEND(4+N_TRACKED_SPECIES,I,ST)
            ELSEIF (RB(NF,J)>0._EB .AND. ANY(RB(4+2*N_TRACKED_SPECIES:3+3*N_TRACKED_SPECIES,J)/=0._EB)) THEN   ! hidden fine burner face (ONE_WALL): A*M_DOT_G_PP_ADJUST
               RS(0) = A*SUM(RB(4+2*N_TRACKED_SPECIES:3+3*N_TRACKED_SPECIES,J))
               DO NQ=1,MIN(NS,N_TRACKED_SPECIES) ; RS(NQ) = A*RB(3+2*N_TRACKED_SPECIES+NQ,J) ; ENDDO
               RS(NS+1) = RS(0)
            ELSE
            RS(0) = RB(2,J)*UA
            DO NQ=1,MIN(NS,N_TRACKED_SPECIES) ; RS(NQ) = RB(2,J)*RB(3+NQ,J)*UA - A*RB(3+N_TRACKED_SPECIES+NQ,J) ; ENDDO
            RS(NS+1) = RB(3,J)*RB(2,J)*ABS(UA)
            ENDIF
            R(NS+1) = R(NS+1) + 0.5_EB*RS(NS+1)
            R(0:MIN(NS,N_TRACKED_SPECIES)) = R(0:MIN(NS,N_TRACKED_SPECIES)) + 0.5_EB*RS(0:MIN(NS,N_TRACKED_SPECIES))
            EXIT
         ENDDO
      ENDDO
   ENDIF
   DEALLOCATE(SB,RB)
ENDDO
END SUBROUTINE REMOTE_PARENT_RATE
END SUBROUTINE FDS_P_BND_RATE

!> Species production per unit heat release (kg/J), for the two-level species balance: COMBUSTION_MODEL sets Q = -RHO*SUM(H_F*DZ)/DT with DZ = NU_MW_O_MW_F*DZ_F for one
!> reaction, so RHO*DZ(N)/DT = C(N)*Q with C(N) = NU_MW_O_MW_F(N)/(-SUM(H_F*NU_MW_O_MW_F)). Returns 0 (C = 0) unless there is exactly one reaction.
FUNCTION FDS_P_REAC_COEF(NS,C) BIND(C,NAME='fds_p_reac_coef') RESULT(OK)
USE TYPES, ONLY: REACTION,SPECIES_MIXTURE
INTEGER(C_INT), VALUE :: NS
REAL(C_DOUBLE), INTENT(OUT) :: C(NS)
INTEGER(C_INT) :: OK
REAL(EB) :: DEN
C = 0._EB ; OK = 0
IF (N_REACTIONS/=1 .OR. NS/=N_TRACKED_SPECIES) RETURN
DEN = -SUM(SPECIES_MIXTURE(1:N_TRACKED_SPECIES)%H_F*REACTION(1)%NU_MW_O_MW_F(1:N_TRACKED_SPECIES))
IF (ABS(DEN)<=0._EB) RETURN
C = REACTION(1)%NU_MW_O_MW_F(1:N_TRACKED_SPECIES)/DEN ; OK = 1
END FUNCTION FDS_P_REAC_COEF

