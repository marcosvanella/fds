!> The per-cell and per-wall terms that DIVERGENCE_PART_1 adds to DSUM, PSUM, USUM (divg.f90, "IF_PRESSURE_ZONES"), with the same expressions and the same skip rules,
!> WITHOUT accumulating them: the driver sums them in fixed point (D-028, decomposition independent). Call right after DIVERGENCE_PART_1 of mesh NM (R_PBAR and WORK1=RTRM
!> are the ones that kernel left). CZONE(1:IBAR*JBAR*KBAR) (I fastest) is 0 for skipped cells; WZONE(1:NW) likewise for walls.
SUBROUTINE FDS_P_ZONE_TERMS(NM,CZONE,DTERM,PTERM,WZONE,WTERM) BIND(C,NAME='fds_p_zone_terms')
INTEGER(C_INT), VALUE :: NM
INTEGER(C_INT), INTENT(OUT) :: CZONE(*),WZONE(*)
REAL(C_DOUBLE), INTENT(OUT) :: DTERM(*),PTERM(*),WTERM(*)
TYPE(MESH_TYPE), POINTER :: M
REAL(EB), POINTER, DIMENSION(:,:,:) :: DP
REAL(EB) :: VC,VC1
INTEGER :: I,J,K,IPZ,IW,L
M => MESHES(NM)
IF (PREDICTOR) THEN ; DP => M%DS ; ELSE ; DP => M%D ; ENDIF
L = 0
DO K=1,M%KBAR
   DO J=1,M%JBAR
      VC1 = M%DY(J)*M%DZ(K)
      DO I=1,M%IBAR
         L = L+1
         CZONE(L) = 0 ; DTERM(L) = 0._EB ; PTERM(L) = 0._EB
         IF (M%INTERPOLATED_MESH(I,J,K)>0) CYCLE
         IPZ = M%PRESSURE_ZONE(I,J,K)
         IF (IPZ<1) CYCLE
         IF (M%CELL(M%CELL_INDEX(I,J,K))%SOLID) CYCLE
         VC = M%DX(I)*M%RC(I)*VC1
         CZONE(L) = IPZ
         DTERM(L) = VC*DP(I,J,K)
         PTERM(L) = VC*(M%R_PBAR(K,IPZ)*1._EB-M%WORK1(I,J,K))
      ENDDO
   ENDDO
ENDDO
DO IW=1,M%N_EXTERNAL_WALL_CELLS+M%N_INTERNAL_WALL_CELLS
   WZONE(IW) = 0 ; WTERM(IW) = 0._EB
   ASSOCIATE (WC=>M%WALL(IW),BC=>M%BOUNDARY_COORD(M%WALL(IW)%BC_INDEX),B1=>M%BOUNDARY_PROP1(M%WALL(IW)%B1_INDEX))
   IF (M%INTERPOLATED_MESH(BC%IIG,BC%JJG,BC%KKG)>0) CYCLE
   IPZ = B1%PRESSURE_ZONE
   IF (IPZ<1) CYCLE
   IF (WC%BOUNDARY_TYPE/=SOLID_BOUNDARY) CYCLE
   WZONE(IW) = IPZ
   IF (PREDICTOR) WTERM(IW) = B1%U_NORMAL_S*B1%AREA
   IF (CORRECTOR) WTERM(IW) = B1%U_NORMAL  *B1%AREA
   END ASSOCIATE
ENDDO
END SUBROUTINE FDS_P_ZONE_TERMS

!> Cell volume terms of the pressure-zone volume (main.f90, P_ZONE(IZ)%VOLUME): zone index (0 = not counted) and DX*RC*DY*DZ with the same expression.
SUBROUTINE FDS_P_ZONE_VOLUME_TERMS(NM,CZONE,VTERM) BIND(C,NAME='fds_p_zone_volume_terms')
INTEGER(C_INT), VALUE :: NM
INTEGER(C_INT), INTENT(OUT) :: CZONE(*)
REAL(C_DOUBLE), INTENT(OUT) :: VTERM(*)
TYPE(MESH_TYPE), POINTER :: M
INTEGER :: I,J,K,L,IZ
M => MESHES(NM)
L = 0
DO K=1,M%KBAR
   DO J=1,M%JBAR
      DO I=1,M%IBAR
         L = L+1
         CZONE(L) = 0 ; VTERM(L) = 0._EB
         IZ = M%PRESSURE_ZONE(I,J,K)
         IF (IZ==0) CYCLE
         IF (M%CELL(M%CELL_INDEX(I,J,K))%SOLID) CYCLE
         CZONE(L) = IZ
         VTERM(L) = M%DX(I)*M%RC(I)*M%DY(J)*M%DZ(K)
      ENDDO
   ENDDO
ENDDO
END SUBROUTINE FDS_P_ZONE_VOLUME_TERMS

