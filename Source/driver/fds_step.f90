!> Pending reaction source of box NM of any level: M_DOT_PPP(:,:,:,1:N_TRACKED_SPECIES) and D_SOURCE (component N_TRACKED_SPECIES+1) as one (0:IBP1,0:JBP1,0:KBP1,N_TRACKED_SPECIES+1) block.
!> MODE=0 reads the box into BUF, MODE=1 writes BUF into the box. NTOT = size of BUF; returns N_TRACKED_SPECIES+1 components, 0 when the box has no reaction arrays, -1 when NTOT does not match.
!> The driver keeps the pending source of a fine level over a regrid (the rebuilt box object starts with zeros, so COMBUSTION's source of the last step would be lost).
FUNCTION FDS_P_PEND(NM,MODE,BUF,NTOT) BIND(C,NAME='fds_p_pend') RESULT(NC)
INTEGER(C_INT), VALUE :: NM,MODE
INTEGER(C_LONG), VALUE :: NTOT
REAL(C_DOUBLE), INTENT(INOUT) :: BUF(NTOT)
INTEGER(C_INT) :: NC
TYPE(MESH_TYPE), POINTER :: M
INTEGER :: NP
M => BOX_OBJ(NM)
NC = 0
IF (.NOT.ALLOCATED(M%M_DOT_PPP) .OR. .NOT.ALLOCATED(M%D_SOURCE)) RETURN
NP = SIZE(M%D_SOURCE)
NC = N_TRACKED_SPECIES+1
IF (NTOT/=INT(NP,C_LONG)*NC) THEN ; NC = -1 ; RETURN ; ENDIF
IF (MODE==0) THEN
   BUF(1:NP*N_TRACKED_SPECIES) = RESHAPE(M%M_DOT_PPP,(/NP*N_TRACKED_SPECIES/))
   BUF(NP*N_TRACKED_SPECIES+1:NTOT) = RESHAPE(M%D_SOURCE,(/NP/))
ELSE
   M%M_DOT_PPP = RESHAPE(BUF(1:NP*N_TRACKED_SPECIES),SHAPE(M%M_DOT_PPP))
