!> The boundary-value block that follows the Poisson solve in PRESSURE_SOLVER_FFT (pres.f90, "Apply boundary conditions to H"), for the PHYSICAL faces only:
!> FLAGS(1:6) = x-low, x-high, y-low, y-high, z-low, z-high. Faces between boxes and periodic images are filled by the AMReX ghost fill instead. HP = H (predictor) or HS.
SUBROUTINE FDS_P_H_GHOST(NM,PRED,FLAGS) BIND(C,NAME='fds_p_h_ghost')
INTEGER(C_INT), VALUE :: NM,PRED
INTEGER(C_INT), INTENT(IN) :: FLAGS(6)
TYPE(MESH_TYPE), POINTER :: M
REAL(EB), POINTER, DIMENSION(:,:,:) :: HP
INTEGER :: I,J,K,IBAR,JBAR,KBAR,IBP1,JBP1,KBP1,LBC,MBC,NBC
M => MESHES(NM)
IF (PRED/=0) THEN ; HP => M%H ; ELSE ; HP => M%HS ; ENDIF
IBAR=M%IBAR ; JBAR=M%JBAR ; KBAR=M%KBAR ; IBP1=IBAR+1 ; JBP1=JBAR+1 ; KBP1=KBAR+1
LBC=M%LBC ; MBC=M%MBC ; NBC=M%NBC
DO K=1,KBAR
   DO J=1,JBAR
      IF (FLAGS(1)/=0) THEN
         IF (LBC==3 .OR. LBC==4)             HP(0,J,K)    = HP(1,J,K)    - M%DXI*M%BXS(J,K)
         IF (LBC==1 .OR. LBC==2)             HP(0,J,K)    =-HP(1,J,K)    + 2._EB*M%BXS(J,K)
         IF (LBC==5 .OR. LBC==6)             HP(0,J,K)    = HP(1,J,K)
         IF (LBC==0)                         HP(0,J,K)    = HP(IBAR,J,K)
      ENDIF
      IF (FLAGS(2)/=0) THEN
         IF (LBC==3 .OR. LBC==2 .OR. LBC==6) HP(IBP1,J,K) = HP(IBAR,J,K) + M%DXI*M%BXF(J,K)
         IF (LBC==1 .OR. LBC==4 .OR. LBC==5) HP(IBP1,J,K) =-HP(IBAR,J,K) + 2._EB*M%BXF(J,K)
         IF (LBC==0)                         HP(IBP1,J,K) = HP(1,J,K)
      ENDIF
   ENDDO
ENDDO
DO K=1,KBAR
   DO I=1,IBAR
      IF (FLAGS(3)/=0) THEN
         IF (MBC==3 .OR. MBC==4) HP(I,0,K)    = HP(I,1,K)    - M%DETA*M%BYS(I,K)
         IF (MBC==1 .OR. MBC==2) HP(I,0,K)    =-HP(I,1,K)    + 2._EB*M%BYS(I,K)
         IF (MBC==0)             HP(I,0,K)    = HP(I,JBAR,K)
      ENDIF
      IF (FLAGS(4)/=0) THEN
         IF (MBC==3 .OR. MBC==2) HP(I,JBP1,K) = HP(I,JBAR,K) + M%DETA*M%BYF(I,K)
         IF (MBC==1 .OR. MBC==4) HP(I,JBP1,K) =-HP(I,JBAR,K) + 2._EB*M%BYF(I,K)
         IF (MBC==0)             HP(I,JBP1,K) = HP(I,1,K)
      ENDIF
   ENDDO
ENDDO
DO J=1,JBAR
   DO I=1,IBAR
      IF (FLAGS(5)/=0) THEN
         IF (NBC==3 .OR. NBC==4) HP(I,J,0)    = HP(I,J,1)    - M%DZETA*M%BZS(I,J)
         IF (NBC==1 .OR. NBC==2) HP(I,J,0)    =-HP(I,J,1)    + 2._EB*M%BZS(I,J)
         IF (NBC==0)             HP(I,J,0)    = HP(I,J,KBAR)
      ENDIF
      IF (FLAGS(6)/=0) THEN
         IF (NBC==3 .OR. NBC==2) HP(I,J,KBP1) = HP(I,J,KBAR) + M%DZETA*M%BZF(I,J)
         IF (NBC==1 .OR. NBC==4) HP(I,J,KBP1) =-HP(I,J,KBAR) + 2._EB*M%BZF(I,J)
         IF (NBC==0)             HP(I,J,KBP1) = HP(I,J,1)
      ENDIF
   ENDDO
ENDDO
END SUBROUTINE FDS_P_H_GHOST

