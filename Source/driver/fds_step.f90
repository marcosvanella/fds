!> Copy Poisson face boundary array of mesh NM into BUF (FDS interior face cells only).
!> FACE: 0=xlo(BXS),1=xhi(BXF),2=ylo(BYS),3=yhi(BYF),4=zlo(BZS),5=zhi(BZF).
!> Layout: x-faces J-fast then K (JBAR*KBAR); y-faces I-fast then K; z-faces I-fast then J.
!> NEXPECT must match that count. IERR: 0 ok, 3 size mismatch, 4 bad FACE.
SUBROUTINE FDS_P_GET_BCFACE(NM,FACE,BUF,NEXPECT,IERR) BIND(C,NAME='fds_p_get_bcface')
INTEGER(C_INT), VALUE :: NM,FACE
REAL(C_DOUBLE), INTENT(OUT) :: BUF(*)
INTEGER(C_LONG), VALUE :: NEXPECT
INTEGER(C_INT), INTENT(OUT) :: IERR
TYPE(MESH_TYPE), POINTER :: M
INTEGER :: I,J,K,N,IBAR,JBAR,KBAR
CALL FDS_HOOK_L0_ONLY('fds_p_get_bcface',NM,NMESHES)
M => BOX_OBJ(NM)
IBAR=M%IBAR ; JBAR=M%JBAR ; KBAR=M%KBAR
IERR = 0 ; N = 0
SELECT CASE(FACE)
CASE(0) ! BXS(J,K)
   IF (NEXPECT/=INT(JBAR,C_LONG)*INT(KBAR,C_LONG)) THEN ; IERR=3 ; RETURN ; ENDIF
   DO K=1,KBAR ; DO J=1,JBAR ; N=N+1 ; BUF(N)=M%BXS(J,K) ; ENDDO ; ENDDO
CASE(1) ! BXF
   IF (NEXPECT/=INT(JBAR,C_LONG)*INT(KBAR,C_LONG)) THEN ; IERR=3 ; RETURN ; ENDIF
   DO K=1,KBAR ; DO J=1,JBAR ; N=N+1 ; BUF(N)=M%BXF(J,K) ; ENDDO ; ENDDO
CASE(2) ! BYS(I,K)
   IF (NEXPECT/=INT(IBAR,C_LONG)*INT(KBAR,C_LONG)) THEN ; IERR=3 ; RETURN ; ENDIF
   DO K=1,KBAR ; DO I=1,IBAR ; N=N+1 ; BUF(N)=M%BYS(I,K) ; ENDDO ; ENDDO
CASE(3) ! BYF
   IF (NEXPECT/=INT(IBAR,C_LONG)*INT(KBAR,C_LONG)) THEN ; IERR=3 ; RETURN ; ENDIF
   DO K=1,KBAR ; DO I=1,IBAR ; N=N+1 ; BUF(N)=M%BYF(I,K) ; ENDDO ; ENDDO
CASE(4) ! BZS(I,J)
   IF (NEXPECT/=INT(IBAR,C_LONG)*INT(JBAR,C_LONG)) THEN ; IERR=3 ; RETURN ; ENDIF
   DO J=1,JBAR ; DO I=1,IBAR ; N=N+1 ; BUF(N)=M%BZS(I,J) ; ENDDO ; ENDDO
CASE(5) ! BZF
   IF (NEXPECT/=INT(IBAR,C_LONG)*INT(JBAR,C_LONG)) THEN ; IERR=3 ; RETURN ; ENDIF
   DO J=1,JBAR ; DO I=1,IBAR ; N=N+1 ; BUF(N)=M%BZF(I,J) ; ENDDO ; ENDDO
CASE DEFAULT
   IERR = 4
END SELECT
END SUBROUTINE FDS_P_GET_BCFACE


!> The boundary-value block that follows the Poisson solve in PRESSURE_SOLVER_FFT (pres.f90, "Apply boundary conditions to H"), for the PHYSICAL faces only:
!> FLAGS(1:6) = x-low, x-high, y-low, y-high, z-low, z-high. Faces between boxes and periodic images are filled by the AMReX ghost fill instead. HP = H (predictor) or HS.
SUBROUTINE FDS_P_H_GHOST(NM,PRED,FLAGS) BIND(C,NAME='fds_p_h_ghost')
INTEGER(C_INT), VALUE :: NM,PRED
INTEGER(C_INT), INTENT(IN) :: FLAGS(6)
TYPE(MESH_TYPE), POINTER :: M
REAL(EB), POINTER, DIMENSION(:,:,:) :: HP
INTEGER :: I,J,K,IBAR,JBAR,KBAR,IBP1,JBP1,KBP1,LBC,MBC,NBC
CALL FDS_HOOK_L0_ONLY('fds_p_h_ghost',NM,NMESHES)
M => BOX_OBJ(NM)
IF (PRED/=0) THEN ; HP => M%H ; ELSE ; HP => M%HS ; ENDIF
IBAR=M%IBAR ; JBAR=M%JBAR ; KBAR=M%KBAR ; IBP1=IBAR+1 ; JBP1=JBAR+1 ; KBP1=KBAR+1
LBC=M%LBC ; MBC=M%MBC ; NBC=M%NBC
DO K=1,KBAR
   DO J=1,JBAR
      IF (FLAGS(1)/=0) THEN
         IF (LBC==3 .OR. LBC==4)             HP(0,J,K)    = HP(1,J,K)    - M%DXI*M%BXS(J,K)
         IF (LBC==1 .OR. LBC==2)             HP(0,J,K)    =-HP(1,J,K)    + 2._EB*M%BXS(J,K)
         IF (LBC==5 .OR. LBC==6)             HP(0,J,K)    = HP(1,J,K)
         IF (LBC==0)                         HP(0,J,K)    = HP(IBAR,J,K)
      ENDIF
      IF (FLAGS(2)/=0) THEN
         IF (LBC==3 .OR. LBC==2 .OR. LBC==6) HP(IBP1,J,K) = HP(IBAR,J,K) + M%DXI*M%BXF(J,K)
         IF (LBC==1 .OR. LBC==4 .OR. LBC==5) HP(IBP1,J,K) =-HP(IBAR,J,K) + 2._EB*M%BXF(J,K)
         IF (LBC==0)                         HP(IBP1,J,K) = HP(1,J,K)
      ENDIF
   ENDDO
ENDDO
DO K=1,KBAR
   DO I=1,IBAR
      IF (FLAGS(3)/=0) THEN
         IF (MBC==3 .OR. MBC==4) HP(I,0,K)    = HP(I,1,K)    - M%DETA*M%BYS(I,K)
         IF (MBC==1 .OR. MBC==2) HP(I,0,K)    =-HP(I,1,K)    + 2._EB*M%BYS(I,K)
         IF (MBC==0)             HP(I,0,K)    = HP(I,JBAR,K)
      ENDIF
      IF (FLAGS(4)/=0) THEN
         IF (MBC==3 .OR. MBC==2) HP(I,JBP1,K) = HP(I,JBAR,K) + M%DETA*M%BYF(I,K)
         IF (MBC==1 .OR. MBC==4) HP(I,JBP1,K) =-HP(I,JBAR,K) + 2._EB*M%BYF(I,K)
         IF (MBC==0)             HP(I,JBP1,K) = HP(I,1,K)
      ENDIF
   ENDDO
ENDDO
DO J=1,JBAR
   DO I=1,IBAR
      IF (FLAGS(5)/=0) THEN
         IF (NBC==3 .OR. NBC==4) HP(I,J,0)    = HP(I,J,1)    - M%DZETA*M%BZS(I,J)
         IF (NBC==1 .OR. NBC==2) HP(I,J,0)    =-HP(I,J,1)    + 2._EB*M%BZS(I,J)
         IF (NBC==0)             HP(I,J,0)    = HP(I,J,KBAR)
      ENDIF
      IF (FLAGS(6)/=0) THEN
         IF (NBC==3 .OR. NBC==2) HP(I,J,KBP1) = HP(I,J,KBAR) + M%DZETA*M%BZF(I,J)
         IF (NBC==1 .OR. NBC==4) HP(I,J,KBP1) =-HP(I,J,KBAR) + 2._EB*M%BZF(I,J)
         IF (NBC==0)             HP(I,J,KBP1) = HP(I,J,1)
      ENDIF
   ENDDO
ENDDO
END SUBROUTINE FDS_P_H_GHOST

