         IF (IZ==0) CYCLE
         IF (M%CELL(M%CELL_INDEX(I,J,K))%SOLID) CYCLE
         CZONE(L) = IZ
         VTERM(L) = M%DX(I)*M%RC(I)*M%DY(J)*M%DZ(K)
      ENDDO
   ENDDO
ENDDO
END SUBROUTINE FDS_P_ZONE_VOLUME_TERMS

