   ALLOCATE(M%REAC_SOURCE_TERM(0:IBP1,0:JBP1,0:KBP1,N_TRACKED_SPECIES),M%Q_REAC(0:IBP1,0:JBP1,0:KBP1,N_REACTIONS)) ; M%REAC_SOURCE_TERM=0._EB ; M%Q_REAC=0._EB
