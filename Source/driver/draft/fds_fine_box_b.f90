INTEGER, PARAMETER :: NK=14
CHARACTER(10), PARAMETER :: KNAME(NK) = [CHARACTER(10) :: 'visc','dens','dens_pre','dens_post','vflux','div1','div2','vpred','vcorr','p_mfd','p_dens','p_dens_pre','baroclinic','noflux']
REAL(EB), SAVE :: MAXREL(NK)=0._EB
INTEGER, SAVE :: NGHOST(NK)=0,NBAD_G(NK)=0,NCALL(NK)=0,NBAD(NK)=0,NCMP(NK)=0,NSKIP=0,NMF=0
REAL(EB), ALLOCATABLE, SAVE :: DT_NEW_SH(:)
TYPE GLOBALS_T   !< module-level FDS state that the kernels update (divergence integrals, pressure-zone DPSTAR); a repeated kernel call needs the state from before the first call
   REAL(EB), ALLOCATABLE :: DSUM(:),USUM(:),PSUM(:)
   TYPE(P_ZONE_TYPE), ALLOCATABLE :: PZ(:)
END TYPE GLOBALS_T
TYPE(GLOBALS_T), SAVE :: G0,G1
LOGICAL, SAVE :: DEBUG_LOC=.FALSE.
LOGICAL, SAVE :: ON=.FALSE.,BUILD=.FALSE.   !< BUILD: the fine box is made by BUILD_FINE_BOX (contents only from the tables below), not copied from the level-0 box

CONTAINS

!> Switch the shadow on: one fine level with one box (the whole-domain copy), mesh number NMESHES+1; needs a single level-0 mesh.
FUNCTION FDS_FINE_B_SHADOW_ENABLE(MODE) RESULT(IERR) BIND(C,NAME='fds_fine_b_shadow_enable')

INTEGER(C_INT), VALUE :: MODE   !< 0: the fine box is a deep copy of the level-0 box (routing test); 1: the fine box is built by BUILD_FINE_BOX and only the state arrays are copied
INTEGER(C_INT) :: IERR
TYPE(MESH_TYPE), POINTER :: R

IERR = 0
IF (NMESHES/=1) THEN ; IERR = 1 ; RETURN ; ENDIF
IF (.NOT.ALLOCATED(FINE_LEVEL)) ALLOCATE(FINE_LEVEL(1))
NMF = NMESHES+1
FINE_LEVEL(1)%NM0 = NMESHES ; FINE_LEVEL(1)%N_BOXES = 1
IF (.NOT.ALLOCATED(FINE_LEVEL(1)%BOX)) ALLOCATE(FINE_LEVEL(1)%BOX(1),FINE_LEVEL(1)%VIEW(1))
CALL FDS_K_RESERVE_BOXES(INT(NMF,C_INT))
ALLOCATE(DT_NEW_SH(NMF)) ; DT_NEW_SH = 0._EB
CALL FDS_HOOK_SET_FINE_READY(1_C_INT)
SHADOW_PROC => SHADOW
BUILD = (MODE==1)
IF (BUILD) THEN
   R => MESHES(1)
   CALL BUILD_FINE_BOX(FINE_LEVEL(1)%BOX(1),R%IBAR,R%JBAR,R%KBAR,R%XS,R%XF,R%YS,R%YF,R%ZS,R%ZF)
   CALL AUDIT_BUILT_BOX(R,FINE_LEVEL(1)%BOX(1))
   CALL BIND_OWN_VIEWS(FINE_LEVEL(1)%BOX(1))   ! the kernels then run through the second array's views, as they will on AMReX data (FDS_FINE_B_SET_VIEW)
ENDIF
ON = .TRUE.

END FUNCTION FDS_FINE_B_SHADOW_ENABLE

!> Bind the views of fine box 1 to the box's own state arrays through the C-callable FDS_FINE_B_SET_VIEW (exercises that entry point and the POINT_TO_BOX view path).
SUBROUTINE BIND_OWN_VIEWS(F)

TYPE(MESH_TYPE), INTENT(INOUT), TARGET :: F

CALL BIND3(1,F%U,LBOUND(F%U),SHAPE(F%U)) ; CALL BIND3(2,F%V,LBOUND(F%V),SHAPE(F%V)) ; CALL BIND3(3,F%W,LBOUND(F%W),SHAPE(F%W))
CALL BIND3(4,F%US,LBOUND(F%US),SHAPE(F%US)) ; CALL BIND3(5,F%VS,LBOUND(F%VS),SHAPE(F%VS)) ; CALL BIND3(6,F%WS,LBOUND(F%WS),SHAPE(F%WS))
CALL BIND3(7,F%D,LBOUND(F%D),SHAPE(F%D)) ; CALL BIND3(8,F%DS,LBOUND(F%DS),SHAPE(F%DS)) ; CALL BIND3(9,F%H,LBOUND(F%H),SHAPE(F%H)) ; CALL BIND3(10,F%HS,LBOUND(F%HS),SHAPE(F%HS)) ; CALL BIND3(11,F%KRES,LBOUND(F%KRES),SHAPE(F%KRES))
CALL BIND3(12,F%FVX,LBOUND(F%FVX),SHAPE(F%FVX)) ; CALL BIND3(13,F%FVY,LBOUND(F%FVY),SHAPE(F%FVY)) ; CALL BIND3(14,F%FVZ,LBOUND(F%FVZ),SHAPE(F%FVZ))
CALL BIND3(15,F%RHO,LBOUND(F%RHO),SHAPE(F%RHO)) ; CALL BIND3(16,F%RHOS,LBOUND(F%RHOS),SHAPE(F%RHOS)) ; CALL BIND3(17,F%MU,LBOUND(F%MU),SHAPE(F%MU)) ; CALL BIND3(18,F%TMP,LBOUND(F%TMP),SHAPE(F%TMP))
CALL BIND3(19,F%Q,LBOUND(F%Q),SHAPE(F%Q)) ; CALL BIND3(20,F%RSUM,LBOUND(F%RSUM),SHAPE(F%RSUM))

END SUBROUTINE BIND_OWN_VIEWS

SUBROUTINE BIND3(WHICH,A,LB,SH)
INTEGER, INTENT(IN) :: WHICH,LB(3),SH(3)
REAL(EB), INTENT(IN), TARGET :: A(LB(1):LB(1)+SH(1)-1,LB(2):LB(2)+SH(2)-1,LB(3):LB(3)+SH(3)-1)   ! explicit shape: the address of the box's own array, no copy
INTEGER(C_INT) :: LB4(4),EXT4(4),IERR
LB4 = [INT(LB(1),C_INT),INT(LB(2),C_INT),INT(LB(3),C_INT),1_C_INT]
EXT4 = [INT(SIZE(A,1),C_INT),INT(SIZE(A,2),C_INT),INT(SIZE(A,3),C_INT),1_C_INT]
IERR = FDS_FINE_B_SET_VIEW(1_C_INT,1_C_INT,INT(WHICH,C_INT),LB4,EXT4,C_LOC(A))
IF (IERR/=0) THEN ; WRITE(0,'(A,I0,A,I0)') 'fine-b shadow: FDS_FINE_B_SET_VIEW failed for WHICH=',WHICH,' ierr=',IERR ; ERROR STOP 1 ; ENDIF
END SUBROUTINE BIND3

SUBROUTINE SHADOW(PHASE,KIND,NM,T,DT,EST,DTNEW,ICHG)

INTEGER, INTENT(IN) :: PHASE,KIND,NM,EST,ICHG
REAL(EB), INTENT(IN) :: T,DT,DTNEW
TYPE(MESH_TYPE), POINTER :: R,F

IF (.NOT.ON) RETURN
IF (NM/=1) THEN
   IF (PHASE==0) NSKIP = NSKIP+1
   RETURN
ENDIF
R => MESHES(1) ; F => FINE_LEVEL(1)%BOX(1)
IF (PHASE==0) THEN
   IF (BUILD) THEN
      CALL COPY_STATE(R,F)               ! built box: only the state arrays (incl. ghost layers) and the scalars the kernels carry between calls
   ELSE
      F = R                              ! deep copy of the level-0 mesh object (state arrays incl. ghost layers, metrics, tables, scalars)
   ENDIF
   CHANGE_TIME_STEP_INDEX(NMF) = CHANGE_TIME_STEP_INDEX(1)
   CALL SAVE_GLOBALS(G0)
   RETURN
ENDIF
CALL SAVE_GLOBALS(G1) ; CALL RESTORE_GLOBALS(G0)       ! the level-0 kernel has run: keep its global effects, run the fine kernel from the same global state
NCALL(KIND) = NCALL(KIND)+1
SELECT CASE(KIND)
   CASE(1) ; CALL COMPUTE_VISCOSITY(NMF,APPLY_TO_ESTIMATED_VARIABLES=(EST/=0))
   CASE(2) ; CALL MASS_FINITE_DIFFERENCES(NMF) ; CALL DENSITY(T,DT,NMF)
   CASE(3) ; CALL MASS_FINITE_DIFFERENCES(NMF) ; CALL DENSITY_PRE_CLIP(T,DT,NMF)
   CASE(4) ; CALL DENSITY_POST_CLIP(T,DT,NMF)
   CASE(5) ; CALL VELOCITY_FLUX(T,DT,NMF,APPLY_TO_ESTIMATED_VARIABLES=(EST/=0))
   CASE(6) ; CALL DIVERGENCE_PART_1(T,DT,NMF)
   CASE(7) ; CALL DIVERGENCE_PART_2(DT,NMF)
   CASE(8)
      DT_NEW_SH = DT ; CHANGE_TIME_STEP_INDEX(NMF) = 0
      CALL VELOCITY_PREDICTOR(T,DT,DT_NEW_SH,NMF)
      IF (DT_NEW_SH(NMF)/=DTNEW) CALL BAD(KIND,'DT_NEW')
      IF (CHANGE_TIME_STEP_INDEX(NMF)/=ICHG) CALL BAD(KIND,'CHANGE_TIME_STEP_INDEX')
      IF (F%CFL/=R%CFL .OR. F%VN/=R%VN) CALL BAD(KIND,'CFL/VN')
   CASE(9) ; CALL VELOCITY_CORRECTOR(T,DT,NMF)
   CASE(10) ; CALL MASS_FINITE_DIFFERENCES(NMF)
   CASE(11) ; CALL DENSITY(T,DT,NMF)
   CASE(12) ; CALL DENSITY_PRE_CLIP(T,DT,NMF)
   CASE(13) ; CALL BAROCLINIC_CORRECTION(T,NMF)
   CASE(14) ; CALL NO_FLUX(DT,NMF)
END SELECT
IF (F%CLIP_RHOMIN.NEQV.R%CLIP_RHOMIN .OR. F%CLIP_RHOMAX.NEQV.R%CLIP_RHOMAX) CALL BAD(KIND,'CLIP flags')
IF (F%DT_RESTRICT_COUNT/=R%DT_RESTRICT_COUNT) CALL BAD(KIND,'DT_RESTRICT_COUNT')
CALL CMP3(KIND,'U',R%U,F%U,LBOUND(R%U),LBOUND(F%U))   ; CALL CMP3(KIND,'V',R%V,F%V,LBOUND(R%V),LBOUND(F%V))   ; CALL CMP3(KIND,'W',R%W,F%W,LBOUND(R%W),LBOUND(F%W))
CALL CMP3(KIND,'US',R%US,F%US,LBOUND(R%US),LBOUND(F%US)) ; CALL CMP3(KIND,'VS',R%VS,F%VS,LBOUND(R%VS),LBOUND(F%VS)) ; CALL CMP3(KIND,'WS',R%WS,F%WS,LBOUND(R%WS),LBOUND(F%WS))
CALL CMP3(KIND,'FVX',R%FVX,F%FVX,LBOUND(R%FVX),LBOUND(F%FVX)) ; CALL CMP3(KIND,'FVY',R%FVY,F%FVY,LBOUND(R%FVY),LBOUND(F%FVY)) ; CALL CMP3(KIND,'FVZ',R%FVZ,F%FVZ,LBOUND(R%FVZ),LBOUND(F%FVZ))
CALL CMP3(KIND,'H',R%H,F%H,LBOUND(R%H),LBOUND(F%H)) ; CALL CMP3(KIND,'HS',R%HS,F%HS,LBOUND(R%HS),LBOUND(F%HS)) ; CALL CMP3(KIND,'KRES',R%KRES,F%KRES,LBOUND(R%KRES),LBOUND(F%KRES))
CALL CMP3(KIND,'D',R%D,F%D,LBOUND(R%D),LBOUND(F%D)) ; CALL CMP3(KIND,'DS',R%DS,F%DS,LBOUND(R%DS),LBOUND(F%DS)) ; CALL CMP3(KIND,'DDDT',R%DDDT,F%DDDT,LBOUND(R%DDDT),LBOUND(F%DDDT))
CALL CMP3(KIND,'MU',R%MU,F%MU,LBOUND(R%MU),LBOUND(F%MU)) ; CALL CMP3(KIND,'STRAIN_RATE',R%STRAIN_RATE,F%STRAIN_RATE,LBOUND(R%STRAIN_RATE),LBOUND(F%STRAIN_RATE)) ; CALL CMP3(KIND,'Q',R%Q,F%Q,LBOUND(R%Q),LBOUND(F%Q))
CALL CMP3(KIND,'RHO',R%RHO,F%RHO,LBOUND(R%RHO),LBOUND(F%RHO)) ; CALL CMP3(KIND,'RHOS',R%RHOS,F%RHOS,LBOUND(R%RHOS),LBOUND(F%RHOS)) ; CALL CMP3(KIND,'TMP',R%TMP,F%TMP,LBOUND(R%TMP),LBOUND(F%TMP)) ; CALL CMP3(KIND,'RSUM',R%RSUM,F%RSUM,LBOUND(R%RSUM),LBOUND(F%RSUM))
CALL CMP4(KIND,'ZZ',R%ZZ,F%ZZ,LBOUND(R%ZZ),LBOUND(F%ZZ)) ; CALL CMP4(KIND,'ZZS',R%ZZS,F%ZZS,LBOUND(R%ZZS),LBOUND(F%ZZS))
CALL CMP4(KIND,'DEL_RHO_D_DEL_Z',R%DEL_RHO_D_DEL_Z,F%DEL_RHO_D_DEL_Z,LBOUND(R%DEL_RHO_D_DEL_Z),LBOUND(F%DEL_RHO_D_DEL_Z))
CALL SAVE_GLOBALS(G0)                                 ! effects of the fine kernel on the globals
IF (ALLOCATED(G1%DSUM)) THEN
   IF (ANY(TRANSFER(G0%DSUM,[0_C_INT64_T])/=TRANSFER(G1%DSUM,[0_C_INT64_T])) .OR. ANY(TRANSFER(G0%USUM,[0_C_INT64_T])/=TRANSFER(G1%USUM,[0_C_INT64_T])) .OR. &
       ANY(TRANSFER(G0%PSUM,[0_C_INT64_T])/=TRANSFER(G1%PSUM,[0_C_INT64_T]))) CALL BAD(KIND,'DSUM/USUM/PSUM (sums over all cells, shell cells included)',GHOST_ONLY=BUILD)
ENDIF
IF (ALLOCATED(G1%PZ)) THEN
   IF (ANY(G0%PZ%DPSTAR/=G1%PZ%DPSTAR)) CALL BAD(KIND,'P_ZONE%DPSTAR (sum over all cells)',GHOST_ONLY=BUILD)
ENDIF
CALL RESTORE_GLOBALS(G1)
CALL CMP4(KIND,'FX',R%FX,F%FX,LBOUND(R%FX),LBOUND(F%FX)) ; CALL CMP4(KIND,'FY',R%FY,F%FY,LBOUND(R%FY),LBOUND(F%FY)) ; CALL CMP4(KIND,'FZ',R%FZ,F%FZ,LBOUND(R%FZ),LBOUND(F%FZ))

END SUBROUTINE SHADOW

!> Allocate the arrays of a fine-level mesh object of NI x NJ x NK cells on [XS,XF]x[YS,YF]x[ZS,ZF] (axis-aligned, uniform, Cartesian, no obstructions) with the contents the kernels read
!> (level-interface.md section 3): metrics (the arithmetic of READ_MESH for an untransformed grid), cell tables (ghost ring SOLID/EXTERIOR as READ_OBST sets it), empty edge and wall tables
!> (a fine box has no WALL cells: its non-domain faces are interface faces whose ghost values the driver fills, and there is no OMESH neighbour), and the state, field and work arrays of
!> INITIALIZE_MESH_VARIABLES_1 (initial values as there). Models with particles or radiation are not supported on fine levels yet.
SUBROUTINE BUILD_FINE_BOX(M,NI,NJ,NK,XS,XF,YS,YF,ZS,ZF)

TYPE(MESH_TYPE), INTENT(INOUT) :: M
INTEGER, INTENT(IN) :: NI,NJ,NK
REAL(EB), INTENT(IN) :: XS,XF,YS,YF,ZS,ZF
INTEGER :: I,J,K,IC,NC,IBP1,JBP1,KBP1,N_LOWER_SCALARS

IF (RADIATION .OR. N_LAGRANGIAN_CLASSES>0 .OR. N_LP_ARRAY_INDICES>0) THEN
   WRITE(0,'(A)') 'fds_amr ERROR in BUILD_FINE_BOX: fine-level boxes do not support particles or radiation yet.' ; ERROR STOP 1
ENDIF
N_LOWER_SCALARS = MERGE(0,1,FLUX_LIMITER_MW_CORRECTION)   ! as in INITIALIZE_MESH_VARIABLES_1
M%IBAR=NI ; M%JBAR=NJ ; M%KBAR=NK ; M%IBM1=NI-1 ; M%JBM1=NJ-1 ; M%KBM1=NK-1 ; M%IBP1=NI+1 ; M%JBP1=NJ+1 ; M%KBP1=NK+1
IBP1=M%IBP1 ; JBP1=M%JBP1 ; KBP1=M%KBP1
M%XS=XS ; M%XF=XF ; M%YS=YS ; M%YF=YF ; M%ZS=ZS ; M%ZF=ZF
M%DXI=(XF-XS)/REAL(NI,EB) ; M%DETA=(YF-YS)/REAL(NJ,EB) ; M%DZETA=(ZF-ZS)/REAL(NK,EB)
M%RDXI=1._EB/M%DXI ; M%RDETA=1._EB/M%DETA ; M%RDZETA=1._EB/M%DZETA
ALLOCATE(M%X(0:NI),M%XC(0:NI+1),M%HX(0:NI+1),M%DX(0:NI+1),M%RDX(0:NI+1),M%DXN(0:NI),M%RDXN(0:NI),M%R(0:NI),M%RC(0:NI+1),M%RRN(0:NI+1))
ALLOCATE(M%Y(0:NJ),M%YC(0:NJ+1),M%HY(0:NJ+1),M%DY(0:NJ+1),M%RDY(0:NJ+1),M%DYN(0:NJ),M%RDYN(0:NJ))
ALLOCATE(M%Z(0:NK),M%ZC(0:NK+1),M%HZ(0:NK+1),M%DZ(0:NK+1),M%RDZ(0:NK+1),M%DZN(0:NK),M%RDZN(0:NK))
M%R=1._EB ; M%RC=1._EB ; M%RRN=1._EB
CALL AXIS(NI,XS,XF,M%DXI,M%X,M%XC,M%HX,M%DX,M%RDX,M%DXN,M%RDXN,M%DXMIN)
CALL AXIS(NJ,YS,YF,M%DETA,M%Y,M%YC,M%HY,M%DY,M%RDY,M%DYN,M%RDYN,M%DYMIN)
CALL AXIS(NK,ZS,ZF,M%DZETA,M%Z,M%ZC,M%HZ,M%DZ,M%RDZ,M%DZN,M%RDZN,M%DZMIN)

! cell tables: the ghost ring gets cell numbers (READ_OBST order), is SOLID and EXTERIOR; interior cells use index 0 (CELL(0), non-solid)
ALLOCATE(M%CELL_INDEX(0:IBP1,0:JBP1,0:KBP1)) ; M%CELL_INDEX = 0
NC = 0
DO K=0,KBP1
   DO J=0,JBP1
      DO I=0,IBP1
         IF (I<=1 .OR. I>=NI .OR. J<=1 .OR. J>=NJ .OR. K<=1 .OR. K>=NK) THEN ; NC = NC+1 ; ENDIF
      ENDDO
   ENDDO
ENDDO
CALL NUMBER_CELLS(M,NI,NJ,NK,NC)
ALLOCATE(M%CELL(0:NC))
DO K=0,KBP1
   DO J=0,JBP1
      DO I=0,IBP1
         IC = M%CELL_INDEX(I,J,K)
         IF (IC>0) THEN
            M%CELL(IC)%I=I ; M%CELL(IC)%J=J ; M%CELL(IC)%K=K
            IF (I==0 .OR. I==IBP1 .OR. J==0 .OR. J==JBP1 .OR. K==0 .OR. K==KBP1) THEN ; M%CELL(IC)%SOLID=.TRUE. ; M%CELL(IC)%EXTERIOR=.TRUE. ; ENDIF
         ENDIF
      ENDDO
   ENDDO
ENDDO
ALLOCATE(M%INTERPOLATED_MESH(1:NI,1:NJ,1:NK)) ; M%INTERPOLATED_MESH = 0     ! no cell of a fine box is covered by a finer mesh (yet)
ALLOCATE(M%EDGE(0:0)) ; ALLOCATE(M%WALL(0:0),M%EXTERNAL_WALL(0),M%THIN_WALL(0:10))
M%WALL(0)%BOUNDARY_TYPE = NULL_BOUNDARY ; M%WALL(0)%SURF_INDEX = DEFAULT_SURF_INDEX
M%N_WALL_CELLS=0 ; M%N_WALL_CELLS_DIM=0 ; M%N_INTERNAL_WALL_CELLS=0 ; M%N_EXTERNAL_WALL_CELLS=0
ALLOCATE(M%UVW_SAVE(0),M%U_GHOST(0),M%V_GHOST(0),M%W_GHOST(0),M%WALL_WORK1(0),M%WALL_WORK2(0))

! state, field and work arrays (init.f90, INITIALIZE_MESH_VARIABLES_1)
ALLOCATE(M%TMP(-1:IBP1+1,-1:JBP1+1,-1:KBP1+1)) ; M%TMP = TMPA
ALLOCATE(M%RHO(-1:IBP1+1,-1:JBP1+1,-1:KBP1+1)) ; M%RHO = RHOA
ALLOCATE(M%RHOS(-1:IBP1+1,-1:JBP1+1,-1:KBP1+1)) ; M%RHOS = RHOA
ALLOCATE(M%ZZ(-1:IBP1+1,-1:JBP1+1,-1:KBP1+1,N_TOTAL_SCALARS)) ; M%ZZ = 0._EB
ALLOCATE(M%ZZS(-1:IBP1+1,-1:JBP1+1,-1:KBP1+1,N_TOTAL_SCALARS)) ; M%ZZS = 0._EB
ALLOCATE(M%WORK_PAD(-1:IBP1+1,-1:JBP1+1,-1:KBP1+1)) ; M%WORK_PAD = 0._EB
ALLOCATE(M%U(-1:IBP1,0:JBP1,0:KBP1),M%US(-1:IBP1,0:JBP1,0:KBP1),M%WORK_U(-1:IBP1,0:JBP1,0:KBP1)) ; M%U=0._EB ; M%US=0._EB ; M%WORK_U=0._EB
ALLOCATE(M%V(0:IBP1,-1:JBP1,0:KBP1),M%VS(0:IBP1,-1:JBP1,0:KBP1),M%WORK_V(0:IBP1,-1:JBP1,0:KBP1)) ; M%V=0._EB ; M%VS=0._EB ; M%WORK_V=0._EB
ALLOCATE(M%W(0:IBP1,0:JBP1,-1:KBP1),M%WS(0:IBP1,0:JBP1,-1:KBP1),M%WORK_W(0:IBP1,0:JBP1,-1:KBP1)) ; M%W=0._EB ; M%WS=0._EB ; M%WORK_W=0._EB
ALLOCATE(M%FVX(0:IBP1,0:JBP1,0:KBP1),M%FVY(0:IBP1,0:JBP1,0:KBP1),M%FVZ(0:IBP1,0:JBP1,0:KBP1)) ; M%FVX=0._EB ; M%FVY=0._EB ; M%FVZ=0._EB
ALLOCATE(M%FVX_B(0:IBP1,0:JBP1,0:KBP1),M%FVY_B(0:IBP1,0:JBP1,0:KBP1),M%FVZ_B(0:IBP1,0:JBP1,0:KBP1)) ; M%FVX_B=0._EB ; M%FVY_B=0._EB ; M%FVZ_B=0._EB
IF (PARTICLE_DRAG) THEN
   ALLOCATE(M%FVX_D(0:IBP1,0:JBP1,0:KBP1),M%FVY_D(0:IBP1,0:JBP1,0:KBP1),M%FVZ_D(0:IBP1,0:JBP1,0:KBP1)) ; M%FVX_D=0._EB ; M%FVY_D=0._EB ; M%FVZ_D=0._EB
ENDIF
