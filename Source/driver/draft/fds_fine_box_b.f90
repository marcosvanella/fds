SUBROUTINE CMP3(KIND,TXT,A,B,LA,LB)
INTEGER, INTENT(IN) :: KIND,LA(3),LB(3)
CHARACTER(*), INTENT(IN) :: TXT
REAL(EB), INTENT(IN) :: A(:,:,:),B(:,:,:)
INTEGER :: I,J,K,NG,NI_,LO(3),HI(3)
NCMP(KIND) = NCMP(KIND)+1
LO = MAX(LA,LB) ; HI = MIN(LA+SHAPE(A)-1,LB+SHAPE(B)-1)   ! the index range both arrays have (the driver's level-0 boxes may carry more ghost layers than a built box)
IF (ANY(HI<LO)) THEN ; CALL BAD(KIND,TXT//' (no common range)') ; RETURN ; ENDIF
NG = 0 ; NI_ = 0
DO K=LO(3),HI(3) ; DO J=LO(2),HI(2) ; DO I=LO(1),HI(1)
   IF (TRANSFER(A(I-LA(1)+1,J-LA(2)+1,K-LA(3)+1),0_C_INT64_T)/=TRANSFER(B(I-LB(1)+1,J-LB(2)+1,K-LB(3)+1),0_C_INT64_T)) THEN
      IF (IS_INTERIOR(I,J,K)) THEN ; NI_ = NI_+1 ; CALL LOC(KIND,TXT,I,J,K,A(I-LA(1)+1,J-LA(2)+1,K-LA(3)+1),B(I-LB(1)+1,J-LB(2)+1,K-LB(3)+1))
      ELSE ; NG = NG+1 ; CALL REL(KIND,A(I-LA(1)+1,J-LA(2)+1,K-LA(3)+1),B(I-LB(1)+1,J-LB(2)+1,K-LB(3)+1)) ; ENDIF
   ENDIF
ENDDO ; ENDDO ; ENDDO
IF (NI_>0) CALL BAD(KIND,TXT//' (core cells)')
IF (NG>0) THEN ; NGHOST(KIND) = NGHOST(KIND)+1 ; CALL BAD(KIND,TXT//' (shell/ghost cells)',.TRUE.) ; ENDIF
END SUBROUTINE CMP3

SUBROUTINE CMP4(KIND,TXT,A,B,LA,LB)
INTEGER, INTENT(IN) :: KIND,LA(4),LB(4)
CHARACTER(*), INTENT(IN) :: TXT
REAL(EB), INTENT(IN) :: A(:,:,:,:),B(:,:,:,:)
INTEGER :: I,J,K,N,NG,NI_,LO(4),HI(4)
NCMP(KIND) = NCMP(KIND)+1
LO = MAX(LA,LB) ; HI = MIN(LA+SHAPE(A)-1,LB+SHAPE(B)-1)
IF (ANY(HI<LO)) THEN ; CALL BAD(KIND,TXT//' (no common range)') ; RETURN ; ENDIF
NG = 0 ; NI_ = 0
DO N=LO(4),HI(4) ; DO K=LO(3),HI(3) ; DO J=LO(2),HI(2) ; DO I=LO(1),HI(1)
   IF (TRANSFER(A(I-LA(1)+1,J-LA(2)+1,K-LA(3)+1,N-LA(4)+1),0_C_INT64_T)/=TRANSFER(B(I-LB(1)+1,J-LB(2)+1,K-LB(3)+1,N-LB(4)+1),0_C_INT64_T)) THEN
      IF (IS_INTERIOR(I,J,K)) THEN ; NI_ = NI_+1
      ELSE ; NG = NG+1 ; CALL REL(KIND,A(I-LA(1)+1,J-LA(2)+1,K-LA(3)+1,N-LA(4)+1),B(I-LB(1)+1,J-LB(2)+1,K-LB(3)+1,N-LB(4)+1)) ; ENDIF
   ENDIF
ENDDO ; ENDDO ; ENDDO ; ENDDO
IF (NI_>0) CALL BAD(KIND,TXT//' (core cells)')
IF (NG>0) THEN ; NGHOST(KIND) = NGHOST(KIND)+1 ; CALL BAD(KIND,TXT//' (shell/ghost cells)',.TRUE.) ; ENDIF
END SUBROUTINE CMP4

!> Cells whose results must be bitwise those of the level-0 run: with the clone (BUILD false) every cell; with the built box (no walls) the cells at least two cells away from every box face
!> (the level-0 box has walls at its periodic faces, the fine box has ghost cells instead: the cells next to a face are compared for information only).
LOGICAL FUNCTION IS_INTERIOR(I,J,K)
INTEGER, INTENT(IN) :: I,J,K
INTEGER :: NI_,NJ_,NK_
IF (.NOT.BUILD) THEN ; IS_INTERIOR = .TRUE. ; RETURN ; ENDIF
NI_ = MESHES(1)%IBAR ; NJ_ = MESHES(1)%JBAR ; NK_ = MESHES(1)%KBAR
IS_INTERIOR = (NI_<5 .OR. (I>=3 .AND. I<=NI_-2)) .AND. (NJ_<5 .OR. (J>=3 .AND. J<=NJ_-2)) .AND. (NK_<5 .OR. (K>=3 .AND. K<=NK_-2)) .AND. &
              I>=1 .AND. I<=NI_ .AND. J>=1 .AND. J<=NJ_ .AND. K>=1 .AND. K<=NK_
IF (NI_<5 .AND. NJ_<5 .AND. NK_<5) IS_INTERIOR = .FALSE.
END FUNCTION IS_INTERIOR

SUBROUTINE REL(KIND,A,B)
INTEGER, INTENT(IN) :: KIND
REAL(EB), INTENT(IN) :: A,B
REAL(EB) :: R
R = ABS(A-B)/MAX(ABS(A),ABS(B),TINY(1._EB))
IF (R>MAXREL(KIND)) MAXREL(KIND) = R
END SUBROUTINE REL

SUBROUTINE LOC(KIND,TXT,I,J,K,A,B)
INTEGER, INTENT(IN) :: KIND,I,J,K
CHARACTER(*), INTENT(IN) :: TXT
REAL(EB), INTENT(IN) :: A,B
IF (NBAD(KIND)<3 .OR. DEBUG_LOC .AND. NBAD(KIND)<400) WRITE(0,'(A,A,A,A,I4,3I4,2ES24.16)') 'fine-b shadow interior difference in ',TRIM(KNAME(KIND)),' ',TXT,NCALL(KIND),I,J,K,A,B
END SUBROUTINE LOC

