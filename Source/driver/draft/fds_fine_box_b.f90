INTEGER(C_INT) :: NFAIL
INTEGER :: K

NFAIL = SUM(NBAD)
DO K=1,NK
   WRITE(6,'(A,A10,A,I8,A,I8,A,I6,A,I6,A,ES9.2)') 'FINE-B SHADOW ',KNAME(K),' calls ',NCALL(K),' array comparisons ',NCMP(K),' core mismatches ',NBAD(K),' shell/ghost arrays differing ',NBAD_G(K),' max rel ',MAXREL(K)
ENDDO
WRITE(6,'(A,I0,A)') 'FINE-B SHADOW calls on other level-0 meshes skipped: ',NSKIP,' (needs a single level-0 mesh)'
