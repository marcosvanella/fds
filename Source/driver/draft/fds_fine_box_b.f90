CALL CP3(F%TMP,LBOUND(F%TMP),R%TMP,LBOUND(R%TMP)) ; CALL CP3(F%RHO,LBOUND(F%RHO),R%RHO,LBOUND(R%RHO)) ; CALL CP3(F%RHOS,LBOUND(F%RHOS),R%RHOS,LBOUND(R%RHOS)) ; CALL CP4(F%ZZ,LBOUND(F%ZZ),R%ZZ,LBOUND(R%ZZ)) ; CALL CP4(F%ZZS,LBOUND(F%ZZS),R%ZZS,LBOUND(R%ZZS))
