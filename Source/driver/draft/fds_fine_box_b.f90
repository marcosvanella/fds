!> \brief DRAFT (D-056 option B), compiled only with -DFDS_AMR_FINE_B_DRAFT=ON on a tree with patches 0007 and 0008 applied; never part of the default build and not used for physics.
!> Shadow test of the fine-level stage functions: with the shadow switched on, every level-0 kernel call (visc, dens, dens_pre, dens_post, vflux, div1, div2, vpred, vcorr) is repeated on
!> a fine-level box FINE_LEVEL(1)%BOX(1) reached through POINT_TO_BOX (mesh number NMESHES+1, patch 0008), started from a deep copy of the level-0 mesh object taken before the kernel
!> (so the metrics, wall/edge tables and all state arrays are bitwise those of the level-0 box, which covers the whole domain), and the results are compared bit by bit.
!> This exercises the routing of the kernels to level > 0 (POINT_TO_BOX, per-mesh-number arrays, M_DOT_PPP lookup), not the build of the fine-box contents (FDS_FINE_BOX_B_BUILD, below).
MODULE FDS_FINE_BOX_B

