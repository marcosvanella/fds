!> Copy the index range common to D and S. Assignment would reallocate D when the level-0 array has another extent (the driver's level-0 boxes carry more ghost layers than FDS
!> gives a box); the built fine box keeps its own allocation, so that views bound to it stay valid. Cells of D outside the range of S keep their value.
SUBROUTINE CP3(D,LD,S,LS)
INTEGER, INTENT(IN) :: LD(3),LS(3)
REAL(EB), INTENT(INOUT) :: D(LD(1):,LD(2):,LD(3):)
REAL(EB), INTENT(IN) :: S(LS(1):,LS(2):,LS(3):)
INTEGER :: LO(3),HI(3)
LO = MAX(LD,LS) ; HI = MIN(UBOUND(D),UBOUND(S))
IF (ANY(HI<LO)) RETURN
D(LO(1):HI(1),LO(2):HI(2),LO(3):HI(3)) = S(LO(1):HI(1),LO(2):HI(2),LO(3):HI(3))
END SUBROUTINE CP3

SUBROUTINE CP4(D,LD,S,LS)
INTEGER, INTENT(IN) :: LD(4),LS(4)
REAL(EB), INTENT(INOUT) :: D(LD(1):,LD(2):,LD(3):,LD(4):)
REAL(EB), INTENT(IN) :: S(LS(1):,LS(2):,LS(3):,LS(4):)
INTEGER :: LO(4),HI(4)
LO = MAX(LD,LS) ; HI = MIN(UBOUND(D),UBOUND(S))
IF (ANY(HI<LO)) RETURN
D(LO(1):HI(1),LO(2):HI(2),LO(3):HI(3),LO(4):HI(4)) = S(LO(1):HI(1),LO(2):HI(2),LO(3):HI(3),LO(4):HI(4))
END SUBROUTINE CP4

